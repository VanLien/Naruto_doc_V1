-spec push_self_appoint(#role{}) -> ok.

push_self_appoint(#role{id = RoleId,
			m_expedition = #m_expedition{appoint = Appoint}}) ->
    case Appoint =:= [] of
      true -> sys_conn:pack_send(24405, {[]});
      _ ->
	  CliL = case info(RoleId) of
		   {ok, #expedition_employ{list = List}} ->
		       [{Id, Bid, PLev, Star, Power, Ext}
			|| #expedition_employ_p{id = Id, ext = Ext, bid = Bid,
						lev = PLev, star = Star,
						power = Power}
			       <- List];
		   _ -> []
		 end,
	  sys_conn:pack_send(24405, {CliL})
    end,
    ok.

