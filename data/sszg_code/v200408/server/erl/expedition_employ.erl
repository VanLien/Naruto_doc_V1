-spec appoint(#role{}, pos_integer()) -> {ok, #role{}} |
					 {false, bitstring()}.

appoint(Role = #role{id = RoleId, name = Name,
		     m_expedition =
			 MExpedition = #m_expedition{appoint = Appoint}},
	Id) ->
    case lists:member(Id, Appoint) of
      true -> {false, lang:get(<<"英雄已派出"/utf8>>)};
      _ ->
	  case partner_lib:get_partner(Role, Id) of
	    #partner{end_time = EndTime} when EndTime =/= 0 ->
		{false, lang:get(<<"赋能英雄无法派遣"/utf8>>)};
	    #partner{power = Power, bid = Bid, star = Star,
		     lev = PLev, break_lev = BreakLev, use_skin = UseSkin} ->
		case length(Appoint) < 1 of
		  true ->
		      P = #expedition_employ_p{ext = [{5, UseSkin}], id = Id,
					       power = Power, bid = Bid,
					       lev = PLev, star = Star,
					       break_lev = BreakLev, num = 0},
		      E = #expedition_employ{rid = RoleId, rname = Name,
					     list = [P]},
		      expedition_mgr:update_data(E),
		      NRole = Role#role{m_expedition =
					    MExpedition#m_expedition{appoint =
									 [Id
									  | Appoint]}},
		      push_self_appoint(NRole),
		      push_red_point(NRole),
		      {ok, NRole};
		  _ -> {false, lang:get(<<"无法更换派遣英雄"/utf8>>)}
		end;
	    _ -> {false, lang:get(<<"英雄不存在"/utf8>>)}
	  end
    end.

-spec employ(#role{}, role_id(), pos_integer()) -> {ok,
						    #role{}, bitstring()} |
						   {false, bitstring()}.

employ(#role{id = RoleId}, RoleId, _Id) ->
    {false, lang:get(<<"不能雇佣自己的英雄"/utf8>>)};
employ(Role = #role{m_expedition =
			MExpedition = #m_expedition{employ = L}},
       TarRoleId, Id) ->
    case lists:keymember({TarRoleId, Id}, 1, L) of
      true -> {false, lang:get(<<"不能重复雇佣同一英雄"/utf8>>)};
      false ->
	  case length(L) <
		 expedition_data:get_const(num_employees)
	      of
	    true ->
		case info(TarRoleId) of
		  {ok, #expedition_employ{rname = RName, list = List}} ->
		      case lists:keyfind(Id, #expedition_employ_p.id, List) of
			false -> {false, lang:get(<<"英雄不存在"/utf8>>)};
			#expedition_employ_p{power = Power, bid = Bid,
					     star = Star, lev = PLev,
					     break_lev = BreakLev, num = Num,
					     ext = Ext} ->
			    case Num < expedition_data:get_const(num_employment)
				of
			      true ->
				  expedition_mgr:info({employ, TarRoleId, Id}),
				  IsUsed = 0,
				  NewL = [{{TarRoleId, Id}, RName, Bid, PLev,
					   Star, BreakLev, Power, IsUsed, Ext}
					  | L],
				  NRole = Role#role{m_expedition =
							MExpedition#m_expedition{employ
										     =
										     NewL}},
				  push_can_employ(NRole),
				  {ok, NRole, lang:get(<<"雇佣成功"/utf8>>)};
			      _ -> {false, lang:get(<<"该英雄已被别人雇佣啦"/utf8>>)}
			    end
		      end;
		  _ -> {false, lang:get(<<"英雄不存在"/utf8>>)}
		end;
	    _ -> {false, lang:get(<<"今天雇佣次数已经达到上限"/utf8>>)}
	  end
    end.

-spec list(#role{}) -> list().

list(#role{m_friend = #m_friend{list = FList},
	   m_expedition = #m_expedition{employ = EmployL},
	   partner_bag = #partner_bag{partner_list = PList}}) ->
    MaxPower = case PList of
		 [_ | _] ->
		     #partner{power = PowerT} = list_util:keymax(PList,
								 #partner.power),
		     PowerT;
		 _ -> 0
	       end,
    Fun = fun (#friend_tmp{fid = Fid}, Acc) ->
		  case info(Fid) of
		    {ok, E = #expedition_employ{}} -> [E | Acc];
		    _ -> Acc
		  end
	  end,
    L = lists:foldl(Fun, [], FList),
    FriendL = lists:flatten([[{Rid, SrvId, RName, Id, Bid,
			       PLev, Star, Power, 0, Ext}
			      || #expedition_employ_p{ext = Ext, id = Id,
						      bid = Bid, lev = PLev,
						      star = Star,
						      power = Power, num = Num}
				     <- List,
				 not
				   lists:keymember({{Rid, SrvId}, Id}, 1,
						   EmployL)
				   andalso
				   Power =<
				     MaxPower *
				       (expedition_data:get_const(war_ratio) /
					  1000)
				     andalso
				     Num <
