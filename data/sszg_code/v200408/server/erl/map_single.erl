-spec transmit(pid(), pos_integer(), pos_integer(),
	       pos_integer(), pid(), non_neg_integer(),
	       non_neg_integer(), non_neg_integer(), non_neg_integer(),
	       list(), list()) -> ok.

transmit(_Pid, _BaseId, Mode, Speed, RolePid, _SrcX,
	 _SrcY, DestX, DestY, _DestList, _Looks) ->
    #map_role{conn_pid = ConnPid, rid = Rid, srv_id = SrvId,
	      dir = Dir} =
	get({role, RolePid}),
    {ok, Bin} = proto_102:pack(10218, srv,
			       {Rid, SrvId, Mode, Speed, Dir, DestX, DestY}),
    ConnPid ! {send_data, Bin},
    ok.

-spec leave(pid(), pid(), non_neg_integer(),
	    non_neg_integer(), pos_integer(), bitstring()) -> ok.

leave(_Pid, _RolePid, _X, _Y, _Rid, _SrvId) -> ok.

-spec update(pid(), #map_role{}) -> ok.

update(_Pid, MapRole = #map_role{conn_pid = ConnPid}) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidmap_single70, _,
       {__Levelmap_single70, __Tracesmap_single70}}
	  when __Levelmap_single70 band 128 /= 0 orelse
		 __Tracesmap_single70 /= [] ->
	  lager:do_log(debug,
		       [{module, map_single}, {function, update}, {line, 70},
			{pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("角色[~ts]更新了场景信息:[SPEED:~w, EVENT:~w]",
				     [MapRole#map_role.name,
				      MapRole#map_role.speed,
				      MapRole#map_role.event]),
		       none, 4096, 128, __Levelmap_single70,
		       __Tracesmap_single70, lager_event, __Pidmap_single70);
      _ -> ok
    end,
    {ok, Bin} = proto_102:pack(10217, srv, MapRole),
    ConnPid ! {send_data, Bin},
    ok.

