-spec distance(#pos{}, #pos{}) -> {ok,
				   {integer(), integer()}} |
				  false.

distance(#pos{map_pid = MapPid, x = X1, y = Y1},
	 #pos{map_pid = MapPid, x = X2, y = Y2}) ->
    Dx = erlang:abs(util:floor(X1 / 700) -
		      util:floor(X2 / 700)),
    Dy = erlang:abs(util:floor(Y1 / 450) -
		      util:floor(Y2 / 450)),
    {ok, {Dx, Dy}};
distance(_, _) -> false.


