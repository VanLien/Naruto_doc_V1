gen_fight_object(RoleLev, Lev, Attr, Sprites) ->
    case RoleLev >=
	   sprite_data:get_const(sprite_unlocked_lv)
	of
      true when is_record(Attr, attr) ->
	  Skills =
	      lists:flatten([sprite_data:get_sprite_skill(SpritesId)
			     || {_, SpritesId} <- lists:keysort(1, Sprites)]),
	  {ActiveSkillIds, PassiveSkillIds} =
