calc_gain_loss([], _Sprites, GainIds, LossIds) ->
    SortGainIds = lists:usort(GainIds),
    SortLossIds = lists:usort(LossIds),
    {SortGainIds -- SortLossIds,
     SortLossIds -- SortGainIds};
calc_gain_loss([{Pos, 0} | PosInfo], Sprites, GainIds,
	       LossIds) ->
    case list_util:keyfind(Pos, Sprites, 0) of
      0 -> calc_gain_loss(PosInfo, Sprites, GainIds, LossIds);
      Id ->
	  calc_gain_loss(PosInfo,
			 lists:keyreplace(Pos, 1, Sprites, {Pos, 0}),
			 [Id | GainIds], LossIds)
    end;
calc_gain_loss([{Pos, Id} | PosInfo], Sprites, GainIds,
	       LossIds) ->
    {NewGainIds, NewSprites1} = case list_util:keyfind(Pos,
						       Sprites, 0)
				    of
				  0 -> {GainIds, Sprites};
				  Id -> {GainIds, Sprites};
				  OldId ->
				      {[OldId | GainIds],
				       lists:keyreplace(Pos, 1, Sprites,
							{Pos, 0})}
				end,
    {NewLossIds, NewSprites} = case lists:keyfind(Id, 2,
						  NewSprites1)
				   of
				 {Pos2, _} ->
				     {LossIds,
				      lists:keyreplace(Pos2, 1, NewSprites1,
						       {Pos2, 0})};
				 _ -> {[Id | LossIds], NewSprites1}
			       end,
    calc_gain_loss(PosInfo, NewSprites, NewGainIds,
		   NewLossIds).

check_arg(Sprites, PosInfo) ->
    check_pos(Sprites, PosInfo) andalso check_id(PosInfo).

check_pos(Sprites, PosInfo) ->
    PosLists = lists:usort([Pos2
			    || {Pos2, _Id2} <- PosInfo]),
    length(PosLists) == length(PosInfo) andalso
      lists:usort([Pos1 || {Pos1, _Id1} <- Sprites]) ==
	PosLists.

check_id([]) -> true;
check_id([{_Pos, 0} | PosInfo]) -> check_id(PosInfo);
check_id([{_Pos, Id} | PosInfo]) ->
    case lists:keyfind(Id, 2, PosInfo) of
      false ->
	  SpriteType = sprite_data:get_sprite_type(Id),
	  SpriteTypeLists = [sprite_data:get_sprite_type(IdT)
			     || {_, IdT} <- PosInfo],
	  case lists:member(SpriteType, SpriteTypeLists) of
	    true -> false;
	    _ when is_integer(SpriteType) -> check_id(PosInfo);
	    _ -> false
	  end;
      _ -> false
    end.

