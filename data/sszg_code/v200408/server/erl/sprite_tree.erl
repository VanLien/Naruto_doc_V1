		      NewRole3 = sprite_hatch:fire(NewRole2),
		      NewRole4 =
			  sprite_formation:sprite_tree_set_sprites(NewRole3,
								   Pos, Id),
		      {ok, NewRole4};
		  {false, #loss{msg = Msg}} -> {false, Msg};
		  {false, #gain{msg = Msg}} -> {false, Msg}
		end;
	    _ -> {false, lang:get(<<"参数错误"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"该位置未解锁"/utf8>>)}
    end.

-spec calc_sprites(#role{}) -> #role{}.

calc_sprites(Role = #role{m_sprite_tree =
			      MS = #m_sprite_tree{sprites = Sprites,
						  break_lev = BreakLev}}) ->
    MaxPos = sprite_data:get_limit_sprite_num(BreakLev),
    Fun = fun (Pos, Acc) ->
		  case lists:keymember(Pos, 1, Acc) of
		    true -> Acc;
		    _ -> [{Pos, 0} | Acc]
		  end
	  end,
    NSprites = lists:foldl(Fun, Sprites,
			   lists:seq(1, MaxPos)),
    NewRole = Role#role{m_sprite_tree =
			    MS#m_sprite_tree{sprites = NSprites}},
    case length(Sprites) =:= length(NSprites) of
      true -> NewRole;
      _ ->
	  NewRole1 = sprite_formation:add_pos(NewRole), NewRole1
    end.

-spec calc_attr_by_lev(pos_integer(),
		       pos_integer()) -> #attr{}.

calc_attr_by_lev(Lev, BreakLev) ->
    InitAttr = sprite_data:get_tree_attr(),
    BaseAttr = lev_attr_addition(InitAttr, Lev, BreakLev),
    BreakAttr = sprite_data:get_break_attr(BreakLev),
    {ok,
     #attr_calc{attr = AttrAdd2, attr_no_ratio = AttrNoRatio,
		ratio = Ratio2}} =
	attr_data:do_sub_list(BreakAttr, 2, 2, #attr_calc{}),
    AllAttr3 = attr_data:mix_attr_and_attr(BaseAttr,
					   AttrAdd2),
    AllAttr4 = attr_data:mix_attr_and_ratio(AllAttr3,
					    Ratio2),
    AllAttr5 = attr_data:mix_attr_and_attr(AllAttr3,
					   AllAttr4),
    attr_data:mix_attr_and_attr(AttrNoRatio, AllAttr5).

-spec calc_attr(#role{}) -> #role{}.

calc_attr(Role = #role{m_sprite_tree =
			   MS = #m_sprite_tree{lev = Lev,
					       break_lev = BreakLev}}) ->
    InitAttr = sprite_data:get_tree_attr(),
    BaseAttr = lev_attr_addition(InitAttr, Lev, BreakLev),
    Skills = get_skills(Role),
    SkillAttr = skill_lib:skill_attrs(Lev,
				      partner_lib:do_remove_skills(Skills)),
    {ok, #attr_calc{attr = AttrAdd, ratio = Ratio}} =
	attr_data:do_sub_list(SkillAttr, 1, 4, #attr_calc{}),
    BaseAttrT1 = attr_data:mix_attr_and_attr(BaseAttr,
					     AttrAdd),
    BaseAttrT2 = attr_data:mix_attr_and_ratio(BaseAttrT1,
					      Ratio),
    BaseAttr2 = attr_data:mix_attr_and_attr(BaseAttrT1,
					    BaseAttrT2),
    BreakAttr = sprite_data:get_break_attr(BreakLev),
    {ok,
     #attr_calc{attr = AttrAdd2, attr_no_ratio = AttrNoRatio,
		ratio = Ratio2}} =
	attr_data:do_sub_list(BreakAttr, 2, 2, #attr_calc{}),
    AllAttr3 = attr_data:mix_attr_and_attr(BaseAttr2,
					   AttrAdd2),
    AllAttr4 = attr_data:mix_attr_and_ratio(AllAttr3,
					    Ratio2),
    AllAttr5 = attr_data:mix_attr_and_attr(AllAttr3,
					   AllAttr4),
    AllAttr = attr_data:mix_attr_and_attr(AttrNoRatio,
					  AllAttr5),
    Role1 = #role{m_sprite_tree =
		      MS2 = #m_sprite_tree{max_power = MaxPower}} =
		Role#role{m_sprite_tree =
			      MS#m_sprite_tree{all_attr = AllAttr}},
    NewPower = calc_power(Role1),
    NewMS2 = MS2#m_sprite_tree{max_power =
				   max(MaxPower, NewPower),
			       power = NewPower},
    Role1#role{m_sprite_tree = NewMS2}.

lev_attr_addition(Attr = #attr{atk = Atk, def = Def,
			       hp_max = HpMax, speed = Speed},
		  Lev, BreakLev) ->
    {BaseGroupHp, BaseGroupAtk, BaseGroupDef,
     BaseGroupSpeed} =
	sprite_data:get_lev_group(),
    {AddeGroupHp, AddeGroupAtk, AddeGroupDef,
     SpeedeGroupDef} =
	sprite_data:get_break_group(BreakLev),
    GroupAtk = BaseGroupAtk * AddeGroupAtk * 1.0e-3 *
		 1.0e-3,
    GroupHp = AddeGroupHp * BaseGroupHp * 1.0e-3 * 1.0e-3,
    GroupDef = BaseGroupDef * AddeGroupDef * 1.0e-3 *
		 1.0e-3,
    GroupSpeed = BaseGroupSpeed * SpeedeGroupDef * 1.0e-3 *
		   1.0e-3,
    Attr#attr{atk = Atk + Lev * GroupAtk,
	      hp_max = HpMax + Lev * GroupHp,
	      def = Def + Lev * GroupDef,
	      speed = Speed + Lev * GroupSpeed}.

