-spec login(#role{}) -> {ok, #role{}}.

login(Role = #role{m_vip = #m_vip{lev = VipLev}}) ->
    Role1 = calc_sprites(Role),
    NRole = #role{m_sprite_tree =
		      #m_sprite_tree{power = Power}} =
		calc_attr(Role1),
    put(sprite_tree_power, Power),
    NewRole = case var:get_var(NRole, other, 3101, 0) of
		0 ->
		    case Power > 0 of
		      true ->
			  SpritePower = calc_sprite_power(NRole),
			  Msg = util:fbin("vip=~w,属性战力=~w,精灵战力=~w,",
					  [VipLev, max(0, Power - SpritePower),
					   SpritePower]),
			  log:save(custom,
				   {Role, <<"古树战力"/utf8>>, [{msg, Msg}]});
		      _ -> skip
		    end,
		    var:set_var(NRole, other, 3101, 1);
		_ -> NRole
	      end,
    {ok, NewRole}.

-spec login_out(#role{}) -> ok.

login_out(Role = #role{m_vip = #m_vip{lev = VipLev},
		       m_sprite_tree = #m_sprite_tree{power = Power}}) ->
    case get(sprite_tree_power) of
      OldPower
	  when is_integer(OldPower) andalso OldPower =/= Power ->
	  SpritePower = calc_sprite_power(Role),
	  Msg = util:fbin("vip=~w,属性战力=~w,精灵战力=~w,",
			  [VipLev, max(0, Power - SpritePower), SpritePower]),
	  log:save(custom, {Role, <<"古树战力"/utf8>>, [{msg, Msg}]});
      _ -> skip
    end,
    ok.

