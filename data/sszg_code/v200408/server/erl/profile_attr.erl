-spec attr_list(#role{}) -> [{AttrId :: integer(),
			      AttVal :: integer()}].

attr_list(Role) -> calc(Role, #attr{}).

-spec calc(RoleOrRobot,
	   Attr) -> NewAttr when RoleOrRobot :: #role{} |
						#role_robot{},
				 Attr :: #attr{}, NewAttr :: #attr{}.

calc(RoleOrRobot, Attr) ->
    calc([avatar, say_frame, honor, looks], RoleOrRobot,
	 Attr, []).

calc([], #role{name = _Name}, _BaseAttr, Attr) -> Attr;
calc([], #role_robot{name = _Name}, _BaseAttr, Attr) ->
    Attr;
calc([Label | Rest], RoleOrRobot, BaseAttr, Attr) ->
    ModAttr = mod_attr(Label, RoleOrRobot),
    calc(Rest, RoleOrRobot, BaseAttr,
	 item_lib:merge(Attr, ModAttr)).

-spec update(#role{}) -> #role{}.

