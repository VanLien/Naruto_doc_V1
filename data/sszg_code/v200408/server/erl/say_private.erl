do_add_private_offine_msg({_, SId}, ToRoleId = {_, SId},
			  SaySend) ->
    say_mgr:info({add_private_offine_msg, ToRoleId,
		  SaySend});
do_add_private_offine_msg(_RoleId,
			  ToRoleId = {_, ToSId}, SaySend) ->
    cluster_lib:cast(ToSId, say_mgr, info,
		     [{add_private_offine_msg, ToRoleId, SaySend}]).

do_del_private_offine_msg(RoleId = {_, SId},
			  ToRoleId = {_, SId}) ->
    say_mgr:info({del_private_offline_msg, ToRoleId,
		  RoleId});
do_del_private_offine_msg(RoleId,
			  ToRoleId = {_, ToSId}) ->
    cluster_lib:cast(ToSId, say_mgr, info,
		     [{del_private_offline_msg, ToRoleId, RoleId}]).

check_lev(Role = #role{lev = Lev},
	  #{to_lev := ToLev, to_vip_lev := ToVipLev})
    when Lev < 30 ->
    case ToLev - 10 > Lev of
      false -> true;
      true -> {false, lang:get(<<"低于对方10级不允许私聊对方"/utf8>>)}
    end;
check_lev(_Role, _ToLev) -> true.

get_target_info(Role, ToRoleId) ->
    case invite_code:get_bind_role(Role, ToRoleId) of
      {ok, #invite_code_bind{lev = ToLev, vip = ToVipLev}} ->
	  {ok,
	   #{lev => ToLev, vip_lev => ToVipLev,
	     type => invite_code}};
      _ ->
	  case friend_lib:get_friend(Role, ToRoleId) of
	    {ok, #friend_tmp{lev = ToLev, vip_lev = ToVipLev}} ->
		{ok,
		 #{lev => ToLev, vip_lev => ToVipLev, type => friend}};
	    _ -> {false, lang:get(<<"对方不是好友，不能私聊"/utf8>>)}
	  end
    end.


