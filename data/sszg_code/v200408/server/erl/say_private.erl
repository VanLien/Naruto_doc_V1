-spec say(#role{}, role_id(), non_neg_integer(),
	  bitstring()) -> {false, bitstring()} |
			  {false, binary(), #role{}} | ok.

say(#role{id = RoleId}, RoleId, _Len, _Msg) ->
    {false, lang:get(<<"不能给自己发送信息"/utf8>>)};
say(Role = #role{id = RoleId = {FromRid, FromSrvId},
		 m_vip = #m_vip{lev = VipLev}, capacity = Capacity,
		 name = FromName, lev = FromLev, career = FromCareer,
		 sex = FromSex, face_id = FromFaceId,
		 m_avatar = #m_avatar{used = HeadBid},
		 m_say = #m_say{used = ChatBubbleBid}},
    ToRoleId = {ToId, ToSrvId}, Len, Msg) ->
    CheckL = [lev, cd, emulator, msg_len, sys_ban, ad,
	      banned, repeak2, freqcy],
    case say:do_check_speak(CheckL, Role,
			    #{channel => 999999999, len => Len, msg => Msg,
			      to_rid => ToRoleId})
	of
      {false, Reason} -> {false, Reason};
      {false, Reason, NRole} -> {false, Reason, NRole};
      {send_self, Reason, NRole} -> {false, Reason, NRole};
      ok ->
	  case sns_black:is_black(RoleId, ToRoleId) of
	    true -> {false, lang:get(<<"不能给自己黑名单中的玩家发信息"/utf8>>)};
	    false ->
		case get_target_info(Role, ToRoleId) of
		  {false, Reason} -> {false, Reason};
		  {ok, #{lev := ToLev, vip_lev := ToVipLev}} ->
		      case check_lev(Role,
				     #{to_lev => ToLev, to_vip_lev => ToVipLev})
			  of
			{false, Reason} -> {false, Reason};
			true ->
			    {SayMsg, KeyWords} =
				keyword:filter_return_keyword(Msg),
			    Now = date:unixtime(),
			    log:chat(Role, 999999999,
				     util:fbin("~w_~s", [ToId, ToSrvId]), Msg,
				     KeyWords),
			    {_, FromFaceFile, FromFaceUpdateTime} =
				role_face:face_info(Role),
			    case role_query:rec(by_id, ToRoleId, role_base) of
			      {ok,
			       #role_base{id = {ToRid, ToSrvId},
					  conn_pid = ToConnPid, name = ToName,
					  lev = ToLev1, career = ToCareer,
					  sex = ToSex, face_id = ToFaceId,
					  face_update_time = FaceUpdateTime,
					  face_file = FaceFile}} ->
				  role:pack_send(Role, 12721,
						 {1, ToRid, ToSrvId, ToName,
						  ToLev1, ToCareer, ToFaceId,
						  Len, SayMsg, ToSex, VipLev,
						  Capacity, HeadBid,
						  ChatBubbleBid, Now,
						  FaceUpdateTime, FaceFile}),
				  case role_lib:is_deposit(ToConnPid) of
				    true ->
					SendMsg = #say_msg{len = Len,
							   msg = SayMsg,
							   tick = Now},
					SaySend = #say_send{id = RoleId,
							    name = FromName,
							    lev = FromLev,
							    career = FromCareer,
							    face_id =
								FromFaceId,
							    sex = FromSex,
							    vip_lev = VipLev,
							    capacity = Capacity,
							    head_bid = HeadBid,
							    chat_bubble =
								ChatBubbleBid,
							    msg_list =
								[SendMsg],
							    face_update_time =
								FromFaceUpdateTime,
							    face_file =
								FromFaceFile},
					do_add_private_offine_msg(RoleId,
								  ToRoleId,
								  SaySend);
				    false ->
					role:pack_send(ToConnPid, 12721,
						       {2, FromRid, FromSrvId,
							FromName, FromLev,
							FromCareer, FromFaceId,
							Len, SayMsg, FromSex,
							VipLev, Capacity,
							HeadBid, ChatBubbleBid,
							Now, FromFaceUpdateTime,
							FromFaceFile}),
					notice_below:send_private(ToConnPid,
								  {FromRid,
								   FromSrvId,
								   FromName,
								   FromCareer})
				  end,
				  role_trigger:async_fire(Role,
							  #evt_friend_sns{}),
				  ok;
			      _ ->
				  {ToRid, ToSrvId} = ToRoleId,
				  role:pack_send(Role, 12721,
						 {11, ToRid, ToSrvId, <<>>, 0,
						  0, 0, Len, SayMsg, 0, VipLev,
						  Capacity, HeadBid,
						  ChatBubbleBid, Now, 0, <<>>}),
				  SendMsg = #say_msg{len = Len, msg = SayMsg,
						     tick = Now},
				  SaySend = #say_send{id = RoleId,
						      name = FromName,
						      lev = FromLev,
						      career = FromCareer,
