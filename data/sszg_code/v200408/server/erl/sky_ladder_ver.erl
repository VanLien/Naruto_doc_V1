do({m_sky_ladder, Ver = 1, RefTime, CombatTime, RefList,
    BestRank, _CanCombatNum, HadCombatNum, BuyCombatNum,
    AccCombatNum, FirstReward, NextResetNine, Worship,
    WorshipList}) ->
    NewVer = Ver + 1,
    MSkyLadder = {m_sky_ladder, NewVer, RefTime, CombatTime,
		  RefList, BestRank,
		  sky_ladder_data:get_const(join_times), HadCombatNum,
		  BuyCombatNum, AccCombatNum, FirstReward, NextResetNine,
		  Worship, WorshipList, 0, 0, 0},
    do(MSkyLadder);
do(MSkyLadder = #m_sky_ladder{ver = 2,
			      ref_list = RefList}) ->
    NewRefList = [sky_ladder_f_ver(I) || I <- RefList],
    {ok, MSkyLadder#m_sky_ladder{ref_list = NewRefList}};
do(MSkyLadder) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidsky_ladder_ver24, _,
       {__Levelsky_ladder_ver24, __Tracessky_ladder_ver24}}
	  when __Levelsky_ladder_ver24 band 8 /= 0 orelse
		 __Tracessky_ladder_ver24 /= [] ->
	  lager:do_log(error,
		       [{module, sky_ladder_ver}, {function, do}, {line, 24},
			{pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("未知的旧数据:~w", [MSkyLadder]), none, 4096, 8,
		       __Levelsky_ladder_ver24, __Tracessky_ladder_ver24,
		       lager_event, __Pidsky_ladder_ver24);
      _ -> ok
    end,
    {false, lang:get(<<"天梯数据转换失败"/utf8>>)}.

