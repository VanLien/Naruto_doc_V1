-spec merge_data(#role{}) -> {ok, #role{}}.

merge_data(Role) ->
    case sys_env:get(merge_index, 0) of
      0 -> {ok, Role};
      MergeIdx ->
	  case MergeIdx > var:get_var(Role, other, 3068, 0) of
	    true ->
		{ok, NRole} = del_timeout_data(Role),
		{ok, var:set_var(NRole, other, 3068, MergeIdx)};
	    _ -> {ok, Role}
	  end
    end.

del_timeout_data(Role = #role{id = {_, Sid},
			      m_var = #m_var{timeout_vars = TimeOutVars}}) ->
    CampIds = lookup(Sid),
    {Role1 = #role{m_var =
		       MVar = #m_var{other_vars = OtherVars}},
     NewTimeOutVars, DelVals} =
	merge_do_holiday_val(Role, CampIds, TimeOutVars, [],
			     []),
    {ok,
     Role1#role{m_var =
		    MVar#m_var{timeout_vars = NewTimeOutVars,
			       other_vars = [{999999, DelVals} | OtherVars]}}}.

merge_do_holiday_val(Role, _CampIds, [], L, DelList) ->
    {Role, lists:reverse(L), DelList};
merge_do_holiday_val(Role, CampIds,
		     [{{holiday, Id}, {T, Val}} | Others], L, DelList) ->
    case holiday_lib:get_holiday_data(Id) of
      Holiday = #holiday{start_time = {open_day, _}} ->
	  case lists:member(Id, CampIds) of
	    true ->
		NRole = do_merge_del_val(Role, Holiday, Val),
		merge_do_holiday_val(NRole, CampIds, Others, L,
				     [{{holiday, Id}, {T, Val}} | DelList]);
	    _ ->
		merge_do_holiday_val(Role, CampIds, Others,
				     [{{holiday, Id}, {T, Val}} | L], DelList)
	  end;
      _ ->
	  merge_do_holiday_val(Role, CampIds, Others,
			       [{{holiday, Id}, {T, Val}} | L], DelList)
    end;
merge_do_holiday_val(Role, CampIds, [Val | Others], L,
		     DelList) ->
    merge_do_holiday_val(Role, CampIds, Others, [Val | L],
			 DelList).

