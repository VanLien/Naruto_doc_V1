send_mail(Role, Award, Title, Content) ->
    {MailAssets, MailItems} =
	format:split_assets_items(Award),
    Mail = {Title, Content, MailAssets, MailItems, Title},
    {ok, NRole} = mail:add(Role, Mail),
    NRole.


