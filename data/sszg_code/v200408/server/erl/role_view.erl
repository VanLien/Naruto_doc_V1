    to_attr_ext_data(Other, Role, P, [{6, GSLev} | L]).

to_cli_add_attr(AddAttr) ->
    [{attr_data:atom_to_int(K), V} || {K, V} <- AddAttr].

to_cli_skill(Skills) ->
    case Skills of
      [_ | _] ->
	  [Sk#hallows_skill{skill_bid = 0}
	   || Sk = #hallows_skill{} <- Skills];
      _ -> [#hallows_skill{pos = 1}]
    end.


