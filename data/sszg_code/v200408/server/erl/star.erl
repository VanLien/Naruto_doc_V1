-spec open_fetter(#role{}, pos_integer()) -> {false,
					      binary()} |
					     {ok, #role{}, list()}.

open_fetter(Role = #role{m_star =
			     MStar = #m_star{fetter_list = List}},
	    SetId) ->
    case [T
	  || {SetIdT, PosT, T} <- List,
	     SetIdT == SetId andalso PosT == 2]
	of
      [_ | _] -> {false, lang:get(<<"该星命已激活第二羁绊"/utf8>>)};
      _ ->
	  Expend = star_data:get_constant(unlocked_yoke),
	  GL = format:val_to_loss([Expend], open_fetter),
	  case role_gain:do(Role, GL) of
	    {ok, NRole} ->
		log:log_gain(GL, Role, NRole, <<"星命"/utf8>>,
			     util:fbin("解锁第二羁绊, 套装:~w", [SetId])),
		NewList = [{SetId, 2, 0} | List],
		NewMStar = MStar#m_star{fetter_list = NewList},
		NewRole = NRole#role{m_star = NewMStar},
		{ok, NewRole, NewList};
	    {false, #loss{msg = Msg}} -> {false, Msg}
	  end
    end.

ref_partner(Role = #role{partner_bag =
			     PB = #partner_bag{partner_list = PList}},
	    PartnerId, NewSetId, Type) ->
    case partner_lib:get_partner(Role, PartnerId) of
      false -> Role;
      P = #partner{fetter = Fetters}
	  when length(Fetters) >= 2 andalso Type == add ->
	  Role;
      P = #partner{fetter = Fetters} ->
	  NewFetters = case Type of
			 add -> [NewSetId | Fetters];
			 _ -> lists:delete(NewSetId, Fetters)
		       end,
	  NewP = partner_lib:calc_attr(Role,
				       P#partner{fetter = NewFetters}),
	  partner:push_ref_partners(Role, [NewP]),
	  NewPList = lists:keystore(PartnerId, #partner.id, PList,
				    NewP),
	  NewPB = PB#partner_bag{partner_list = NewPList},
	  Role2 = Role#role{partner_bag = NewPB},
	  partner_lib:ref_formation_attr(Role2, PartnerId)
    end.

check_can_fetter([partner | Other], Role,
		 Cache = #{partner_id := Id, set_id := SetId}) ->
    LimitLev = partner_data:get_constant(fetter_open),
    case partner_lib:get_partner(Role, Id) of
      #partner{fetter = SetIds} when length(SetIds) >= 2 ->
	  {false, lang:get(<<"羁绊已达上限"/utf8>>)};
      #partner{fetter = SetIds, lev = Lev}
	  when length(SetIds) >= 1 andalso Lev < LimitLev ->
	  {false,
	   util:fbin(lang:get(<<"英雄~w级才能羁绊第二个星命"/utf8>>),
		     [LimitLev])};
      #partner{fetter = SetIds} ->
	  case lists:member(SetId, SetIds) of
	    true -> {false, lang:get(<<"已经与当前星命达成羁绊"/utf8>>)};
	    _ ->
		check_can_fetter(Other, Role, Cache#{old_set => SetIds})
	  end;
      _ -> {false, lang:get(<<"找不到该伙伴"/utf8>>)}
    end;
check_can_fetter([set_id | _], Role,
		 #{set_id := SetId, old_set := OldSet}) ->
    case get_star(Role, SetId) of
      #star{natals = Natals} when length(Natals) >= 4 ->
	  OldSet;
      false -> {false, lang:get(<<"该星命未激活"/utf8>>)};
      _ -> {false, lang:get(<<"穿戴4个命格激活后才能羁绊哦"/utf8>>)}
    end;
check_can_fetter(_Other, _Role, _Cache) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidstar254, _, {__Levelstar254, __Tracesstar254}}
	  when __Levelstar254 band 8 /= 0 orelse
		 __Tracesstar254 /= [] ->
	  lager:do_log(error,
		       [{module, star}, {function, check_can_fetter},
			{line, 254}, {pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("错误的处理流程: ~w", [_Other]), none, 4096, 8,
		       __Levelstar254, __Tracesstar254, lager_event,
		       __Pidstar254);
      _ -> ok
    end,
    {false, lang:get(<<"参数错误"/utf8>>)}.

