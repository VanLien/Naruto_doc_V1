-spec gm_set_lev(#role{}, pos_integer(),
		 pos_integer()) -> {ok, #role{}} | {false, binary()}.

gm_set_lev(Role = #role{m_star =
			    #m_star{star_list = List}},
	   SetId, Lev) ->
    case lists:keyfind(SetId, #star.set_id, List) of
      Star = #star{} ->
	  BreakLev = Lev rem 10,
	  NewStar = Star#star{lev = Lev, break_lev = BreakLev},
	  NRole2 = star_lib:cal_star(Role, NewStar),
	  NRole3 = role_trigger:fire(#evt_star_level_up{},
				     NRole2),
	  StarType = star_data:get_type(SetId),
	  NewRole = partner_lib:ref_partner_by_type(NRole3,
						    [StarType], []),
	  {ok, NewRole};
      false -> {false, lang:get(<<"设置失败"/utf8>>)}
    end.

