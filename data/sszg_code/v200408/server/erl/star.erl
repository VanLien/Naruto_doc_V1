-spec fetter(#role{}, pos_integer(), pos_integer(),
	     pos_integer()) -> {false, binary()} |
			       {ok, #role{}, binary()}.

fetter(Role = #role{m_star =
			MStar = #m_star{fetter_list = Fetters}},
       SetId, PosId, PartnerId)
    when PosId =< 2 ->
    Cache = #{partner_id => PartnerId, set_id => SetId},
    case check_can_fetter([partner, set_id], Role, Cache) of
      {false, Msg} -> {false, Msg};
      _OldSets ->
	  case [{SetIdT, PosIdT, IdT}
		|| {SetIdT, PosIdT, IdT} <- Fetters,
		   SetIdT == SetId andalso PosIdT == PosId]
	      of
	    [{SetIdTemp, PosIdTemp, 0} | _] ->
		NewFetters = [{SetId, PosId, PartnerId}
			      | lists:delete({SetIdTemp, PosIdTemp, 0},
					     Fetters)],
		NRole = Role#role{m_star =
				      MStar#m_star{fetter_list = NewFetters}},
		NewRole = ref_partner(NRole, PartnerId, SetId, add),
		{NewRole, NewFetters};
	    [_ | _] -> {false, lang:get(<<"已有英雄羁绊"/utf8>>)};
	    _ -> {false, lang:get(<<"未激活该羁绊"/utf8>>)}
	  end
    end;
fetter(_Role, _SetId, _PosId, _PartnerId) ->
    {false, lang:get(<<"参数错误"/utf8>>)}.

