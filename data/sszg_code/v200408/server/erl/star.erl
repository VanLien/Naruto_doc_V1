	  end,
    NewL = lists:foldl(Fun, [], L),
    Role#role{m_star = MStar#m_star{fetter_list = NewL}}.

do_open(Role = #role{m_star_tower =
			 #m_star_tower{max_tower = Tower},
		     m_star =
			 MStar = #m_star{star_list = List,
					 fetter_list = List2}},
	CombatTower) ->
    AllList = star_data:get_all_star(),
    NoOpens = [SetId
	       || SetId <- AllList,
		  lists:keyfind(SetId, #star.set_id, List) == false],
    {OpenList, AddFetterList} = do_open(NoOpens, List2,
					Tower, [], []),
    case OpenList =/= [] andalso AddFetterList =/= [] of
      true ->
	  case CombatTower == 0 of
	    false -> role:pack_send(11326, {CombatTower});
	    _ -> ok
	  end,
	  role:pack_send(11308,
			 {star_lib:to_cli(OpenList), AddFetterList});
      _ -> ok
    end,
    Role#role{m_star =
		  MStar#m_star{star_list = OpenList ++ List,
			       fetter_list = List2 ++ AddFetterList}}.

do_open([], _List, _Tower, L1, L2) -> {L1, L2};
do_open([SetId | NoOpens], List, Tower, L1, L2) ->
    case check_open(SetId, Tower) of
      true ->
	  NL1 = [init_star(SetId) | L1],
	  NL2 = case lists:keyfind(SetId, 1, List) of
		  false -> [{SetId, 1, 0} | L2];
		  _ -> lists:usort(L2)
		end,
	  do_open(NoOpens, List, Tower, NL1, NL2);
      _ -> do_open(NoOpens, List, Tower, L1, L2)
    end.

check_open(SetId, Tower) ->
    case star_data:get_limit(SetId) of
      undefined -> false;
      Num when Tower >= Num -> true;
      _ -> false
    end.

