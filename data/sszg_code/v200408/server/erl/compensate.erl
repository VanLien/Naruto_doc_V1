    {ok, var:set_var(Role, other, 3029, 1)};
login(Role = #role{id = RoleId,
		   m_vip = #m_vip{lev = VipLev}}) ->
    IsComp = var:get_var(Role, other, 3029, 0),
    NewRole = case IsComp =:= 0 of
		true ->
		    Gold = charge_misc:charge_sum(Role),
		    VipReward = vip_reward(VipLev),
		    Items = VipReward ++ [{3, Gold}],
		    role:apply(async, Role#role.pid,
			       {mail, send,
				[{lang:get(<<"Bồi thường điều chỉnh trò chơi"/utf8>>),
				  lang:get(<<"Để tối ưu hóa trải nghiệm đẩy bản đồ "
					     "cho phần lớn các nhà thám hiểm, bản "
					     "cập nhật này đã giảm đáng kể độ khó "
					     "khi đẩy ngục tối bản đồ. Để cân bằng "
					     "vấn đề nhịp điệu tổng thể,Cấu trúc sức "
					     "chiến đấu của anh hùng sẽ được điều "
					     "chỉnh đồng thời. Sau khi cập nhật, sức "
					     "chiến đấu có thể giảm xuống. Chúng tôi "
