-spec push(#role{}, all | tuple()) -> ok.

push(Role = #role{channel = Channel, lev = Lev}, all) ->
    L = ets:tab2list(notice_board),
    Now = date:unixtime(),
    L1 = [I
	  || I = #notice_board{start_time = StartTime,
			       end_time = EndTime, lev = NeedLev,
			       channel = ChannelNames}
		 <- L,
	     StartTime =< Now, Now < EndTime, Lev >= NeedLev,
	     ChannelNames =:= [] orelse
	       lists:member(Channel, ChannelNames)],
    push(Role, {0, L1});
push(Role = #role{lev = Lev, channel = Channel},
     {Type, Boards}) ->
    L = [{Board,
	  util:if_true(var:get_var(Role, timeout, {3003, Id}) =:=
			 0,
		       0, 1)}
	 || Board = #notice_board{id = Id, lev = NeedLev,
				  channel = ChannelNames}
		<- Boards,
	    Lev >= NeedLev,
	    ChannelNames =:= [] orelse
	      lists:member(Channel, ChannelNames)],
    sys_conn:pack_send(10950, {Type, L}),
    ok.

