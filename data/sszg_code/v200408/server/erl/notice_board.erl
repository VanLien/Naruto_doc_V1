load() ->
    Now = date:unixtime(),
    ets:delete_all_objects(notice_board),
    case
      db:get_all("select id, type, title, summary, content, "
		 "sort, lev, start_time, end_time, channel "
		 "from sys_notice_board where type > 2 "
		 "and end_time > ?",
		 [Now])
	of
      {ok, L} -> do_load(L, Now, []);
      _ -> skip
    end.

do_load([], Now, L) ->
    L1 = [I || I <- L, I#notice_board.start_time =< Now],
    role_group:apply(world,
		     {notice_board, push, [{0, L1}]});
do_load([[Id, Type, Title, Summary, Content, Sort, Lev,
	  StartTime, EndTime, Channel]
	 | T],
	Now, L) ->
    {ok, ChannelNames} = util:string_to_term(Channel),
    Board = #notice_board{id = Id, type = Type,
			  title = Title, summary = Summary, content = Content,
			  sort = Sort, lev = Lev, start_time = StartTime,
			  end_time = EndTime, channel = ChannelNames},
    ets:insert(notice_board, Board),
    if StartTime > Now ->
	   util:set_timer({board, Id},
			  min(864000, StartTime - Now), {board, Id});
       EndTime > Now ->
	   util:set_timer({board, Id}, min(864000, EndTime - Now),
			  {board, Id});
       true -> skip
    end,
    do_load(T, Now, [Board | L]).


