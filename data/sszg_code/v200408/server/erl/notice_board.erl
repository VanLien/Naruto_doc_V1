			     io_lib:format("公告过期:~w", [Id]), none, 4096, 128,
			     __Levelnotice_board91, __Tracesnotice_board91,
			     lager_event, __Pidnotice_board91);
	    _ -> ok
	  end,
	  role_group:pack_send(world, 10951, {Id}),
	  ets:delete(notice_board, Id);
      [] -> skip
    end,
    {noreply, State};
handle_info(_Info, State) -> {noreply, State}.

terminate(_Reason, _State) -> ok.

