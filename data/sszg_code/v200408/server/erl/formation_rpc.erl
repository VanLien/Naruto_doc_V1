    case formation:push_sys_formation(Role, SysType) of
      {ok, NRole} -> {ok, NRole};
      _ -> ok
    end;
handle(11212, {0, FormationType, PosInfo, HallowsId},
       Role) ->
    case formation_lib:set_formation(Role, FormationType,
				     PosInfo, HallowsId)
	of
      {ok, Role1} ->
	  {ok, NRole} = role_misc:calc_power(Role1),
	  NRole2 = partner_lib:ref_formation_attr(NRole, 0),
	  {reply, {1, lang:get(<<"阵法设置成功"/utf8>>), 0}, NRole2};
      {false, Reason} -> {reply, {0, Reason, 0}}
    end;
