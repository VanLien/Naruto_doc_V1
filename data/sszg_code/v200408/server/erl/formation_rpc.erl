handle(_Cmd, _Data, _Role = #role{s_event = _SEvent}) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidformation_rpc56, _,
       {__Levelformation_rpc56, __Tracesformation_rpc56}}
	  when __Levelformation_rpc56 band 128 /= 0 orelse
		 __Tracesformation_rpc56 /= [] ->
	  lager:do_log(debug,
		       [{module, formation_rpc}, {function, handle},
			{line, 56}, {pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("模块[~w]收到无效的RPC调用[~w]: ~w ~w",
				     [formation_rpc, _Cmd, _Data, _SEvent]),
		       none, 4096, 128, __Levelformation_rpc56,
		       __Tracesformation_rpc56, lager_event,
		       __Pidformation_rpc56);
      _ -> ok
    end,
    {error, unknow_command}.


