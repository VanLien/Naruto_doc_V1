gen_partner_([], _Role, L) -> L;
gen_partner_([#formation_fight_info{fight_pos = Pos,
				    id = PId}
	      | T],
	     Role, L) ->
    case partner_lib:get_partner(Role, PId) of
      false -> gen_partner_(T, Role, L);
      #partner{bid = Bid, lev = PLev, star = Star,
	       quality = Quality, all_attr = AllAttr,
	       use_skin = UseSkin} ->
	  #attr{speed = Speed, hp_max = HpMax,
		crit_rate = _Crit} =
	      AllAttr,
	  #partner_base_data{hook_skills = HookSkills} =
	      partner_data:get_base(Bid),
	  AllSkills = HookSkills ++ [10001],
	  SkillInfo = gen_skill_(AllSkills, AllAttr, []),
	  Crit = 0,
	  Data = {Pos, Speed, Bid, PLev, Star, Quality,
		  HpMax * 100, Crit, SkillInfo, UseSkin},
	  gen_partner_(T, Role, [Data | L])
    end;
gen_partner_([_ | T], Role, L) ->
    gen_partner_(T, Role, L).

gen_skill_([], _Attr, List) -> List;
gen_skill_([10001], _Attr, List = [_ | _]) -> List;
gen_skill_([SkillId | T], Attr = #attr{atk = Atk},
	   List) ->
    case skill_data:get_skill(SkillId) of
      #skill_data{type = active_skill, is_normal_skill = 1,
		  effect_list = EffList} ->
	  Fun = fun (EffId) ->
			case skill_data:get_effect(EffId) of
			  #effect_data{effect_type = hurt, target_num = TNum,
				       condition = none} ->
			      {true,
			       {EffId, TNum, round(Atk * 1.3999999999999999),
				round(Atk * 1.6)}};
			  _ -> false
			end
		end,
	  case lists:filtermap(Fun, EffList) of
	    EffInfo = [{_, 1, _, _}] ->
		gen_skill_(T, Attr, [{SkillId, EffInfo, 100} | List]);
	    _ -> gen_skill_(T, Attr, List)
	  end;
      _ -> gen_skill_(T, Attr, List)
    end.

gen_unit(UnitId) ->
    #unit_data{formation = {FormationType, _FormationLev}} =
	unit_data:get(UnitId),
    MonList = case unit_data:get_multi_wave(UnitId) of
		[] ->
		    case gen_unit_(UnitId, FormationType) of
		      false -> [];
		      {true, FOList} -> [FOList]
		    end;
		UnitIds ->
		    lists:filtermap(fun (Id) -> gen_unit_(Id, FormationType)
				    end,
				    UnitIds)
	      end,
    {FormationType, MonList}.

