gen_unit_fighter_(MonBid, Pos, FormationType) ->
    #formation_data{pos = FightPosList} =
	formation_data:get_formation(FormationType),
    FightPos = list_util:keyfind(Pos, FightPosList),
    Attr = #attr{hp_max = _HpMax, speed = Speed,
		 crit_rate = _Crit} =
	       unit_data:get_attr(MonBid),
    HpMax = 10,
    SkillIds = unit_data:get_active_skills(MonBid) ++
		 [10001],
    SkillInfo = gen_skill_(SkillIds, Attr#attr{atk = 1},
			   []),
    Crit = 0,
    {FightPos, MonBid, Speed, HpMax, Crit, SkillInfo}.


