-spec enter(#role{}, pos_integer()) -> {ok, #role{}}.

enter(Role = #role{id = RoleId, pid = RolePid,
		   link = #link{conn_pid = ConnPid},
		   combat_pid = CombatPid, play_speed = Speed},
      CombatType) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidcombat_loop25, _,
       {__Levelcombat_loop25, __Tracescombat_loop25}}
	  when __Levelcombat_loop25 band 128 /= 0 orelse
		 __Tracescombat_loop25 /= [] ->
	  lager:do_log(debug,
		       [{module, combat_loop}, {function, enter}, {line, 25},
			{pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("角色[~ts]请求进入指定类型战斗:~w ~w ~w",
				     [Role#role.name, CombatType,
				      Role#role.combat_type_list, CombatPid]),
		       none, 4096, 128, __Levelcombat_loop25,
		       __Tracescombat_loop25, lager_event, __Pidcombat_loop25);
      _ -> ok
    end,
    {ok, Role1} = enter_map(Role, CombatType),
    Role2 = combat_type_update(Role1,
			       Role#role.ui_combat_type),
    NRole = combat_type_update(Role2, CombatType),
    case combat_lib:combat_pid(Role, CombatType) of
      {CombatType1, CombatPid} ->
	  sys_conn:pack_send(20060, {CombatType1, 1}),
	  case {whereis(lager_event), whereis(lager_event),
		lager_config:get({lager_event, loglevel}, {0, []})}
	      of
	    {undefined, undefined, _} ->
		fun () -> {error, lager_not_running} end();
	    {undefined, _, _} ->
