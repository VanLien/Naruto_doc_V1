	      AllNum)
    when AllNum > 0 ->
    case resonate_lib:check_open(Role) of
      {false, Msg} -> {false, Msg};
      _ ->
	  ResonateLev = resonate_lib:get_lev(Role),
	  LimitNum =
	      resonate_data:get_extract_limit_num(ResonateLev),
	  NeedTime =
	      resonate_data:get_extract_need_time(ResonateLev),
	  case AllNum > LimitNum of
	    true ->
		{false,
		 lang:get(<<"Vượt quá giới hạn tinh chế"/utf8>>)};
	    _ when NeedTime > 0 ->
		Expend = [{ExpendId, AllNum * ExpendNum}
			  || {ExpendId, ExpendNum}
				 <- resonate_data:get_const(single_refine_consume)],
		Loss = format:val_to_loss(Expend,
					  resonate_extract_start),
		case role_gain:do(Role, Loss) of
		  {ok, NRole = #role{m_resonate_extract = MR}} ->
		      log:log_gain(Loss, Role, NRole, <<"石碑提炼"/utf8>>,
				   util:fbin(lang:get(<<"Bắt đầu tinh luyện, cấp độ tượng đài:~w, "
