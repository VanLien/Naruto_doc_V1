		    (AllNum - DoNum - GetNum) * ExpendNum}
		   || {ExpendId, ExpendNum}
			  <- resonate_data:get_const(single_refine_consume)],
	  Items = case DoNum > 0 of
		    true ->
			ItemId = resonate_data:get_const(alchemy_goods),
			item_lib:merge(Item1, [{ItemId, DoNum}]);
		    _ -> Item1
		  end,
	  Gain = format:val_to_gain(Items, resonate_extract_stop),
	  case role_gain:do_notice(Role, Gain) of
	    {ok, NRole = #role{m_resonate_extract = MR}} ->
		log:log_gain(Gain, Role, NRole, <<"石碑提炼"/utf8>>,
			     util:fbin(lang:get(<<"Việc tinh luyện bia đá kết thúc sớm, "
						  "tổng cộng:~w, Đang chờ nhận hàng:~w, "
						  "Đã nhận:~w"/utf8>>),
				       [AllNum, DoNum, GetNum])),
		NewMR = MR#m_resonate_extract{all_num = 0, do_num = 0,
					      get_num = 0, do_end_time = 0},
		NewRole1 = NRole#role{m_resonate_extract = NewMR},
		NewRole = role_timer:del(resonate_extract_timer,
					 NewRole1),
		info(NewRole),
		{ok, NewRole};
	    {false, #gain{msg = Msg}} -> {false, Msg}
	  end;
      _ ->
	  {false,
	   lang:get(<<"Mọi sự tinh chế đã được hoàn tất"/utf8>>)}
    end;
extract_stop(_Role) ->
    {false,
     lang:get(<<"Việc tinh chế chưa bắt đầu"/utf8>>)}.

-spec extract_award(#role{}) -> {ok, #role{}}.

extract_award(Role = #role{m_resonate_extract =
			       #m_resonate_extract{all_num = AllNum,
						   do_num = DoNum,
						   get_num = GetNum}})
    when DoNum > 0 ->
    ItemId = resonate_data:get_const(alchemy_goods),
    Items = [{ItemId, DoNum}],
    Gain = format:val_to_gain(Items,
			      resonate_extract_award),
    case role_gain:do_notice(Role, Gain) of
      {ok, NRole = #role{m_resonate_extract = MR}} ->
	  log:log_gain(Gain, Role, NRole, <<"石碑提炼"/utf8>>,
		       util:fbin(lang:get(<<"Khai thác bia đá để lấy đạo cụ, tổng "
					    "cộng:~w, Đang chờ nhận hàng:~w, Đã "
					    "nhận:~w"/utf8>>),
				 [AllNum, DoNum, GetNum])),
	  NewMR = case AllNum =< GetNum + DoNum of
		    false ->
			MR#m_resonate_extract{do_num = 0,
					      get_num = GetNum + DoNum};
		    _ ->
			MR#m_resonate_extract{all_num = 0, do_num = 0,
					      get_num = 0}
		  end,
	  NRole2 = NRole#role{m_resonate_extract = NewMR},
	  NewRole = role_trigger:fire(#evt_extract_award{},
				      NRole2),
	  info(NewRole),
	  {ok, NewRole};
      {false, #gain{msg = Msg}} -> {false, Msg}
    end;
extract_award(#role{m_resonate_extract =
			#m_resonate_extract{all_num = AllNum}})
    when AllNum =< 0 ->
    {false,
     lang:get(<<"Việc tinh chế vẫn chưa bắt đầu"/utf8>>)};
extract_award(_Role) ->
    {false,
     lang:get(<<"Không có vật phẩm nào để thu hoạch"/utf8>>)}.

set_timer(Role = #role{m_resonate_extract =
			   #m_resonate_extract{all_num = AllNum, do_num = DoNum,
					       get_num = GetNum,
					       do_end_time = DoEndTime}})
    when AllNum > DoNum + GetNum ->
    TimeOut = max(1, DoEndTime - date:unixtime()),
    Timer1 = #timer{id = resonate_extract_timer,
		    timeout = TimeOut * 1000, times = 1,
		    m = resonate_extract, f = apply_timer, a = []},
    role_timer:set(Timer1, Role);
set_timer(Role) -> Role.

apply_timer(Role = #role{m_resonate_extract =
			     MR = #m_resonate_extract{all_num = AllNum,
						      do_num = DoNum,
						      get_num = GetNum}})
    when AllNum > DoNum + GetNum ->
    ResonateLev = resonate_lib:get_lev(Role),
    NeedTime =
	resonate_data:get_extract_need_time(ResonateLev),
    case AllNum =< DoNum + GetNum + 1 of
      true ->
	  NewMR = MR#m_resonate_extract{do_num = DoNum + 1,
					do_end_time = date:unixtime()},
	  NewRole = Role#role{m_resonate_extract = NewMR},
	  info(NewRole),
	  {ok, NewRole};
      _ ->
	  NewMR = MR#m_resonate_extract{do_num = DoNum + 1,
					do_end_time =
					    date:unixtime() + NeedTime},
	  NewRole1 = Role#role{m_resonate_extract = NewMR},
	  NewRole = set_timer(NewRole1),
	  info(NewRole),
	  {ok, NewRole}
    end;
apply_timer(Role) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidresonate_extract235, _,
       {__Levelresonate_extract235,
	__Tracesresonate_extract235}}
	  when __Levelresonate_extract235 band 8 /= 0 orelse
		 __Tracesresonate_extract235 /= [] ->
	  lager:do_log(error,
		       [{module, resonate_extract}, {function, apply_timer},
			{line, 235}, {pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("[~ts]~w定时器异常，在完全结束提炼后，仍然有定时器执行",
				     [Role#role.name, Role#role.id]),
		       none, 4096, 8, __Levelresonate_extract235,
		       __Tracesresonate_extract235, lager_event,
		       __Pidresonate_extract235);
      _ -> ok
    end,
    {ok, Role}.


