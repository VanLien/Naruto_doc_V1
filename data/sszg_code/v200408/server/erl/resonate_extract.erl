					     [ResonateLev, AllNum])),
		      Now = date:unixtime(),
		      NewMR = MR#m_resonate_extract{start_time = Now,
						    all_num = AllNum,
						    do_num = 0, get_num = 0,
						    do_end_time =
							Now + NeedTime},
		      NewRole1 = NRole#role{m_resonate_extract = NewMR},
		      NewRole2 = set_timer(NewRole1),
		      NewRole = role_trigger:fire(#evt_extract_start{},
						  NewRole2),
		      log:save(join,
			       {NewRole, <<"功能玩法"/utf8>>, <<"石碑提炼"/utf8>>}),
		      info(NewRole),
		      {ok, NewRole};
		  {false, #loss{msg = Msg}} -> {false, Msg}
		end;
	    _ ->
		case {whereis(lager_event), whereis(lager_event),
		      lager_config:get({lager_event, loglevel}, {0, []})}
		    of
		  {undefined, undefined, _} ->
		      fun () -> {error, lager_not_running} end();
		  {undefined, _, _} ->
		      fun () -> {error, {sink_not_configured, lager_event}}
		      end();
		  {__Pidresonate_extract144, _,
		   {__Levelresonate_extract144,
		    __Tracesresonate_extract144}}
		      when __Levelresonate_extract144 band 8 /= 0 orelse
			     __Tracesresonate_extract144 /= [] ->
		      lager:do_log(error,
				   [{module, resonate_extract},
				    {function, extract_start}, {line, 144},
				    {pid, pid_to_list(self())}, {node, node()}
				    | lager:md()],
				   io_lib:format("共鸣石碑提炼配置所需时间出错, 存在提炼时间为0的配置:~w",
						 [ResonateLev]),
				   none, 4096, 8, __Levelresonate_extract144,
				   __Tracesresonate_extract144, lager_event,
				   __Pidresonate_extract144);
		  _ -> ok
		end,
		{false, lang:get(<<"Lỗi tham số"/utf8>>)}
	  end
    end;
