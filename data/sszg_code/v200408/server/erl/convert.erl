-spec wish(#role{}) -> {false, bitstring()} |
		       {ok, #role{}}.

wish(Role = #role{m_vip = #m_vip{lev = VipLev},
		  m_wish =
		      MWish = #m_wish{is_double = IsDouble,
				      count = WishCount}}) ->
    Count = var:get_var(Role, five, 563, 0),
    case convert_data:wish_reward(Count + 1) of
      {Loss, Gain, Rate, VipLimit} when VipLimit =< VipLev ->
	  NewGain = calc_double_gain(Gain, IsDouble, []),
	  GL0 = format:val_to_gain(NewGain, wish),
	  GL1 = case Loss of
		  [{_, Num}] when Num =< 0 -> [];
		  _ -> format:val_to_loss(Loss, wish)
		end,
	  GL = lists:flatten([GL1, GL0]),
	  case role_gain:do_notice(Role, GL,
				   #gain_loss_opts{type = 1})
	      of
	    {false, #loss{}} ->
		{false, lang:get(<<"Không đủ Vàng"/utf8>>)};
	    {false, #gain{msg = Msg}} -> {false, Msg};
	    {ok, Role1} ->
		Role2 = var:set_var(Role1, five, 563, Count + 1),
		Role3 = Role2#role{m_wish =
				       MWish#m_wish{is_double = 0,
						    count = WishCount + 1}},
		NRole = calc_double_rate(Role3, Rate),
		push_info(NRole),
		log:log_gain(GL, Role, NRole,
			     <<"Trao đổi tài sản"/utf8>>,
			     util:fbin("Hôm nay~wNguyện thần phụ, tình huống "
				       "chí mạng:~w",
				       [Count + 1, IsDouble])),
		{ok, NRole}
	  end;
      {_Loss, _Gain, _Rate, VipLimit} ->
	  {false,
	   util:fbin(lang:get(<<"Thăng cấp lên VIP~wCó thể tăng số lần"/utf8>>),
		     [VipLimit])};
      _ ->
	  {false,
	   lang:get(<<"Đã đạt đến số lượng mong muốn tối đa "
		      "mỗi ngày"/utf8>>)}
    end.

-spec reward(#role{}) -> {false, bitstring()} |
			 {ok, #role{}}.

reward(Role = #role{m_wish =
			MWish = #m_wish{count = WishCount}}) ->
    case WishCount >= convert_data:get_const(reward_num) of
      true ->
	  Reward = convert_data:get_const(times_reward),
	  Gain = format:val_to_gain(Reward, wish_reward),
	  case role_gain:do_notice(Role, Gain) of
	    {false, #gain{}} ->
		{false,
		 lang:get(<<"Phần thưởng này tạm thời không có"/utf8>>)};
	    {ok, Role1} ->
		NewWishCount = WishCount -
				 convert_data:get_const(reward_num),
		Role2 = Role1#role{m_wish =
				       MWish#m_wish{count = NewWishCount}},
		push_info(Role2),
		log:log_gain(Gain, Role, Role2,
			     <<"Trao đổi tài sản"/utf8>>,
			     util:fbin("Nhận phần thưởng theo số điều ước do "
				       "Thần chủ thực hiện và số điều ước còn "
				       "lại~w",
				       [NewWishCount])),
		{ok, Role2}
	  end;
      _ ->
	  {false,
	   lang:get(<<"Chưa đáp ứng đủ điều kiện để nhận"/utf8>>)}
    end.

push_info(Role) ->
    Date = info(Role), role:pack_send(Role, 23601, Date).

push_ext_rate(Role) ->
    Date = info_ext_rate(Role),
    role:pack_send(Role, 23604, {Date}).

info(Role = #role{m_wish =
		      #m_wish{count = WishCount, is_double = IsDouble}}) ->
    Count = var:get_var(Role, five, 563, 0),
    Reward = util:if_true(WishCount >=
			    convert_data:get_const(reward_num),
			  1, 0),
    {Reward, WishCount, IsDouble, Count}.

calc_double_rate(Role = #role{m_wish =
				  MWish = #m_wish{}},
		 Rate) ->
    case util:rand_per_mille(Rate) of
      true -> Role#role{m_wish = MWish#m_wish{is_double = 1}};
      _ -> Role
    end.

calc_double_gain([], _IsDouble, Acc) -> Acc;
calc_double_gain([Gain = {Id, Val} | Rest], IsDouble,
		 Acc) ->
    NewGain = case IsDouble of
		1 -> {Id, Val * 2};
		_ -> Gain
	      end,
    calc_double_gain(Rest, IsDouble, [NewGain | Acc]).

calc_ext_gain(Type, Val, Role) ->
    DunList = list_pass_dun(Role),
    ExtRate = get_ext_rate(Type, DunList),
    case ExtRate =< 0 of
      false -> Val + util:floor(Val * ExtRate / 1000);
      _ -> Val
    end.

list_pass_dun(#role{m_dungeon =
			#m_dungeon{list = ModeList}}) ->
    List = [[[DId
	      || #dungeon{id = DId, status = DStatus} <- Duns,
		 DStatus =:= 3]
	     || #dun_chapter{list = Duns} <- Chapters]
	    || {_Mode1, Chapters} <- ModeList],
    lists:flatten(List).

info_ext_rate(Role) ->
    DunList = list_pass_dun(Role),
    get_ext_rate([1, 2], [], DunList).

get_ext_rate(Type, DunList) ->
    List = convert_data:ext_list(Type),
    ExtRate = case List -- List -- DunList of
		[] -> 0;
		Rest = [_ | _] ->
		    MaxDunId = lists:max(Rest),
		    convert_data:ext_reward({Type, MaxDunId});
		_ -> 0
	      end,
    ExtRate.

get_ext_rate([], Acc, _PassDunList) -> Acc;
get_ext_rate([Type | Rest], Acc, PassDunList) ->
    Rate = get_ext_rate(Type, PassDunList),
    get_ext_rate(Rest, [{Type, Rate} | Acc], PassDunList).

-spec push_coin(#role{}) -> ok.

push_coin(Role = #role{m_convert =
			   #m_convert{coin_ref_time = CoinRefTime}}) ->
    CampType = coin_camp_type(Role),
    CliList = to_coin_cli(convert_data:coin_list(CampType),
			  CampType, Role, []),
    sys_conn:pack_send(23606,
		       {CoinRefTime, CampType, CliList}),
    ok.

to_coin_cli([], _CampType, _Role, L) -> L;
to_coin_cli([Id | T], CampType,
	    Role = #role{m_convert =
			     #m_convert{coin_list = CoinList}},
	    L) ->
    Data = #{price := Price, num := Max} =
	       convert_data:get_coin({CampType, Id}),
    Coin = calc_coin(Role, Data),
    Num = list_util:keyfind(Id, CoinList, 0),
    D = {Id, Price, Coin, Num, Max},
    to_coin_cli(T, CampType, Role, [D | L]).

-spec buy_coin(#role{}, pos_integer()) -> {false,
					   binary()} |
					  {ok, #role{}}.

buy_coin(Role = #role{m_convert =
			  MConvert = #m_convert{coin_ref_time = RefTime,
						coin_list = CoinList},
		      m_vip = #m_vip{lev = VipLev}},
	 Id) ->
    CampType = coin_camp_type(Role),
    Num = list_util:keyfind(Id, CoinList, 0),
    case convert_data:get_coin({CampType, Id}) of
      #{num := Max} when Num >= Max ->
	  {false,
	   lang:get(<<"Số điểm vàng loại này đã được sử dụng "
		      "hết"/utf8>>)};
      Data = #{price := Price} ->
	  Coin = calc_coin(Role, Data),
	  VipCoin = case convert_data:coin_vip(VipLev) of
		      0 -> 0;
		      Ratio -> round(Coin * Ratio / 1000)
		    end,
	  GainVal = Coin + VipCoin,
	  Loss = format:val_to_loss([{gold, Price}], buy_coin),
	  Gain = format:val_to_gain([{1, GainVal}], buy_coin),
	  GL = Loss ++ Gain,
	  case role_gain:do(Role, GL) of
	    {false, #loss{msg = Msg}} -> {false, Msg};
	    {false, #gain{msg = Msg}} -> {false, Msg};
	    {ok, Role1} ->
		Msg = case VipLev > 0 of
			true ->
			    color:msg(lang:get(<<"lấy~ts(VIP~tsphép cộng)"/utf8>>),
				      [{item, {1, GainVal}}, {binary, VipLev}]);
			_ ->
			    color:msg(lang:get(<<"lấy~ts"/utf8>>),
				      [{item, {1, GainVal}}])
		      end,
		notice:alert(Msg),
		NewCoinList = lists:keystore(Id, 1, CoinList,
					     {Id, Num + 1}),
		NRole = Role1#role{m_convert =
				       MConvert#m_convert{coin_list =
							      NewCoinList}},
		log:log_gain(GL, Role, NRole, <<"点金处理"/utf8>>,
			     util:fbin("id:~w,ref_time:~w", [Id, RefTime])),
		NRole1 = var:add_var(NRole, day, 90, 1),
		NewRole = role_trigger:fire([#evt_convert{}], NRole1),
		push_coin(NewRole),
		{ok, NewRole}
	  end;
      _ ->
	  {false,
	   lang:get(<<"Dữ liệu cấu hình không tồn tại"/utf8>>)}
    end.

next_ref_time() ->
    date:next_diff(convert_data:get_const(point_gold_refresh)).

-spec add_coin_timer(#role{}) -> #role{}.

add_coin_timer(Role = #role{m_convert =
				MConvert = #m_convert{coin_ref_time = 0}}) ->
    Now = date:unixtime(),
    DiffTime = next_ref_time(),
    NewRefTime = Now + DiffTime,
    NRole = Role#role{m_convert =
			  MConvert#m_convert{coin_ref_time = NewRefTime}},
    role_timer:set(#timer{id = coin_timer,
			  timeout = DiffTime * 1000, times = 1, m = convert,
			  f = apply_coin_timer},
		   NRole);
add_coin_timer(Role = #role{m_convert =
				MConvert = #m_convert{coin_ref_time =
							  RefTime}}) ->
    Now = date:unixtime(),
    case RefTime > Now of
      true ->
	  DiffTime = next_ref_time(),
	  NewRefTime = Now + DiffTime,
	  NRole = Role#role{m_convert =
				MConvert#m_convert{coin_ref_time = NewRefTime}},
	  role_timer:set(#timer{id = coin_timer,
				timeout = DiffTime * 1000, times = 1,
				m = convert, f = apply_coin_timer},
			 NRole);
      _ ->
	  role_timer:set(#timer{id = coin_timer,
				timeout = max(1, RefTime - Now) * 1000,
				times = 1, m = convert, f = apply_coin_timer},
			 Role)
    end;
add_coin_timer(Role) -> Role.

-spec apply_coin_timer(#role{}) -> {ok, #role{}}.

apply_coin_timer(Role = #role{m_convert = MConvert}) ->
    NRole = add_coin_timer(Role#role{m_convert =
					 MConvert#m_convert{coin_ref_time = 0,
							    coin_list = []}}),
    push_coin(NRole),
    {ok, NRole}.

-spec coin_camp_type(#role{}) -> 0..1.

coin_camp_type(Role) ->
    case holiday_lib:get_open_holiday(Role,
				      [7001, 97001, 997001])
	of
      #holiday{end_time = EndTime} ->
	  case EndTime - date:unixtime() - 86400 > 0 of
	    true -> 1;
	    _ -> 0
	  end;
      _ -> 0
    end.

calc_coin(Role, #{coin := Coin, time := Time}) ->
    case dungeon:max_dun_id(Role) of
      0 -> Coin;
      DunId ->
	  #dungeon_data{hook_items = HookItems} =
	      dungeon_data:get(DunId),
	  N = list_util:keyfind(1, HookItems, 0),
	  max(Coin, N * Time)
    end.


