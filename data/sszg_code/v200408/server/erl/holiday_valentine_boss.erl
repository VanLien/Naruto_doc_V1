can_skip_combat(#role{m_holiday_valentine_boss =
			  #m_holiday_valentine_boss{times = Time,
						    buy_times = BuyTime,
						    id = Id}}) ->
    case holiday_valentine_boss_data:get_time(Id) of
      {FreeTime, _CanBuyTime} ->
	  AllTime = BuyTime + FreeTime,
	  case Time + 1 < AllTime of
	    true -> true;
	    _ -> {false, lang:get(<<"至少需要挑战过一次才可以跳过战斗"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"该战斗不可跳过"/utf8>>)}
    end.

