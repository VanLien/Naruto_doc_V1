combat(Role = #role{m_holiday_valentine_boss =
			MHValentineBoss = #m_holiday_valentine_boss{times =
									OldTime}},
       Id, FormationType, PosInfo, HallowId) ->
    case check_cond([holiday, time, formation, defend],
		    Role,
		    #{id => Id, formation => FormationType,
		      pos_info => PosInfo, hallows_id => HallowId})
	of
      {ok, DefendList, BFormationType, BFormationLev,
       TarName} ->
	  CombatType = 41,
	  FormationLev = formation_lib:get_formation_lev(Role,
							 FormationType),
	  FightPos = formation_lib:gen_fight_pos(PosInfo,
						 FormationType),
	  AtkGroup0 = combat_lib:gen_fight_objects(Role,
						   FightPos),
	  AtkGroup = sprite_tree:gen_fight_object_type(Role, 33)
		       ++
		       hallows_lib:gen_fight_object(Role, HallowId) ++
			 AtkGroup0,
	  Args = #{on_role_combat_end =>
		       {holiday_valentine_boss, combat_over, [Id]},
		   ext_args => [{is_show_panel, false}],
		   formation =>
		       [{1, FormationType, FormationLev},
			{2, BFormationType, BFormationLev}],
		   target_role_name => TarName},
	  case combat_lib:start_combat(Role, CombatType, AtkGroup,
				       [DefendList], Args)
	      of
	    {ok, _CombatPid} ->
		NewMHValentineBoss =
		    MHValentineBoss#m_holiday_valentine_boss{times =
								 max(0,
								     OldTime -
								       1)},
		Role1 = Role#role{m_holiday_valentine_boss =
				      NewMHValentineBoss},
		push(Role1, 28800),
		Role2 = role_trigger:fire(#evt_valentine_boss{}, Role1),
		case formation:set_sys_formation(Role2, 33,
						 FormationType, PosInfo,
						 HallowId)
		    of
		  {ok, NewRole} -> {ok, NewRole};
		  _ -> {ok, Role2}
		end;
	    {false, Msg} -> {false, Msg};
	    _ -> {false, lang:get(<<"无法发起战斗"/utf8>>)}
	  end;
      {false, Reason} -> {false, Reason}
    end.

-spec combat_over(#role{}, #combat_result{}, #combat{},
		  tuple()) -> {ok, #role{}}.

combat_over(Role = #role{partner_bag =
			     #partner_bag{partner_list = PartnerList}},
	    #combat_result{total_hurt = Dps,
			   hurt_statistics_a = PartnerDpsList,
			   hurt_statistics = HurtStatistics},
	    #combat{target_role_name = TargetName}, Id) ->
    BestPartnerId = case lists:reverse(lists:keysort(2,
						     PartnerDpsList))
			of
		      [{BestPartnerIdTemp, _} | _] -> BestPartnerIdTemp;
		      _ -> 0
		    end,
    {BestPartnerId1, Bid1, Lev1, Star1, UseSkin1} = case
						      lists:keyfind(BestPartnerId,
								    #partner.id,
								    PartnerList)
							of
						      #partner{bid = Bid,
							       lev = Lev,
							       star = Star,
							       use_skin =
								   UseSkin} ->
							  {BestPartnerId, Bid,
							   Lev, Star, UseSkin};
						      _ ->
							  {BestPartnerId, 0, 0,
							   0, 0}
						    end,
    log:save(join,
	     {Role, <<"运营活动"/utf8>>, <<"运营活动_女神试炼"/utf8>>, 1, 0,
	      util:fbin(<<"伤害~w, id~w"/utf8>>, [Dps, Id])}),
    case holiday_valentine_boss_data:get_reward({Id, Dps})
	of
      {DropIdList, BeReward} ->
	  RewardList = case drop_lib:common_drop2(Role,
						  DropIdList)
			   of
			 [{_, DropItems, _, _}] ->
			     [{Bid, Val} || {Bid, _, Val} <- DropItems];
			 _ -> []
		       end,
	  AllReward = RewardList ++ BeReward,
	  push(Role, 28802,
	       {Dps, BestPartnerId1, Bid1, Lev1, Star1, UseSkin1,
		TargetName, HurtStatistics, RewardList, 1}),
	  Gain = format:val_to_gain(AllReward,
				    holiday_valentine_boss),
	  case role_gain:do(Role, Gain) of
	    {ok, GainRole} ->
		log:log_gain(Gain, Role, GainRole, <<"运营活动_女神试炼"/utf8>>,
			     <<"运营活动_女神试炼"/utf8>>),
		{ok, GainRole};
	    _ ->
		lager:error(io_lib:format("运营活动_女神试炼奖励失败玩家:~ts id:~w, 活动唯一id:~w",
					  [Role#role.name, Role#role.id, Id])),
		{ok, Role}
	  end;
      _ ->
	  lager:error(io_lib:format("运营活动_女神试炼奖励失败玩家:~ts id:~w, 活动唯一id:~w "
				    "Dps:~w",
				    [Role#role.name, Role#role.id, Id, Dps])),
	  {ok, Role}
    end.

