buy_time(Role) ->
    case check_buy_cond([holiday, time], Role, #{}) of
      {ok, Loss} ->
	  NewLossList = format:val_to_loss(Loss,
					   holiday_valentine_boss),
	  case role_gain:do(Role, NewLossList) of
	    {ok,
	     LossRole = #role{m_holiday_valentine_boss =
				  MHValentineBoss =
				      #m_holiday_valentine_boss{buy_times =
								    BuyTime,
								times =
								    Time}}} ->
		NewMHValentineBoss =
		    MHValentineBoss#m_holiday_valentine_boss{buy_times =
								 BuyTime + 1,
							     times = Time + 1},
		NewRole = LossRole#role{m_holiday_valentine_boss =
					    NewMHValentineBoss},
		log:log_gain(NewLossList, Role, NewRole,
			     <<"运营活动_女神试炼"/utf8>>, <<"运营活动_女神试炼"/utf8>>),
		push(NewRole, 28800),
		{ok, NewRole};
	    _ -> {false, lang:get(<<"购买资产不足"/utf8>>)}
	  end;
      {false, Reason} -> {false, Reason}
    end.

get_now_id_time(CampId) ->
    Now = date:unixtime(),
    case [{DataId, DataTime}
	  || {DataCampId, DataStartTime, DataEndTime, DataId,
	      DataTime}
		 <- holiday_valentine_boss_data:get_all_id_time(),
	     DataCampId =:= CampId,
	     Now >= date:datetime_to_seconds(DataStartTime),
	     date:datetime_to_seconds(DataEndTime) >= Now]
	of
      [{Id, Time} | _Rest] -> {Id, Time};
      _ -> false
    end.

check_cond([], _Role,
	   _Arg = #{defendlist := DefendList,
		    b_formation_type := BFormationType,
		    b_formation_lev := BFormationLev,
		    tarname := TarName}) ->
    {ok, DefendList, BFormationType, BFormationLev,
