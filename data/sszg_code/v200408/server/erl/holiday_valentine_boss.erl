push(Role = #role{m_holiday_valentine_boss =
		      #m_holiday_valentine_boss{camp_id = RoleCampId, id = Id,
						times = Times,
						buy_times = BuyTimes}},
     Code = 28800) ->
    case holiday_lib:get_open_holiday(Role,
				      [3050, 93050, 993050])
	of
      #holiday{camp_id = RoleCampId} ->
	  case holiday_valentine_boss_data:get_time(Id) of
	    {_FreeTime, CanBuyTime} ->
		sys_conn:pack_send(Code,
				   {Id, Times, CanBuyTime - BuyTimes});
	    _ -> sys_conn:pack_send(Code, {Id, Times, 0})
	  end;
      _ -> skip
    end,
    ok;
