mix_buff([], BuffList) -> BuffList;
mix_buff([{Buff, Num} | Rest], BuffList) ->
    case lists:keyfind(Buff, 1, BuffList) of
      {_, OldNum} ->
	  MaxNumList =
	      monopoly_dungeons_data:get_const(monopoly_buff_max),
	  NewNum = case lists:keyfind(Buff, 1, MaxNumList) of
		     {_, MaxNum} -> min(MaxNum, OldNum + Num);
		     _ -> OldNum + Num
		   end,
	  NewBuffList = lists:keyreplace(Buff, 1, BuffList,
					 {Buff, NewNum}),
	  mix_buff(Rest, NewBuffList);
      _ -> mix_buff(Rest, [{Buff, Num} | BuffList])
    end;
mix_buff(_, BuffList) -> BuffList.

