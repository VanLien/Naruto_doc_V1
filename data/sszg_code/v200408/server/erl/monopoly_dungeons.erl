-spec update_data(#monopoly_dungeons{},
		  ets | dets | all) -> ok.

update_data(G, ets)
    when is_record(G, monopoly_dungeons) ->
    ets:insert(monopoly_dungeons, G);
update_data(G, dets)
    when is_record(G, monopoly_dungeons) ->
    dets:insert(monopoly_dungeons, G);
update_data(G, all)
    when is_record(G, monopoly_dungeons) ->
    ets:insert(monopoly_dungeons, G),
    dets:insert(monopoly_dungeons, G);
update_data(_, _) -> ok.

-spec init_dungeons(tuple()) -> ok.

init_dungeons(Gid) ->
    case catch ets:lookup(monopoly_dungeons, Gid) of
      [] ->
	  NewData = #monopoly_dungeons{id = Gid},
	  update_data(NewData, all),
	  start_link(NewData);
      [MonopolyDungeons = #monopoly_dungeons{}] ->
	  start_link(MonopolyDungeons);
      _ -> ok
    end,
    ok.

