init_boss([], OldStageList) -> OldStageList;
init_boss([{StageId, Id, BaseId} | Rest],
	  OldStageList) ->
    case lists:keyfind(StageId, #dungeons_stage.id,
		       OldStageList)
	of
      DungeonsStage = #dungeons_stage{boss_list = BossList} ->
	  NewHp = unit_monster:get_boss_hp_max(BaseId),
	  DungeonsBoss = #dungeons_boss{id = Id, base_id = BaseId,
					hp = NewHp, max_hp = NewHp},
	  NewBossList = lists:keystore(Id, #dungeons_boss.id,
				       BossList, DungeonsBoss),
	  NewDungeonsStage =
	      DungeonsStage#dungeons_stage{boss_list = NewBossList},
	  NewStageList = lists:keyreplace(StageId,
					  #dungeons_stage.id, OldStageList,
					  NewDungeonsStage),
	  init_boss(Rest, NewStageList);
      _ ->
	  NewHp = unit_monster:get_boss_hp_max(BaseId),
	  DungeonsBoss = #dungeons_boss{id = Id, base_id = BaseId,
					hp = NewHp, max_hp = NewHp},
	  DungeonsStage = #dungeons_stage{id = StageId,
					  boss_list = [DungeonsBoss]},
	  NewStageList = lists:keystore(StageId,
					#dungeons_stage.id, OldStageList,
					DungeonsStage),
	  init_boss(Rest, NewStageList)
    end;
init_boss(_, OldStageList) -> OldStageList.

client_boss(_, [], _, ClientBossList) -> ClientBossList;
client_boss(Id,
	    [#dungeons_boss{id = BossId, hp = Hp, max_hp = MaxHp}
	     | Rest],
	    Develop, ClientBossList) ->
    case monopoly_dungeons_data:get_boss_develop({Id,
						  BossId})
	of
      LimitDevelop
	  when is_integer(LimitDevelop),
	       Develop >= LimitDevelop ->
	  case Hp > 0 of
	    true ->
		client_boss(Id, Rest, Develop,
			    [{BossId, 2, Hp, MaxHp} | ClientBossList]);
	    _ ->
		client_boss(Id, Rest, Develop,
			    [{BossId, 3, Hp, MaxHp} | ClientBossList])
	  end;
      _ ->
	  client_boss(Id, Rest, Develop,
		      [{BossId, 1, Hp, MaxHp} | ClientBossList])
    end;
client_boss(_, _, _, ClientBossList) -> ClientBossList.

