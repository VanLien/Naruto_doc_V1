		 Args = #{formation := FormationType,
			  pos_info := PosInfo, hallows_id := HallowsId}) ->
    case formation:check_formation_pos_info(Role,
					    FormationType, PosInfo, HallowsId,
					    30)
	of
      {false, Reason} -> {false, Reason};
      {ok, []} -> {false, lang:get(<<"至少需要上阵一个英雄"/utf8>>)};
      {ok, _NewPosInfo} -> check_can_combat(Rest, Role, Args)
    end;
check_can_combat([boss | Rest],
		 Role = #role{guild_bag =
				  #guild_bag{id = Gid, name = GName}},
		 Args = #{statge_id := StageId, boos_id := BossId}) ->
    case get_monopoly_dungeons(Gid) of
      #monopoly_dungeons{stage_list = StageList,
			 buffs = BuffList} ->
	  case lists:keyfind(StageId, #dungeons_stage.id,
			     StageList)
	      of
	    #dungeons_stage{boss_list = BossList,
			    develop = Develop} ->
		case monopoly_dungeons_data:get_boss_develop({StageId,
							      BossId})
		    of
		  LimitDevelop
		      when is_integer(LimitDevelop),
			   Develop >= LimitDevelop ->
		      case lists:keyfind(BossId, #dungeons_boss.id, BossList)
			  of
			#dungeons_boss{hp = 0, max_hp = MaxHp,
				       base_id = BossBaseId} ->
			    NewBossList = [1
					   || #dungeons_boss{hp = 0}
						  <- BossList],
			    [FollowId] =
				monopoly_dungeons_data:get_const(monopoly_follow_combat_id),
			    case length(NewBossList) =:= length(BossList) of
			      true when FollowId =:= BossId ->
				  check_can_combat(Rest, Role,
						   Args#{hp => MaxHp,
							 base_id => BossBaseId,
							 guild_id => Gid,
							 buff => BuffList,
							 guild_name => GName});
			      _ -> {false, lang:get(<<"Boss已被击败"/utf8>>)}
			    end;
			#dungeons_boss{base_id = BossBaseId, hp = Hp} ->
			    check_can_combat(Rest, Role,
					     Args#{hp => Hp,
						   base_id => BossBaseId,
						   guild_id => Gid,
						   buff => BuffList,
						   guild_name => GName});
			_ -> {false, lang:get(<<"没有该Boss"/utf8>>)}
		      end;
		  _ -> {false, lang:get(<<"该Boss还没解锁"/utf8>>)}
		end;
	    _ -> {false, lang:get(<<"没有该Boss"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"你没有公会,不能挑战"/utf8>>)}
    end;
