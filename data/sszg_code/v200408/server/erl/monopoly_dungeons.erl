combat(StageId, BossId, FormationType, PosInfo,
       HallowsId, Role = #role{lev = Lev}) ->
    case check_can_combat([holiday, formation, boss], Role,
			  #{statge_id => StageId, boos_id => BossId,
			    formation => FormationType, pos_info => PosInfo,
			    hallows_id => HallowsId})
	of
      {false, Reason} -> {false, Reason};
      {Hp, BossBaseId, Gid, CombatBuff, GName} ->
	  case combat_loss(Role) of
	    {ok, Loss, LossRole} ->
		CombatType = 105,
		FormationLev = formation_lib:get_formation_lev(LossRole,
							       FormationType),
		FightPos = formation_lib:gen_fight_pos(PosInfo,
						       FormationType),
		AtkGroup0 = combat_lib:gen_fight_objects(LossRole,
							 FightPos),
		AtkGroup1 = [combat_lib:add_base_attr(FO, CombatBuff)
			     || FO <- AtkGroup0],
		AtkGroup2 = [add_main_partner_skill(FO, StageId)
			     || FO <- AtkGroup1],
		AtkGroup = sprite_tree:gen_fight_object(LossRole) ++
			     hallows_lib:gen_fight_object(LossRole, HallowsId)
			       ++ AtkGroup2,
		#unit_data{formation = {BFormationType, BFormationLev},
			   name = TarName} =
		    unit_data:get(BossBaseId),
		Args = #{on_role_combat_end =>
			     {monopoly_dungeons, combat_over,
			      [{StageId, BossId, Gid, GName}]},
			 ext_args => [{is_show_panel, false}],
			 formation =>
			     [{1, FormationType, FormationLev},
			      {2, BFormationType, BFormationLev}],
			 target_role_name => TarName},
		case unit_monster:gen_fight_objects(Lev, BossBaseId) of
		  [] -> {false, lang:get(<<"怪物配置有问题"/utf8>>)};
		  [DefendList | _] ->
		      NewDefendList = get_new_hp(DefendList, Hp, []),
		      case combat_lib:start_combat(LossRole, CombatType,
						   AtkGroup, [NewDefendList],
						   Args)
			  of
			{ok, _CombatPid} ->
			    log:save(join,
				     {LossRole, <<"功能玩法"/utf8>>,
				      <<"圣夜奇境Boss"/utf8>>}),
			    log:log_gain(Loss, Role, LossRole,
					 <<"圣夜奇境Boss"/utf8>>, <<"道具消耗"/utf8>>),
			    case formation:set_sys_formation(LossRole, 30,
							     FormationType,
							     PosInfo, HallowsId)
				of
			      {ok, NewRole} ->
				  TriggerRole =
				      role_trigger:fire(#evt_monopoly_dungeon{},
							NewRole),
				  {ok, TriggerRole};
			      _ ->
				  TriggerRole =
				      role_trigger:fire(#evt_monopoly_dungeon{},
							LossRole),
				  {ok, TriggerRole}
			    end;
			{false, Msg} -> {false, Msg};
			_ -> {false, lang:get(<<"无法发起剧情副本战斗"/utf8>>)}
		      end
		end;
	    {false, Reason} -> {false, Reason};
	    _ -> {false, lang:get(<<"发起挑战失败"/utf8>>)}
	  end
    end.

