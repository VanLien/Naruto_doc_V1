do_handle(RTypeList, Role, Args) ->
    do_handle(RTypeList, Role, Args, #rank_rc.val1).

do_handle([], _Role, _Args, _ValPos) -> ok;
do_handle([RType | T], Role, Args, ValPos) ->
    do_handle(RType, Role, Args, ValPos),
    do_handle(T, Role, Args, ValPos);
do_handle(RType, Role, Args, ValPos) ->
    CheckRtn = case rank_cond:check(RType, Role, Args) of
		 true -> {true, Args};
		 {true, RtnArgs} -> {true, RtnArgs};
		 False -> False
	       end,
    case CheckRtn of
      {true, NArgs} ->
	  case rank_convert:do(RType, Role, NArgs) of
	    {ok, RankRcs = [_ | _]} ->
		[in_rank(RType, element(ValPos, RankRc), RankRc)
		 || RankRc <- RankRcs];
	    {ok, RankRc} when is_record(RankRc, rank_rc) ->
		Value = element(ValPos, RankRc),
		in_rank(RType, Value, RankRc);
	    _ -> skip
	  end;
      _ -> skip
    end,
    ok.

in_rank(Type, Value, RankRc) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidrank_listener166, _,
       {__Levelrank_listener166, __Tracesrank_listener166}}
	  when __Levelrank_listener166 band 128 /= 0 orelse
		 __Tracesrank_listener166 /= [] ->
	  lager:do_log(debug,
		       [{module, rank_listener}, {function, in_rank},
			{line, 166}, {pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("rank listen in rank ~w, ~w",
				     [Type, Value]),
		       none, 4096, 128, __Levelrank_listener166,
		       __Tracesrank_listener166, lager_event,
		       __Pidrank_listener166);
      _ -> ok
    end,
    #rank_cfg{exit_rank = ExitRank, num = _Max,
	      min_val = MinVal} =
	rank_zone:cfg(Type),
    case Value >= MinVal of
      true ->
	  Id = element(3, RankRc),
	  in_rank(Type, Id, Value, RankRc);
      false when ExitRank =:= 1 ->
	  exit_rank(Type, element(3, RankRc));
      _ -> ok
    end.

exit_rank(Type, Id) ->
    rank_zone:cast(Type, {exit_rank, Type, Id}).

in_rank(Type, Id, Value, RankRc) ->
    rank_zone:cast(Type,
		   {in_rank, Type, Id, Value, RankRc}).

