-spec login(#role{}) -> ok | {ok, #role{}}.

login(_Role) ->
    put(rank_check_idx, 0),
    role:set_ms_timer(rank_timer, util:rand(30000, 90000),
		      {rank_listener, rank_check, []}),
    ok.

-spec rank_check(#role{}) -> ok | {ok, #role{}}.

rank_check(Role) ->
    role:set_ms_timer(rank_timer, 200000,
		      {rank_listener, rank_check, []}),
    Idx = put(rank_check_idx, get(rank_check_idx) + 1),
    do_rank_check(Role, Idx, Idx rem 2 + 1),
    ok.

do_rank_check(Role, 0, _Idx) ->
    do_handle([], Role, 1),
    handle(power, Role, 1),
    handle(partner_power, Role, 1),
    handle(hallows, Role, 1),
    days_rank_check(Role);
do_rank_check(Role, _, _Idx) ->
    handle(partner_power, Role, 1),
    days_rank_check(Role),
    ok.

days_rank_check(Role) ->
    handle(days_star, Role, 1),
    Count = var:get_var(Role, acc, 2050, 0),
    handle(days_adventure, Role, #{count => Count}),
    ok.

