		PreId :: non_neg_integer() |
			 [non_neg_integer()]) -> #role{}.

open_next(Role, []) -> Role;
open_next(Role, [PreId | Rest]) ->
    NRole = open_next(Role, PreId), open_next(NRole, Rest);
