-spec gm_accept(#role{}, Id :: pos_integer()) -> {ok,
						  #role{}} |
						 {false, binary()}.

gm_accept(Role = #role{m_feat =
			   #m_feat{doing = Quests}},
	  Id) ->
    case lists:keyfind(Id, #quest.id, Quests) of
      false ->
	  NRole = do_calc_can_do(add, Role, feat_data:get(Id),
				 push),
	  {ok, NRole};
      _ -> {false, util:fbin("当前已接受成就Id:~w", [Id])}
    end.

-spec gm_del(#role{}, Id :: pos_integer()) -> {ok,
					       #role{}}.

gm_del(Role = #role{m_feat =
			MFeat = #m_feat{doing = Quests}},
       Id) ->
    NewQuests = lists:keydelete(Id, #quest.id, Quests),
    NRole = Role#role{m_feat =
			  MFeat#m_feat{doing = NewQuests}},
    {ok, NRole}.

init() -> #m_feat{}.

-spec login(#role{}) -> {ok, #role{}}.

login(Role) ->
    Role1 = #role{m_feat =
		      MFeat = #m_feat{doing = Quests}} =
		overdue(Role),
    Quests1 = quest_revise:do_list(Role1, feat, Quests),
    {NewQuests,
     NRole = #role{m_feat = #m_feat{finish = FinL}}} =
	quest:load_quest(Quests1, [], feat, Role1),
    NewRole = flush(NRole#role{m_feat =
				   MFeat#m_feat{doing = NewQuests,
						finish = FinL}},
		    not_push),
    {ok, NewRole}.

-spec flush(#role{}, push | not_push) -> #role{}.

flush(Role, Push) ->
    NRole = calc_can_do(feat_data:list(), Role, Push),
    NRole.

-spec level_up(#evt_levup{}, #role{}) -> #role{}.

level_up(#evt_levup{old_lev = OldLev, lev = Lev},
	 Role) ->
    do_level_up(OldLev, Lev, Role).

do_level_up(OldLev, Lev, Role) when Lev >= OldLev ->
    NRole = calc_can_do(feat_data:lev(OldLev), Role, push),
    do_level_up(OldLev + 1, Lev, NRole);
do_level_up(_OldLev, _Lev, Role) -> Role.

