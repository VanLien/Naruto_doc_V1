	    #quest_data{commit_rewards = RewardsCfg} ->
		Rewards = format:val_to_gain(RewardsCfg, make_feat),
		case role_gain:do_notice(Role, Rewards,
					 #gain_loss_opts{type = 1})
		    of
		  {ok,
		   GainRole = #role{m_feat =
					MFeat = #m_feat{doing = DoL1,
							finish = FinL1}}} ->
		      NewDoL = lists:keydelete(Id, #quest.id, DoL1),
		      FTime = date:unixtime(),
		      NewMFeat = MFeat#m_feat{doing = NewDoL,
					      finish = [{Id, FTime} | FinL1]},
		      NewRole = GainRole#role{m_feat = NewMFeat},
		      log:log_gain(Rewards, Role, NewRole, <<"成就"/utf8>>,
				   util:fbin("领取成就奖励:~w", [Id])),
		      {ok, NewRole};
		  {false, #gain{msg = Msg}} -> {false, Msg};
		  _ -> {false, lang:get(<<"无法领取成就奖励"/utf8>>)}
		end;
	    _ -> {false, lang:get(<<"成就基础数据不存在"/utf8>>)}
	  end;
      #quest{finish = 0} ->
	  {false, lang:get(<<"该成就未完成，无法领取奖励"/utf8>>)};
      false ->
	  case lists:keyfind(Id, 1, FinL) of
	    false -> {false, lang:get(<<"成就不存在"/utf8>>)};
	    _ -> {false, lang:get(<<"奖励已领取"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"成就不存在"/utf8>>)}
    end.

pre_quest_check(all, [], _Finished) -> true;
pre_quest_check(one, [], _Finished) -> false;
pre_quest_check(one = Label, [H | T], Finished) ->
    case lists:keyfind(H, 1, Finished) of
      {H, _} -> true;
      _ -> pre_quest_check(Label, T, Finished)
    end;
pre_quest_check(all = Label, [H | T], Finished) ->
    case lists:keyfind(H, 1, Finished) of
      false -> false;
      _ -> pre_quest_check(Label, T, Finished)
    end.


