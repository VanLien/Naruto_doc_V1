do_calc_can_do([], Role, _Data, _Push) -> Role;
do_calc_can_do([Label | T], Role, Data, Push) ->
    case do_calc_can_do(Label, Role, Data, Push) of
      true -> do_calc_can_do(T, Role, Data, Push);
      {ok, NRole} -> do_calc_can_do(T, NRole, Data, Push);
      _ -> Role
    end;
do_calc_can_do(finish,
	       #role{m_feat = #m_feat{finish = FinL, overdue = OverL}},
	       #quest_data{id = Id}, _Push) ->
    lists:keyfind(Id, 1, FinL) =:= false andalso
      lists:member(Id, OverL) =:= false;
do_calc_can_do(doing,
	       #role{m_feat = #m_feat{doing = DoL}},
	       #quest_data{id = Id}, _Push) ->
    lists:keyfind(Id, #quest.id, DoL) =:= false;
do_calc_can_do(lev, #role{lev = Lev},
	       #quest_data{lev = MinLev}, _Push) ->
    Lev >= MinLev;
do_calc_can_do(pre_quest,
	       #role{m_feat = #m_feat{finish = FinL}},
	       #quest_data{pre_quest = PreId}, _Push) ->
    case PreId of
      [0 | PreList] -> pre_quest_check(all, PreList, FinL);
      PreList = [_ | _] ->
	  pre_quest_check(one, PreList, FinL);
      PreId when is_integer(PreId) andalso PreId > 0 ->
	  pre_quest_check(one, [PreId], FinL);
      _ -> true
    end;
do_calc_can_do(condition, Role,
	       #quest_data{condition = Conds}, _Push) ->
    role_cond:check(Conds, Role) =:= true;
do_calc_can_do(add,
	       Role = #role{m_feat = MFeat = #m_feat{doing = DoL}},
	       #quest_data{id = Id, pre_quest = PreQ,
			   progress = Progress, val_from_prev = ValFromPrev,
			   end_time = EndT},
	       Push) ->
    Progress0 = get_val_from_prev(ValFromPrev, Progress,
				  PreQ),
    Progress1 = quest_prog_init:do(Role, Progress0, Id),
    Finish = case [false
		   || #quest_progress{finish = 0} <- Progress1]
		 of
	       [] -> 1;
	       _ -> 0
	     end,
    {NewProgress, Role1} = quest:load_progress(Progress1,
					       feat, Id, [], Role),
    NewEndT = case EndT > 0 of
		true -> date:unixtime(zero) + EndT;
		_ -> 0
	      end,
    NewQuest = #quest{id = Id, finish = Finish,
		      progress = NewProgress, end_time = NewEndT},
    NRole = Role1#role{m_feat =
			   MFeat#m_feat{doing = [NewQuest | DoL]}},
    case Push of
      push -> push_prog(NRole, [NewQuest]);
      _ -> skip
    end,
    {ok, NRole}.

get_val_from_prev(1, Progs, PreQ)
    when is_integer(PreQ) andalso PreQ > 0 ->
    case feat_data:get(PreQ) of
      #quest_data{progress = PreProgs}
	  when length(Progs) =:= length(PreProgs) ->
	  do_get_val_from_prev(Progs, PreProgs, []);
      _ -> Progs
    end;
get_val_from_prev(Bool = 1, Progs, [PreQ]) ->
    get_val_from_prev(Bool, Progs, PreQ);
get_val_from_prev(_ValFromPrev, Progs, _) -> Progs.

do_get_val_from_prev([], [], Progs) ->
    lists:reverse(Progs);
do_get_val_from_prev([Prog | T1],
		     [#quest_progress{target_val = TarVal} | T2], Progs) ->
    do_get_val_from_prev(T1, T2,
			 [Prog#quest_progress{value = TarVal} | Progs]).

do_reward(Role = #role{m_feat =
