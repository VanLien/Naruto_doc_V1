-spec push(#role{}, pos_integer()) -> {ok, #role{}} |
				      {false, string()}.

push(Role = #role{m_training_camp =
		      #m_training_camp{finish_id = Ids}},
     Code = 27600) ->
    LowLevels = [Id
		 || {Id, 1} <- training_camp_data:get_low_level()],
    Flag = case LowLevels -- Ids of
	     [] -> 1;
	     _ -> 0
	   end,
    role:pack_send(Role, Code, {Ids, Flag}),
    ok;
push(_, _) -> ok.

-spec enter(#role{}, pos_integer()) -> {ok, boolean(),
					#role{}} |
				       {false, string()}.

enter(Role = #role{m_training_camp =
		       TrainingCamp = #m_training_camp{first_id = FirstIds,
						       formation_id =
							   FormationId}},
      Id) ->
    case check_cond([lev, unlock], Id, Role, #{}) of
      ok ->
	  {Flag, NewFirstIds} = case lists:member(Id, FirstIds) of
				  true -> {0, FirstIds};
				  _ -> {1, [Id | FirstIds]}
				end,
	  NewTrainingCamp = TrainingCamp#m_training_camp{first_id
							     = NewFirstIds},
	  NewRole = Role#role{m_training_camp = NewTrainingCamp},
	  case Flag =:= 1 of
	    true ->
		CampName = case training_camp_data:get_name(Id) of
			     undefined -> lang:get(<<"训练营"/utf8>>);
			     Name -> Name
			   end,
		log:save(join,
			 {NewRole, <<"新手训练营"/utf8>>,
			  util:fbin(<<"进入训练_~ts"/utf8>>, [CampName])});
	    _ -> ok
	  end,
	  FormationFlag = case lists:member(Id, FormationId) of
			    true -> 1;
			    _ -> 0
			  end,
	  {ok, Flag, FormationFlag, NewRole};
      {false, Reason} -> {false, Reason}
    end.

-spec train(#role{}, pos_integer(), pos_integer(),
	    list()) -> {ok, #role{}} | {false, string()}.

train(Role = #role{lev = Lev}, Id, FormationType,
      PosInfo) ->
    case check_cond([lev, unlock, formation, pos,
		     required_partner, partner],
		    Id, Role, #{formation => FormationType, pos => PosInfo})
	of
      ok ->
	  case get_atk_defend(PosInfo, Id, Lev, FormationType) of
	    {AtkGroup, {BFormationType, TarName, DefendList}} ->
		CombatArgs = #{on_role_combat_end =>
				   {training_camp, combat_over, [Id]},
			       formation =>
				   [{1, FormationType, 1},
				    {2, BFormationType, 1}],
			       target_role_name => TarName,
			       ext_args => [{is_show_panel, false}]},
		case combat_lib:start_combat(Role, 36, AtkGroup,
					     [DefendList], CombatArgs)
		    of
		  {ok, _CombatPid} -> ok;
		  {false, Msg} -> {false, Msg};
		  _ -> {false, lang:get(<<"训练失败"/utf8>>)}
		end;
	    _ -> {false, lang:get(<<"没有对应怪物"/utf8>>)}
	  end;
      {false, Reason} -> {false, Reason}
    end.

