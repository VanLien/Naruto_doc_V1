combat_over(Role = #role{pid = Pid,
			 m_training_camp =
			     #m_training_camp{finish_id = FinishIds}},
	    #combat_result{result = Result}, #combat{}, Id) ->
    case lists:member(Id, FinishIds) of
      true -> {ok, Role};
      _ ->
	  CampName = case training_camp_data:get_name(Id) of
		       undefined -> lang:get(<<"训练营"/utf8>>);
		       Name -> Name
		     end,
	  log:save(join,
		   {Role, <<"新手训练营"/utf8>>,
		    util:fbin(<<"开始挑战_~ts"/utf8>>, [CampName])}),
	  case Result of
	    1 ->
		log:save(task,
			 {Role, 0, Id, CampName, 100, <<"新手训练营"/utf8>>,
			  <<"战斗胜利"/utf8>>}),
		role:apply(async, Pid, {training_camp, reward, [Id]}),
		{ok, Role};
	    _ ->
		log:save(task,
			 {Role, 0, Id, CampName, 100, <<"新手训练营"/utf8>>,
			  <<"战斗失败"/utf8>>}),
		{ok, Role}
	  end
    end.

