    case get_defend(Id, Lev) of
      {BFormationType, TarName, DefendList} ->
	  case get_atk(PosInfo, Lev, [], FormationType) of
	    AtkGroup when is_list(AtkGroup) ->
		{AtkGroup, {BFormationType, TarName, DefendList}};
	    {false, Reason} -> {false, Reason}
	  end;
      {false, Reason} -> {false, Reason}
    end.

