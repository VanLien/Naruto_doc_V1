reward(Role = #role{m_training_camp =
			TrainingCamp = #m_training_camp{finish_id = FinishIds}},
       Id) ->
    case training_camp_data:get_reward(Id) of
      RewardList when is_list(RewardList) ->
	  Gain = format:val_to_gain(RewardList, training_camp),
	  case role_gain:do_notice(Role, Gain) of
	    {ok, GainRole} ->
		NewFinishIds = [Id | FinishIds],
		NewTrainingCamp = TrainingCamp#m_training_camp{finish_id
								   =
								   NewFinishIds},
		NewRole = GainRole#role{m_training_camp =
					    NewTrainingCamp},
		log:log_gain(Gain, Role, GainRole, <<"新手训练营"/utf8>>,
			     <<"通关奖励"/utf8>>),
		push(NewRole, 27600),
		{ok, NewRole};
	    _ -> {ok, Role}
	  end;
      _ -> {ok, Role}
    end.

check_cond([], _, _, _) -> ok;
check_cond([lev | Rest], Id, Role = #role{lev = Lev},
	   Args) ->
    LevLimit =
	training_camp_data:get_const(training_camp_lev_limit),
    case Lev >= LevLimit of
      true -> check_cond(Rest, Id, Role, Args);
      _ -> {false, lang:get(<<"你的等级不够"/utf8>>)}
    end;
check_cond([unlock | Rest], Id,
	   Role = #role{m_training_camp =
			    #m_training_camp{finish_id = Ids}},
	   Args) ->
    case training_camp_data:get_unlock_id(Id) of
      [] -> check_cond(Rest, Id, Role, Args);
      LockIds when is_list(LockIds) ->
	  case LockIds -- Ids of
	    [] -> check_cond(Rest, Id, Role, Args);
	    _ -> {false, lang:get(<<"该训练内容还未解锁"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"没有该训练内容"/utf8>>)}
    end;
check_cond([formation | Rest], Id, Role,
	   Args = #{formation := FormationType}) ->
    case training_camp_data:get_formation_type(Id) of
      {0, FormationType} -> check_cond(Rest, Id, Role, Args);
      {0, _} -> {false, lang:get(<<"不能选择该阵法"/utf8>>)};
      {1, _} -> check_cond(Rest, Id, Role, Args);
      _ -> {false, lang:get(<<"没有该阵法类型"/utf8>>)}
    end;
check_cond([pos | Rest], Id, Role,
	   Args = #{pos := PosInfo}) ->
    case PosInfo of
      [] -> {false, lang:get(<<"至少要上阵一个英雄"/utf8>>)};
      _ ->
	  AllPos = [Pos || {Pos, _} <- PosInfo],
	  case erlang:length(AllPos) =:=
		 erlang:length(lists:usort(AllPos))
	      of
	    true ->
		case training_camp_data:get_ban_pos(Id) of
		  BanPos when is_list(BanPos) ->
		      case length(AllPos -- BanPos) =:= length(AllPos) of
			true -> check_cond(Rest, Id, Role, Args);
			_ -> {false, lang:get(<<"英雄上阵了被禁止的位置"/utf8>>)}
		      end;
		  _ -> check_cond(Rest, Id, Role, Args)
		end;
	    _ -> {false, lang:get(<<"同一个位置上不能上阵多个英雄"/utf8>>)}
	  end
    end;
check_cond([required_partner | Rest], Id, Role,
	   Args = #{pos := PosInfo}) ->
    case training_camp_data:get_required_partner(Id) of
      RequiredPartner when is_list(RequiredPartner) ->
	  RequiredIds = [RId || {RId, _} <- RequiredPartner],
	  RoleIds = [RolePId || {_, RolePId} <- PosInfo],
	  case RequiredIds -- RoleIds of
	    [] ->
		check_cond(Rest, Id, Role,
			   Args#{required_ids => RequiredIds});
	    _ -> {false, lang:get(<<"有必选的英雄没有上阵"/utf8>>)}
	  end;
      _ ->
	  check_cond(Rest, Id, Role, Args#{required_ids => []})
    end;
check_cond([partner | Rest], Id, Role,
	   Args = #{pos := PosInfo,
		    required_ids := RequiredIds}) ->
    RoleIds = [RolePId || {_, RolePId} <- PosInfo],
    case training_camp_data:get_partner(Id) of
      SelectList when is_list(SelectList) ->
	  AllIds = SelectList ++ RequiredIds,
	  case RoleIds -- AllIds of
	    [] ->
		case SelectList of
		  [] -> check_cond(Rest, Id, Role, Args);
		  _ ->
		      case length(SelectList -- RoleIds) < length(SelectList)
			  of
			true -> check_cond(Rest, Id, Role, Args);
			_ -> {false, lang:get(<<"请至少在选择框选择一名英雄上阵"/utf8>>)}
		      end
		end;
	    _ -> {false, lang:get(<<"有英雄不可上阵"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"没有可上阵的英雄"/utf8>>)}
    end;
check_cond(_, _, _, _) ->
    {false, lang:get(<<"参数错误"/utf8>>)}.

