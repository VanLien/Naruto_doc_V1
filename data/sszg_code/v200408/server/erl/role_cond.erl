comp(ue, Val, TargetVal) -> Val =/= TargetVal;
comp(eq, Val, TargetVal) -> Val =:= TargetVal;
comp(lt, Val, TargetVal) -> Val < TargetVal;
comp(gt, Val, TargetVal) -> Val > TargetVal;
comp(le, Val, TargetVal) -> Val =< TargetVal;
comp(ge, Val, TargetVal) -> Val >= TargetVal;
comp(include, L, TargetVal) ->
    lists:member(TargetVal, L);
comp(not_in, L, TargetVal) ->
    lists:member(TargetVal, L) =:= false.

msg(Msg, ue, Val) ->
    util:fbin(lang:get(<<"~ts，必须不等于~w"/utf8>>), [Msg, Val]);
msg(Msg, eq, Val) ->
    util:fbin(lang:get(<<"~ts，必须等于~w"/utf8>>), [Msg, Val]);
msg(Msg, lt, Val) ->
    util:fbin(lang:get(<<"~ts，必须小于~w"/utf8>>), [Msg, Val]);
msg(Msg, gt, Val) ->
    util:fbin(lang:get(<<"~ts，必须大于~w"/utf8>>), [Msg, Val]);
msg(Msg, le, Val) ->
    util:fbin(lang:get(<<"~ts，必须小于等于~w"/utf8>>),
	      [Msg, Val]);
msg(Msg, ge, Val) ->
    util:fbin(lang:get(<<"~ts，必须大于等于~w"/utf8>>),
	      [Msg, Val]);
msg(Msg, include, _Val) -> Msg;
msg(Msg, not_in, _Val) -> Msg.

rtn(_Cond, true, _Msg) -> true;
rtn(Cond = #condition{}, false, Msg) ->
    case Cond#condition.msg =:= <<>> of
      true -> {false, Cond#condition{msg = Msg}};
      false -> {false, Cond}
    end;
rtn(Cond, false, _Msg) -> {false, Cond}.


