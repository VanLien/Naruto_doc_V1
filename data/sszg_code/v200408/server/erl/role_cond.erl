-spec check(CondList, #role{}) -> true |
				  {false, CondFalse} when CondList ::
							      [#condition{}],
							  CondFalse ::
							      #condition{}.

check([], _Role) -> true;
check([C | T], Role) ->
    case check(C, Role) of
      true -> check(T, Role);
      {false, Cond} -> {false, Cond}
    end;
check({Label, Op, Val, Msg}, Role) ->
    check(#condition{label = Label, op = Op, val = Val,
		     msg = Msg},
	  Role);
check(Cond = #condition{label = rpc_cooldown,
			val = Val},
      _) ->
    Cooldown = {rpc_cooldown, get(rpc_code)},
    T = date:unixtime(),
    case get(Cooldown) of
      undefined -> put(Cooldown, T), true;
      T0 ->
	  put(Cooldown, T),
	  rtn(Cond, T - T0 < Val, lang:get(<<"发送请求太快"/utf8>>))
    end;
check(Cond = #condition{label = role_in_normal},
      #role{status = Status}) ->
    rtn(Cond, Status =:= 0,
	lang:get(<<"当前状态下无法进行此操作"/utf8>>));
