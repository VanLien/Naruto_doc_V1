do_sync_hurt(BossId,
	     R = #world_boss_role{id = RoleId, hurt = AddHurt}) ->
    RL = get(BossId),
    NewR = case lists:keyfind(RoleId, #world_boss_role.id,
			      RL)
	       of
	     #world_boss_role{hurt = OldHurt} ->
		 R#world_boss_role{hurt = OldHurt + AddHurt};
	     _ ->
		 ets:update_counter(world_boss, BossId,
				    {#world_boss.rnum, 1}),
		 R
	   end,
    NewRL = list_util:add_sort(RL, NewR,
			       [#world_boss_role.hurt], #world_boss_role.id),
    put(BossId, NewRL),
    util:set_ms_timer({check_timer,
		       {push_boss_timer, BossId}},
		      2000, {push_boss, BossId}).

