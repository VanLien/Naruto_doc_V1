load_data([]) -> ok;
load_data([BossId | T]) ->
    case dets:lookup(world_boss, BossId) of
      [B = #world_boss{role_list = RoleList, hp = Hp,
		       ref_time = RefTime}] ->
	  if RefTime > 0 ->
		 util:set_timer({ref_boss_timer, BossId},
				max(20, RefTime - date:unixtime()),
				{ref_boss, BossId});
	     Hp =< 0 ->
		 util:set_timer({boss_reward_timer, BossId}, 60,
				{boss_reward, BossId});
	     true -> pass
	  end,
	  put(BossId, RoleList),
	  ets:insert(world_boss, B#world_boss{role_list = []});
      [] -> init_boss(#world_boss{id = BossId})
    end,
    load_data(T).

