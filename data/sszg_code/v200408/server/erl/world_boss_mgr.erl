		     {fun (R = #role{m_boss =
					 #m_boss{world_remind = RemindL}}) ->
			      case lists:member(BossId, RemindL) of
				true ->
				    notice_below:send(R, world_boss,
						      [{1, BossId}], []),
				    ok;
