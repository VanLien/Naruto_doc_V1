loop_daily_zero_hour(zone, WeekNum) ->
    holiday_mgr:zero(),
    arena_champion_mgr:zero_update(),
    arena_cluster_champion_mgr:zero_update(),
    replay_hall_mgr:zero_update(WeekNum),
    notify(0),
    ok;
loop_daily_zero_hour(center, _WeekNum) -> ok;
loop_daily_zero_hour(_SrvType, _WeekNum) -> ok.

loop_pm_per_hour(zone, 6) -> notify(6);
loop_pm_per_hour(zone, 18) -> notify(18);
loop_pm_per_hour(_SrvType, _) -> pass.

loop_five(zone, _WeekNum) -> notify(5);
loop_five(center, 1) -> ok;
loop_five(_, _WeekNum) -> ok.

notify(Clock) ->
    role_group:pack_send(world, 10994, {Clock}), ok.


