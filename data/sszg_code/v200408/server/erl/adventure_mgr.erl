calc_time() ->
    OpenTime = 1563724800,
    Now = date:unixtime(),
    StartTime = case Now > OpenTime of
		  true ->
		      OpenTime +
			(Now - OpenTime) div (86400 * 2) * (86400 * 2);
		  _ -> OpenTime
		end,
    {StartTime, StartTime + 86400 * 2}.

