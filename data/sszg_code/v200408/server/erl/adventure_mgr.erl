call(Info) ->
    case catch gen_server:call(adventure_mgr, Info, 10000)
	of
      {'EXIT', _Call_Err} ->
	  case {whereis(lager_event), whereis(lager_event),
		lager_config:get({lager_event, loglevel}, {0, []})}
	      of
	    {undefined, undefined, _} ->
		fun () -> {error, lager_not_running} end();
	    {undefined, _, _} ->
		fun () -> {error, {sink_not_configured, lager_event}}
		end();
	    {__Pidadventure_mgr47, _,
	     {__Leveladventure_mgr47, __Tracesadventure_mgr47}}
		when __Leveladventure_mgr47 band 8 /= 0 orelse
		       __Tracesadventure_mgr47 /= [] ->
		lager:do_log(error,
			     [{module, adventure_mgr}, {function, call},
			      {line, 47}, {pid, pid_to_list(self())},
			      {node, node()}
			      | lager:md()],
			     io_lib:format("call_pid:~w req:~w timeout:~w get_stacktrace:~w",
					   [adventure_mgr, Info, 10000,
					    erlang:get_stacktrace()]),
			     none, 4096, 8, __Leveladventure_mgr47,
			     __Tracesadventure_mgr47, lager_event,
			     __Pidadventure_mgr47);
	    _ -> ok
