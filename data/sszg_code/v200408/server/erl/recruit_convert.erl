convert(Role = #role{m_recruit =
			 MRecruit = #m_recruit{convert_state = State}},
	_, 0) ->
    NRole = case State of
	      [{PartnerId, NewBid} | _] ->
		  log:save(partner_convert,
			   {Role,
			    util:fbin("取消置换, 【英雄Id:~w，NewBid:~w】",
				      [PartnerId, NewBid])}),
		  case partner:lock(Role, PartnerId, 2, 0) of
		    {ok, NRoleT} -> NRoleT;
		    _ -> Role
		  end;
	      _ -> Role
	    end,
    {ok,
     NRole#role{m_recruit =
		    MRecruit#m_recruit{convert_state = []}}};
convert(Role = #role{id = RoleId,
		     m_recruit = #m_recruit{convert_state = State}},
	PartnerId, 1) ->
    case State of
      [_ | _] -> {false, lang:get(<<"当前无法进行置换"/utf8>>)};
      _ ->
	  case partner_lib:get_partner(Role, PartnerId) of
	    #partner{camp_type = Type, bid = OldBid, star = Star}
		when Star =:= 4 orelse Star =:= 5 ->
		case lists:member(Type,
				  recruit_high_data:get_const(hero_change))
		    of
		  true ->
		      case check_ids(Role, PartnerId, 1) of
			true ->
			    LossItems = util:if_true(Star =:= 4,
						     recruit_high_data:get_const(hero_change4),
						     recruit_high_data:get_const(hero_change5)),
			    Loss = format:val_to_loss(LossItems, hero_convert),
			    case role_gain:do(Role, Loss,
					      #gain_loss_opts{need_notify_fail_item
								  = true})
				of
			      {false, #loss{msg = Msg}} -> {false, Msg};
			      {ok, NRole, _} ->
				  RandClassL =
				      recruit_high_data:rand_convert_class({Type,
									    Star}),
				  {ClassId, _} = util:rand_list(RandClassL, 2),
				  RandList =
				      recruit_high_data:convert_group_items(ClassId),
				  LimitInfo = limit_info({RoleId, Type}),
				  Stats = stats(Type, Role),
				  DrawTimes = maps:get(draw_times, Stats, 0),
				  CurDrawTimes = DrawTimes + 1,
				  Args = #{class_id => ClassId,
					   cur_times => CurDrawTimes,
					   limit_info => LimitInfo,
					   old_bid => OldBid},
				  Steps = [must_not_in_m_times,
					   hit_must_not_after_m_times, weight],
				  case convert_steps(Steps, RandList, NRole,
						     Args)
				      of
				    {ok,
				     #{new_bid := NewBid,
				       convert_id := ConvertId}} ->
					NStats = Stats#{draw_times =>
							    CurDrawTimes},
					NConvertState = [{PartnerId, NewBid}],
					NRole1 = update_stats(Type, NStats,
							      NConvertState,
							      NRole),
					NewRole = case partner:lock(NRole1,
								    PartnerId,
								    2, 1)
						      of
						    {ok, NRoleT} -> NRoleT;
						    _ -> NRole1
						  end,
					NewLimitInfo =
					    update_limit_info(ConvertId,
							      CurDrawTimes,
							      LimitInfo),
					recruit_mgr:save(NewLimitInfo),
					log:log_gain(Loss, Role, NewRole,
						     <<"英雄置换"/utf8>>,
						     util:fbin("置换[原英雄id:~w, old:~w, new:~w]",
							       [PartnerId,
								OldBid,
								NewBid])),
					NewRole1 =
					    role_trigger:fire([#evt_recruit_convert{}],
							      NewRole),
					{ok, NewRole1};
				    {false, Msg} -> {false, Msg}
				  end
			    end;
			{false, Msg} -> {false, Msg}
		      end;
		  _ -> {false, lang:get(<<"该阵营的英雄无法置换"/utf8>>)}
		end;
	    #partner{} -> {false, lang:get(<<"该星级的英雄无法置换"/utf8>>)};
	    _ -> {false, lang:get(<<"转换的英雄不存在"/utf8>>)}
	  end
    end;
