			   #m_recruit{convert_state = List},
		       partner_bag = #partner_bag{partner_list = PList}}) ->
    {PartnerId, NewBid} = case List of
			    [{PartnerIdT, NewBidT} | _] ->
				{PartnerIdT, NewBidT};
			    _ -> {0, 0}
			  end,
    LockPList = [PId
		 || #partner{id = PId, star = Star} <- PList,
		    Star == 4 orelse Star == 5,
		    check_ids(Role, PId, 1) =/= true],
    sys_conn:pack_send(23214,
		       {PartnerId, NewBid, LockPList}),
    ok.

