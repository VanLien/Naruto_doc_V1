check_ids(Role, PartnerId, LockTypes) ->
    case partner:is_lock(Role, PartnerId, LockTypes) of
      {false, Msg} -> {false, Msg};
      _ ->
	  case partner:check_formation_id(Role, [PartnerId]) of
	    {false, Msg} -> {false, Msg};
	    _ -> true
	  end
    end.

stats(Type,
      #role{m_recruit = #m_recruit{convert_list = List}}) ->
    case lists:keyfind(Type, #recruit_info.group_id, List)
	of
      #recruit_info{stats = Stats} -> Stats;
      _ -> #{draw_times => 0}
    end.

limit_info(Key) ->
    case recruit_mgr:lookup(Key) of
      {ok, Info = #recruit_limit{}} -> Info;
      _ ->
	  Info = #{last_hit_n => 0},
	  #recruit_limit{key = Key, info = Info}
    end.

update_stats(Type, Stats, ConvertState,
	     Role = #role{m_recruit =
			      MRecruit = #m_recruit{convert_list = List}}) ->
    case lists:keyfind(Type, #recruit_info.group_id, List)
	of
      Info = #recruit_info{} ->
	  NewList = lists:keystore(Type, #recruit_info.group_id,
				   List, Info#recruit_info{stats = Stats}),
	  Role#role{m_recruit =
			MRecruit#m_recruit{convert_list = NewList,
					   convert_state = ConvertState}};
      false ->
	  Role#role{m_recruit =
			MRecruit#m_recruit{convert_list =
					       [#recruit_info{group_id = Type,
							      stats = Stats}
						| List],
					   convert_state = ConvertState}}
    end.

update_limit_info(Id, Times,
		  LimitInfo = #recruit_limit{info = Info})
    when Id > 0 ->
    IdLimit = maps:get(Id, Info, #{}),
    NewInfo = Info#{Id => IdLimit#{last_hit_n => Times}},
    LimitInfo#recruit_limit{info = NewInfo};
update_limit_info(_Id, _Times, LimitInfo) -> LimitInfo.

convert_steps([], _RandList, _Role, Args) -> {ok, Args};
convert_steps([weight | T], RandList, _Role,
	      Args = #{class_id := ClassId, old_bid := OldBid}) ->
    DoList1 = case RandList of
		[_ | _] -> RandList;
		_ -> recruit_high_data:convert_group_items(ClassId)
	      end,
    DoList2 = [RandCfg
	       || RandCfg = #{bid := BidT} <- DoList1,
		  BidT =/= OldBid],
    case maps_util:rand(DoList2, weight) of
      #{bid := Bid, id := Id} ->
	  convert_steps(T, RandList, _Role,
			Args#{new_bid => Bid, convert_id => Id});
      _ -> {false, lang:get(<<"没有可以匹配的英雄置换"/utf8>>)}
    end;
convert_steps([must_not_in_m_times | T], RandList,
	      _Role, Args = #{cur_times := CurTimes}) ->
    NewRandList = [Cfg
		   || Cfg = #{must_not_in_m_times := N} <- RandList,
		      N =:= 0 orelse CurTimes > N],
    convert_steps(T, NewRandList, _Role, Args);
convert_steps([hit_must_not_after_m_times | T],
	      RandList, _Role,
	      Args = #{cur_times := CurTimes,
		       limit_info := #recruit_limit{info = LimitInfo}}) ->
    Fun = fun (#{id := Id, hit_must_not_after_m_times := N})
		  when N > 0 ->
		  IdLimit = maps:get(Id, LimitInfo, #{}),
		  HitN = maps:get(last_hit_n, IdLimit, 0),
		  N < CurTimes - HitN;
	      (_) -> true
	  end,
    NewRandList = lists:filter(Fun, RandList),
    convert_steps(T, NewRandList, _Role, Args);
