-spec remove_task_unit(#role{}, list()) -> #role{}.

remove_task_unit(Role, Progs) ->
    {ok, NRole, DelList} = do_remove_task_unit(Progs, Role,
					       []),
    case DelList of
      [] -> skip;
      _ ->
	  ActType = drama_act:act_to_type(remove_obj),
	  Plays = [#drama_play{act_type = ActType,
