create_task_unit(Role, QuestId, Progs, Args) ->
    case do_create_task_unit(Progs, Role, QuestId, Args, [])
	of
      {ok, NRole, []} -> NRole;
      {ok, NRole, PlayObjs} ->
	  send_drama_obj_act(NRole, PlayObjs), NRole
    end.

send_drama_obj_act(_Role, []) -> ok;
send_drama_obj_act(Role, PlayObjs) ->
    ActType = drama_act:act_to_type(create_obj),
    Plays = [#drama_play{act_type = ActType, type = Type,
			 base_id = BaseId, map_bid = MapBid, x = X, y = Y,
			 val = Dir}
	     || #drama_obj{type = Type, base_id = BaseId,
			   map_bid = MapBid, x = X, y = Y, dir = Dir}
		    <- PlayObjs],
    role:pack_send(Role, 11110, {0, Plays}).

do_create_task_unit([], Role, _Quest, _Args, Acc) ->
    {ok, Role, Acc};
do_create_task_unit([Prog | Rest],
		    Role = #role{m_drama =
				     MDrama = #m_drama{obj_list = ObjList}},
		    QuestId, Args, Acc) ->
    case make_task_unit(Prog, Role, QuestId, Args) of
      {ok, DramaObj = #drama_obj{base_id = UnitBaseId}} ->
	  NewObjList = lists:keystore(UnitBaseId,
				      #drama_obj.base_id, ObjList, DramaObj),
	  NRole = Role#role{m_drama =
				MDrama#m_drama{obj_list = NewObjList}},
	  do_create_task_unit(Rest, NRole, QuestId, Args,
			      [DramaObj | Acc]);
      _False ->
	  do_create_task_unit(Rest, Role, QuestId, Args, Acc)
    end;
do_create_task_unit([_ | T], Role, Quest, Args,
		    Plays) ->
    do_create_task_unit(T, Role, Quest, Args, Plays).

