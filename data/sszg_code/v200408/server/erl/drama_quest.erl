		 UnitData = #unit_data{data = DataList}, 0, Role) ->
    case lists:keyfind(time, 1, DataList) of
      {_, {Time, MsgCfg}} ->
	  Msg = case is_list(MsgCfg) of
		  true -> unicode:characters_to_binary(MsgCfg);
		  _ -> MsgCfg
		end,
	  {ok, Msg, Time};
      _ -> click_obj_action(Obj, UnitData, 1, Role)
    end;
