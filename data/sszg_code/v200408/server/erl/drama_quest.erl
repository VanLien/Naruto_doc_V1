						      #role{}} |
						     {false, bitstring()}.

click_obj(ObjBaseId, Action,
	  Role = #role{m_drama = #m_drama{obj_list = ObjList}}) ->
    case lists:keyfind(ObjBaseId, #drama_obj.base_id,
		       ObjList)
	of
      DramaObj = #drama_obj{base_id = BaseId} ->
	  click_obj_action(DramaObj, unit_data:get(BaseId),
			   Action, Role);
      _ ->
	  {false,
	   lang:get(<<"Đơn vị cốt truyện không tồn tại"/utf8>>)}
    end.

