-spec guess_bet(atom(), tuple(), tuple()) -> ok.

guess_bet(StateName, _State,
	  {RoleId, RolePid, ConnPid, BetType, BetVal})
    when StateName =:= score_guess orelse
	   StateName =:= champion_guess ->
    Bet = #champion_bet{bet = CanBet, logs = Logs} =
	      arena_cluster_champion_lib:cluster_get_bet(RoleId),
    GuessLimit =
	arena_cluster_champion_data:get_const(guess_limit),
    case lists:keymember(RoleId, 1, get(guess_list)) of
      _ when BetVal > CanBet ->
	  sys_conn:pack_send(ConnPid, 26204,
			     {0, lang:get(<<"竞猜币不足"/utf8>>), 0, 0, 0});
      _ when BetVal > GuessLimit ->
	  sys_conn:pack_send(ConnPid, 26204,
			     {0, lang:get(<<"竞猜币押注超出上限"/utf8>>), 0, 0, 0});
      false ->
	  Log = case BetType of
		  1 ->
		      put(guess_a_bet, get(guess_a_bet) + BetVal),
		      put(guess_list,
			  [{RoleId, 1, BetVal} | get(guess_list)]),
		      ets:update_counter(arena_cluster_champion_pk,
					 get(guess_roleid),
					 {#champion_pk.a_bet, BetVal}),
		      #champion_bet_log{id = get(guess_id),
					rid = get(guess_roleid), target = 1,
					bet = BetVal};
		  _ ->
		      put(guess_b_bet, get(guess_b_bet) + BetVal),
		      put(guess_list,
			  [{RoleId, 2, BetVal} | get(guess_list)]),
		      ets:update_counter(arena_cluster_champion_pk,
					 get(guess_roleid),
					 {#champion_pk.b_bet, BetVal}),
		      #champion_bet_log{id = get(guess_id),
					rid = get(guess_roleid), target = 2,
					bet = BetVal}
		end,
	  NewBet = Bet#champion_bet{bet = CanBet - BetVal,
				    logs = [Log | Logs]},
	  d_ets_lib:save_ets(arena_cluster_champion_bet, NewBet),
	  sys_conn:pack_send(ConnPid, 26204,
			     {1, lang:get(<<"押注成功"/utf8>>), CanBet - BetVal,
			      BetType, BetVal}),
	  ABetRatio =
	      arena_cluster_champion_mgr:calc_bet_ratio(get(guess_a_bet),
							get(guess_b_bet)),
	  BBetRatio =
	      arena_cluster_champion_mgr:calc_bet_ratio(get(guess_b_bet),
							get(guess_a_bet)),
	  role:apply(async, RolePid,
		     {fun (R) ->
			      log:save(join,
				       {R, <<"功能玩法"/utf8>>,
					<<"跨服冠军赛押注"/utf8>>}),
			      NewR =
				  role_trigger:fire([#evt_arena_cluster_champion_bet{}],
						    R),
			      {ok, NewR}
		      end}),
	  catch cluster_dynamic_group:group_other_cast(1,
						       role_group, pack_send,
						       [world, 26207,
							{get(guess_a_bet),
							 get(guess_b_bet),
							 ABetRatio,
							 BBetRatio}]),
	  role_group:pack_send(world, 26207,
			       {get(guess_a_bet), get(guess_b_bet), ABetRatio,
				BBetRatio});
      _ ->
	  sys_conn:pack_send(ConnPid, 26204,
			     {0, lang:get(<<"已经竞猜过啦"/utf8>>), 0, 0, 0})
    end;
guess_bet(_StateName, _State, Info) ->
