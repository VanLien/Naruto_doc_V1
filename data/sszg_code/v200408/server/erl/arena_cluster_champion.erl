-spec get_and_update_pk(any(), atom(),
			#champion_state{}) -> false | {ok, #champion_pk{}}.

get_and_update_pk(Id, _StateName,
		  #champion_state{step = Step, round = Round,
				  round_status = RoundStatus}) ->
    case arena_cluster_champion_lib:get_pk(Id) of
      {ok, O = #champion_pk{ret = 0}}
	  when RoundStatus =:= 1 ->
	  {ok, arena_cluster_champion_mgr:do_update_pk_info(O)};
      {ok, O = #champion_pk{step = Step, round = Round}}
	  when RoundStatus =:= 3 ->
	  {ok, O#champion_pk{ret = 0}};
      Ret -> Ret
    end.


