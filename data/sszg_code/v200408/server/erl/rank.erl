-spec list(Type :: pos_integer()) -> RankList :: list().

list(Type) ->
    #rank{list = L} = rank_mgr:lookup(Type), L.

-spec idx(Type :: pos_integer(),
	  tuple()) -> non_neg_integer().

-spec idx(Type :: pos_integer(), tuple(),
	  [#rank_rc{}]) -> non_neg_integer().

idx(Type, Key) -> idx(Type, Key, list(Type)).

idx(_Type, _Key, []) -> 0;
idx(_Type, Key, List) ->
    case lists:keyfind(Key, 3, List) of
      #rank_rc{idx = Idx} -> Idx;
      _ -> 0
    end.

