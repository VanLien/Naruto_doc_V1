	   Idx :: pos_integer()) -> {ok, #rank_rc{}} | undefined.

-spec rank(Type :: pos_integer(), Idx :: pos_integer(),
	   [#rank_rc{}]) -> {ok, #rank_rc{}} | undefined.

rank(Type, Idx) -> rank(Type, Idx, list(Type)).

rank(_Type, _Idx, []) -> undefined;
rank(_Type, Idx, List) ->
    case lists:keyfind(Idx, #rank_rc.idx, List) of
      RankRc = #rank_rc{} -> {ok, RankRc};
      _ -> undefined
    end.

-spec get_partners_in_rank(#role{},
			   MinVal :: non_neg_integer()) -> list().

get_partners_in_rank(#role{partner_bag =
			       #partner_bag{partner_list = List}},
		     MinVal) ->
    L1 = util:keys_sort([#partner.star, #partner.quality,
			 #partner.power],
			[P || P <- List, P#partner.power >= MinVal]),
    lists:sublist(L1, 1).

-spec my_rank(any(), list()) -> tuple().

my_rank(Rid, List) ->
    case lists:keyfind(Rid, #rank_rc.id, List) of
      false -> {0, 0, 0, 0};
      #rank_rc{idx = Rank, val1 = Val1, val2 = Val2,
	       val3 = Val3} ->
	  {Rank, Val1, Val2, Val3}
    end.

