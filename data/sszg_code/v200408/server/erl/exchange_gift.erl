				    none, 4096, 8, __Levelexchange_gift73,
				    __Tracesexchange_gift73, lager_event,
				    __Pidexchange_gift73);
		   _ -> ok
		 end,
		 NewRole = set_expire_gift_timer(Role, EId, DiffTime),
		 {ok, NewRole}
	   end;
       DiffTime >= 86400 ->
	   do_gain_expire_gift(Role, EId, ExpireGift, Now);
       true ->
	   case {whereis(lager_event), whereis(lager_event),
		 lager_config:get({lager_event, loglevel}, {0, []})}
	       of
	     {undefined, undefined, _} ->
		 fun () -> {error, lager_not_running} end();
	     {undefined, _, _} ->
		 fun () -> {error, {sink_not_configured, lager_event}}
		 end();
	     {__Pidexchange_gift80, _,
	      {__Levelexchange_gift80, __Tracesexchange_gift80}}
		 when __Levelexchange_gift80 band 8 /= 0 orelse
			__Tracesexchange_gift80 /= [] ->
