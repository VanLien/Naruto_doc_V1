					    [Role#role.name, ExpireGift]),
			      none, 4096, 8, __Levelexchange_gift80,
			      __Tracesexchange_gift80, lager_event,
			      __Pidexchange_gift80);
	     _ -> ok
	   end,
	   del_expire_gift(Role, EId)
    end.

do_gain_expire_gift(Role, EId,
		    ExpireGift = #exchange_expire_gift{base_id = BaseId,
						       bind = Bind, num = Num,
						       reward_time =
							   RewardTime},
		    Now) ->
    ZeroTime = date:unixtime({zero, Now}),
    case ZeroTime =/= RewardTime of
      true ->
	  case gift:open_exchange_expire_gift(Role, BaseId, Bind,
					      Num, EId)
	      of
	    {ok,
	     GiftRole = #role{m_exchange =
				  MExchange = #m_shop{expire_list = List}}} ->
		NewExpireGift =
		    ExpireGift#exchange_expire_gift{reward_time = ZeroTime},
		NewList = lists:keystore(EId, #exchange_expire_gift.eid,
					 List, NewExpireGift),
		NewRole = GiftRole#role{m_exchange =
					    MExchange#m_shop{expire_list =
								 NewList}},
		{ok, NewRole};
	    {false, Msg} -> {false, Msg}
	  end;
      _ -> {false, lang:get(<<"已发放过今日奖励"/utf8>>)}
    end.

del_expire_gift(Role = #role{m_exchange =
				 MExchange = #m_shop{expire_list = List}},
		EId) ->
    NewList = lists:keydelete(EId,
			      #exchange_expire_gift.eid, List),
    NewRole = Role#role{m_exchange =
			    MExchange#m_shop{expire_list = NewList}},
    {ok, NewRole}.

expire_rest_num(#role{m_exchange =
			  #m_shop{expire_list = List}},
		EId) ->
    case lists:keyfind(EId, #exchange_expire_gift.eid, List)
	of
      #exchange_expire_gift{timeout = Timeout} ->
	  Now = date:unixtime(),
	  case Now =< Timeout of
	    true -> date:day_diff(Now, Timeout);
	    false -> 0
	  end;
      _ -> 0
    end.

set_expire_gift_timer(Role, EId, Time) ->
    Timeout = erlang:max(Time, 1) * 1000,
    Timer = #timer{id = {exchange_expire_gift, EId},
		   timeout = Timeout, m = exchange_gift,
		   f = del_expire_gift, a = [EId]},
    role_timer:set(Timer, Role).


