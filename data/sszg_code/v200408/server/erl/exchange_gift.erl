check_expire(#role{m_exchange =
		       #m_shop{expire_list = List}},
	     EId) ->
    case lists:keyfind(EId, #exchange_expire_gift.eid, List)
	of
      false -> ok;
      _ -> {false, lang:get(<<"已拥有该礼包，无法重复使用"/utf8>>)}
    end.

activate_expire(Role = #role{m_exchange =
				 MExchange = #m_shop{expire_list = List}},
		EId, ExpireTime, #item{base_id = BaseId, bind = Bind},
		Num) ->
    Now = date:unixtime(),
    Timeout = Now + ExpireTime,
    ExpireGift = #exchange_expire_gift{eid = EId,
				       base_id = BaseId, bind = Bind, num = Num,
				       timeout = Timeout},
    NewList = lists:keystore(EId, #exchange_expire_gift.eid,
			     List, ExpireGift),
    NewRole = Role#role{m_exchange =
			    MExchange#m_shop{expire_list = NewList}},
    {ok, NewRole}.

zero_flush(Role = #role{m_exchange =
			    #m_shop{expire_list = List}}) ->
    zero_flush_expire_gift(Role, List).

zero_flush_expire_gift(Role, []) -> Role;
zero_flush_expire_gift(Role,
		       [ExpireGift = #exchange_expire_gift{} | Rest]) ->
    case gain_expire_gift(Role, ExpireGift) of
      {ok, NewRole} -> zero_flush_expire_gift(NewRole, Rest);
      _ -> zero_flush_expire_gift(Role, Rest)
    end.

gain_expire_gift(Role,
		 ExpireGift = #exchange_expire_gift{timeout = Timeout,
						    eid = EId}) ->
    Now = date:unixtime(),
    DiffTime = Timeout - Now,
    if DiffTime >= 0 andalso DiffTime < 86400 ->
	   case do_gain_expire_gift(Role, EId, ExpireGift, Now) of
	     {ok, GiftRole} ->
		 NewRole = set_expire_gift_timer(GiftRole, EId,
						 DiffTime),
		 {ok, NewRole};
	     _ ->
		 case {whereis(lager_event), whereis(lager_event),
		       lager_config:get({lager_event, loglevel}, {0, []})}
		     of
		   {undefined, undefined, _} ->
		       fun () -> {error, lager_not_running} end();
		   {undefined, _, _} ->
		       fun () -> {error, {sink_not_configured, lager_event}}
		       end();
		   {__Pidexchange_gift73, _,
		    {__Levelexchange_gift73, __Tracesexchange_gift73}}
		       when __Levelexchange_gift73 band 8 /= 0 orelse
			      __Tracesexchange_gift73 /= [] ->
		       lager:do_log(error,
				    [{module, exchange_gift},
				     {function, gain_expire_gift}, {line, 73},
				     {pid, pid_to_list(self())}, {node, node()}
				     | lager:md()],
				    io_lib:format("[~ts]获取商城特惠时效礼包奖励错误[ExpireGift:~w]",
