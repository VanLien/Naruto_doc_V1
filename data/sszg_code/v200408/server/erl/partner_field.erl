info(Role) ->
    PartnerField = #partner_field{fields = Fields,
				  lev = Lev} =
		       get_partner_field(Role),
    LimitDungeon =
	partner_field_data:get_constant(open_level),
    MaxDunId = dungeon:max_dun_id(Role),
    if MaxDunId >= LimitDungeon, Fields == [] ->
	   NewFields = [{1, 0}],
	   NewPartnerField = PartnerField#partner_field{fields =
							    NewFields},
	   {ok, 0, NewFields,
	    set_partner_field(Role, NewPartnerField)};
       MaxDunId >= LimitDungeon -> {ok, Lev, Fields, Role};
       true ->
	   case dungeon_data:get(LimitDungeon) of
	     #dungeon_data{name = Name} ->
		 Msg = util:fbin(lang:get(<<"助阵需通关~ts解锁"/utf8>>),
				 [Name]),
		 {false, Msg};
	     _ -> {false, lang:get(<<"助阵未开放"/utf8>>)}
	   end
    end.

save_field(Role = #role{partner_bag =
			    #partner_bag{partner_field = PartnerField}},
	   Fields) ->
    case check_field(Role, Fields) of
      false -> {false, lang:get(<<"助阵阵容不合规"/utf8>>)};
      _ ->
	  NRole = set_partner_field(Role,
				    PartnerField#partner_field{fields =
								   Fields}),
	  NRole2 = partner_lib:ref_formation_attr(NRole, 0),
	  {ok, NRole2}
    end.

check_field(_Role, []) -> true;
check_field(Role, [{Pos, PartnerId} | OFields]) ->
    case check_right_field([pos, partner], Role, Pos,
			   PartnerId)
	of
      true -> check_field(Role, OFields);
      _ -> false
    end;
check_field(_Role, _Arg) ->
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidpartner_field60, _,
       {__Levelpartner_field60, __Tracespartner_field60}}
	  when __Levelpartner_field60 band 8 /= 0 orelse
		 __Tracespartner_field60 /= [] ->
	  lager:do_log(error,
		       [{module, partner_field}, {function, check_field},
			{line, 60}, {pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("错误的参数:~w==", [_Arg]), none, 4096, 8,
		       __Levelpartner_field60, __Tracespartner_field60,
		       lager_event, __Pidpartner_field60);
      _ -> ok
    end,
    false.

check_right_field([], _Role, _Pos, _PartnerId) -> true;
check_right_field([pos | Other],
		  Role = #role{partner_bag =
				   #partner_bag{partner_field =
						    #partner_field{fields =
								       Fields}}},
		  Pos, PartnerId) ->
    case lists:keyfind(Pos, 1, Fields) =/= false of
      true -> check_right_field(Other, Role, Pos, PartnerId);
      _ -> false
    end;
check_right_field([partner | _], Role, _Pos,
		  PartnerId) ->
    case partner_lib:get_partner(Role, PartnerId) == false
	   andalso PartnerId =/= 0
	of
      true -> false;
      _ ->
	  List = formation_lib:list_partners(Role),
	  case lists:member(PartnerId, List) of
	    false -> true;
	    _ -> false
	  end
    end;
check_right_field(_, _, _, _) -> false.

-spec field_open(#role{}, pos_integer()) -> {ok,
					     #role{}, pos_integer()} |
					    {false, binary()}.

field_open(Role = #role{lev = Lev}, Pos) ->
    PartnerField = #partner_field{fields = Fields} =
		       get_partner_field(Role),
    case lists:keyfind(Pos, 1, Fields) of
      false ->
	  case partner_field_data:get_pos(Pos) of
	    {_AttrAtom, _Ratio, _LimitLev, val_not_exist} ->
		{ok, Role};
	    {_AttrAtom, _Ratio, LimitLev, Expend}
		when Lev >= LimitLev ->
		Loss = format:val_to_loss(Expend, field_open),
		case role_gain:do(Role, Loss) of
		  {ok, NRole} ->
		      log:log_gain(Loss, Role, NRole, <<"伙伴"/utf8>>,
				   util:fbin("助阵阵位解锁 Pos:~w", [Pos])),
		      NewPartnerField = PartnerField#partner_field{fields =
								       [{Pos, 0}
									| Fields]},
		      {ok, set_partner_field(NRole, NewPartnerField)};
		  {false, #loss{msg = Msg}} -> {false, Msg}
		end;
	    _ -> {false, lang:get(<<"未开放该阵位"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"该阵位已解锁"/utf8>>)}
    end.

-spec field_lev_up(#role{}) -> {ok, #role{}} |
			       {false, binary()}.

field_lev_up(Role) ->
    PartnerField = #partner_field{lev = Lev} =
		       get_partner_field(Role),
    case partner_field_data:get_lev_expend(Lev) of
      L when is_list(L) ->
	  Loss = format:val_to_loss(L, field_open),
	  case role_gain:do(Role, Loss) of
	    {ok, NRole} ->
		log:log_gain(Loss, Role, NRole, <<"伙伴"/utf8>>,
			     util:fbin("助阵升级 Lev:~w", [Lev])),
		NewPartnerField = PartnerField#partner_field{lev =
								 Lev + 1},
		NRole2 = set_partner_field(NRole, NewPartnerField),
		NRole3 = partner_lib:ref_formation_attr(NRole2, 0),
		{ok, Lev + 1,
		 set_partner_field(NRole3, NewPartnerField)};
	    {false, #loss{msg = Msg}} -> {false, Msg}
	  end;
      _ -> {false, lang:get(<<"未开放下一等级"/utf8>>)}
    end.

get_partner_field(#role{partner_bag =
			    #partner_bag{partner_field = PartnerField}}) ->
    PartnerField.

set_partner_field(Role = #role{partner_bag = PBag},
		  PartnerField) ->
    Role#role{partner_bag =
		  PBag#partner_bag{partner_field = PartnerField}}.


