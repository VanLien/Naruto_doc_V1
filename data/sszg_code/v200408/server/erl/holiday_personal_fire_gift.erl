set_ico(#role{m_holiday_personal_fire_gift =
		  #m_holiday_personal_fire_gift{gift_list = []}}) ->
    activity_self:set_activity(804, 0, []);
set_ico(#role{m_holiday_personal_fire_gift =
		  #m_holiday_personal_fire_gift{gift_list = List}}) ->
    Now = date:unixtime(),
    Fun = fun ({Id, _, _, _BuyCount, _, _, EndTimeT},
	       Acc) ->
		  case holiday_personal_fire_gift_data:get_gift_info(Id)
		      of
		    {_, _ChargeId, _, _} when EndTimeT > Now ->
			[EndTimeT | Acc];
		    _ -> Acc
		  end
	  end,
    GList = lists:foldl(Fun, [], List),
    case GList of
      [_ | _] ->
	  EndTime = lists:min(GList),
	  activity_self:set_activity(804, 1, [EndTime]);
      _ -> activity_self:set_activity(804, 0, [])
    end.

-spec push_base_info(#role{}) -> ok.

push_base_info(Role = #role{m_holiday_personal_fire_gift
				=
				#m_holiday_personal_fire_gift{gift_list =
								  GiftList}}) ->
    Fun = fun ({Id, _, _, BuyCount, _, _, EndTime}, Acc) ->
		  case holiday_personal_fire_gift_data:get_gift_info(Id)
		      of
		    {_, _ChargeId, _, _} -> [{EndTime, BuyCount, Id} | Acc];
		    _ -> Acc
		  end
	  end,
    CliInfo = lists:foldl(Fun, [], GiftList),
    set_ico(Role),
    sys_conn:pack_send(28000, {CliInfo}).

is_open_dungeon_heaven(#role{id = RoleId,
			     m_dun_heaven =
				 #m_dungeon_heaven{chapter_list = L}}) ->
    case lists:keyfind(1, #heaven_chapter.id, L) of
      #heaven_chapter{dun_list = DunList} ->
	  case lists:keyfind(1, #heaven_dun.id, DunList) of
	    #heaven_dun{state = 1} ->
		case lists:keyfind(2, #heaven_dun.id, DunList) of
		  #heaven_dun{state = 0} ->
		      var:set_role_var(RoleId, other, 20, 1);
		  _ -> skip
		end;
	    _ -> skip
	  end;
      _ -> skip
    end.

