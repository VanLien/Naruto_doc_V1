fire_gift(Role = #role{m_holiday_personal_fire_gift =
			   MHolidayPersonalFireGift =
			       #m_holiday_personal_fire_gift{gift_list =
								 GiftList,
							     ext = Ext}}) ->
    Now = date:unixtime(),
    AllGift = holiday_personal_fire_gift_data:gift_list(),
    LimitGiftCount =
	holiday_personal_fire_gift_data:get_const(limit_gift_count),
    OnceList = list_util:keyfind(once_id, Ext, []),
    Fun1 = fun ({Id, FireCond, MappingCond}, {Acc, Acc2}) ->
		   case role_misc:check_open_cond(FireCond ++ MappingCond,
						  Role)
		       of
		     true ->
			 {ZoneId, ChargeId, LimitTime, LimitCount} =
			     holiday_personal_fire_gift_data:get_gift_info(Id),
			 case length(Acc) < LimitGiftCount andalso
				lists:keyfind(ZoneId, 2, Acc) =:= false andalso
				  lists:member(ZoneId,
					       list_util:keyfind(buy_zone_id,
								 Ext, []))
				    =:= false
				    andalso lists:keyfind(Id, 1, Acc) =:= false
			     of
			   true ->
			       case lists:member(Id, [501, 601, 701, 801]) of
				 true ->
				     case lists:member(Id, Acc2) of
				       true -> {Acc, Acc2};
				       _ ->
					   EndTime = Now + LimitTime,
					   NewAcc1 = lists:keystore(Id, 1, Acc,
								    {Id, ZoneId,
								     ChargeId,
								     0,
								     LimitCount,
								     Now,
								     EndTime}),
					   set_time(Id, EndTime, Now),
					   {NewAcc1, [Id | Acc2]}
				     end;
				 _ ->
				     EndTime = Now + LimitTime,
				     NewAcc2 = lists:keystore(Id, 1, Acc,
							      {Id, ZoneId,
							       ChargeId, 0,
							       LimitCount, Now,
							       EndTime}),
				     set_time(Id, EndTime, Now),
				     {NewAcc2, Acc2}
			       end;
			   _ -> {Acc, Acc2}
			 end;
		     _ -> {Acc, Acc2}
		   end
	   end,
    {GiftList1, NewOnceList} = lists:foldl(Fun1,
					   {GiftList, OnceList}, AllGift),
    NewExt = lists:keystore(once_id, 1, Ext,
			    {once_id, NewOnceList}),
    NewRole = Role#role{m_holiday_personal_fire_gift =
			    MHolidayPersonalFireGift#m_holiday_personal_fire_gift{gift_list
										      =
										      GiftList1,
										  ext
										      =
										      NewExt}},
    set_ico(NewRole),
    push_base_info(NewRole),
    NewRole.

