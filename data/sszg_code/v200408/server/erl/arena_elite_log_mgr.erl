	  CombatLog = #arena_elite_log{atk_elite_lev = Lev1,
				       def_rank = Lev2}}) ->
    LimitPower =
	video_data:get_const(elite_battlenum_conditon),
    DiffPower = util:abs(Power - TarPower),
    LimitLev = video_data:get_const(elitelev_conditon),
    MaxPower = max(Power, TarPower),
    Flag = case DiffPower / MaxPower =< LimitPower / 1000 of
	     true when Lev1 >= LimitLev orelse Lev2 >= LimitLev ->
		 true;
	     _ -> false
	   end,
    info({add_log, RoleId, CombatLog, Flag});
save_log(CombatLog = #arena_elite_log{atk_id = Id}) ->
    info({add_log, Id, CombatLog, false}).

get_log(Id) ->
    case ets:lookup(role_arena_elite_log, Id) of
      [#role_arena_elite_log{list = List} | _] ->
	  List, [arena_elite_ver:do_log_list_ver(T) || T <- List];
      _ ->
	  case dets:lookup(role_arena_elite_log, Id) of
	    [Log = #role_arena_elite_log{list = List} | _] ->
		NList = [arena_elite_ver:do_log_list_ver(T)
			 || T <- List],
		ets:insert(role_arena_elite_log,
			   Log#role_arena_elite_log{list = NList}),
		NList;
	    _ -> []
	  end
    end.

