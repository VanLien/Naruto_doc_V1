    case catch gen_server:call(arena_elite_log_mgr, Info,
			       10000)
	of
      {'EXIT', _Call_Err} ->
	  case {whereis(lager_event), whereis(lager_event),
		lager_config:get({lager_event, loglevel}, {0, []})}
	      of
	    {undefined, undefined, _} ->
		fun () -> {error, lager_not_running} end();
	    {undefined, _, _} ->
		fun () -> {error, {sink_not_configured, lager_event}}
		end();
	    {__Pidarena_elite_log_mgr59, _,
	     {__Levelarena_elite_log_mgr59,
	      __Tracesarena_elite_log_mgr59}}
		when __Levelarena_elite_log_mgr59 band 8 /= 0 orelse
		       __Tracesarena_elite_log_mgr59 /= [] ->
		lager:do_log(error,
			     [{module, arena_elite_log_mgr}, {function, call},
			      {line, 59}, {pid, pid_to_list(self())},
			      {node, node()}
			      | lager:md()],
			     io_lib:format("call_pid:~w req:~w timeout:~w get_stacktrace:~w",
					   [arena_elite_log_mgr, Info, 10000,
					    erlang:get_stacktrace()]),
			     none, 4096, 8, __Levelarena_elite_log_mgr59,
			     __Tracesarena_elite_log_mgr59, lager_event,
			     __Pidarena_elite_log_mgr59);
	    _ -> ok
	  end,
	  case _Call_Err of
	    {timeout, _} -> {error, timeout};
	    {noproc, _} -> {error, noproc};
	    {normal, _} -> {error, exit};
	    _ -> {error, _Call_Err}
	  end;
      _Call_Return -> _Call_Return
    end.

