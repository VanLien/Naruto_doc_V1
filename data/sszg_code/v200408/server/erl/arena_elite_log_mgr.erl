handle_info({add_log, RoleId,
	     CombatLog = #arena_elite_log{atk_id = Id = {_, Sid},
					  ret = Ret, def_id = Id2,
					  replay_list = ReplayList},
	     Flag},
	    State = #state{}) ->
    Logs = get_log(RoleId),
    LogId = case Logs of
	      [#arena_elite_log{id = LogId1} | _] when LogId1 < 30 ->
		  LogId1 + 1;
	      _ -> 1
	    end,
    ZoneId = arena_elite_mgr:get_zid(RoleId),
    ARank = arena_elite_mgr:get_role_ranks(Id, ZoneId),
    BRank = arena_elite_mgr:get_role_ranks(Id2, ZoneId),
    NewLogData = CombatLog#arena_elite_log{id = LogId,
					   atk_rank = ARank, def_rank = BRank},
    case RoleId == Id of
      true -> skip;
      _ ->
	  [cluster_lib:cast(Sid, combat_replay_mgr,
			    acc_replay_reference, [Temp])
	   || {_, #arena_replay_info{id = Temp}} <- ReplayList]
    end,
    {NewLogs, DelLogs} = list_util:split(20,
					 [NewLogData | Logs]),
    [[cluster_lib:cast(SidT, combat_replay_mgr,
		       dec_replay_reference, [Temp])
      || {_, #arena_replay_info{id = Temp}} <- ReplayListT]
     || #arena_elite_log{atk_id = {_, SidT},
			 replay_list = ReplayListT}
	    <- DelLogs],
    ets:insert(role_arena_elite_log,
	       #role_arena_elite_log{id = RoleId, list = NewLogs}),
    dets:insert(role_arena_elite_log,
		#role_arena_elite_log{id = RoleId, list = NewLogs}),
    case ARank =< 100 andalso
	   Ret == 1 andalso ARank > 0 andalso RoleId == Id
	of
      true ->
	  [cluster_lib:cast(Sid, combat_replay_mgr,
			    acc_replay_reference, [Temp])
	   || {_, #arena_replay_info{id = Temp}} <- ReplayList],
	  big_world_lib:cast(center, c_arena_elite_mgr, info,
			     [{add_log, NewLogData}]);
      _ -> ok
    end,
    case Flag of
      true ->
	  big_world_lib:cast(center, c_arena_elite_mgr, info,
			     [{add_log_hall, NewLogData}]);
      _ -> ok
    end,
    {noreply, State};
