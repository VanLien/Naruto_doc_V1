broadcast(_BroadcastType, <<>>) -> ok;
broadcast(BroadcastType, Msg) ->
    broadcast(world, undefined, BroadcastType, Msg).

broadcast(Range, RangeArg, BroadcastType, Msg)
    when is_list(Msg) ->
    broadcast(Range, RangeArg, BroadcastType,
	      list_to_binary(Msg));
broadcast(Range, RangeArg, BroadcastType, Msg) ->
    Code = broadcast_code(BroadcastType),
    Data = {[], Code, 0, Msg, date:unixtime()},
    case Range of
      world when is_integer(RangeArg) ->
	  notice_mgr:info({delay_notice, RangeArg, Data});
      world ->
	  case is_need_add(RangeArg) of
	    true -> erlang:send(say_mgr, {say, 1, Data});
	    false -> ok
	  end,
	  role_group:pack_send(world, 12761, Data);
      {channel, Channel} ->
	  role_group:pack_send({channel, Channel}, 12761, Data);
      role ->
	  case is_list(RangeArg) of
	    true ->
		[role:pack_send(TmpArg, 12761, Data)
		 || TmpArg <- RangeArg];
	    false -> role:pack_send(RangeArg, 12761, Data)
	  end;
      guild ->
	  case RangeArg of
	    {GPid, true} when is_pid(GPid) ->
		guild:info(GPid, {say, Data, true});
	    _ -> guild_member:pack_send(RangeArg, all, 12761, Data)
	  end;
      _ -> ok
    end.

is_need_add(RangeArg) ->
    RangeArg == sys orelse RangeArg == sys_top.

broadcast_code(L) when is_list(L) ->
    F = fun (Label, Sum) -> Sum bor broadcast_code(Label)
	end,
    lists:foldl(F, [], 0);
broadcast_code(rumor) -> 16;
broadcast_code(rumor_top) -> 32;
broadcast_code(rumor_left_top) -> 48;
broadcast_code(sys) -> 64;
broadcast_code(sys_top) -> 128;
broadcast_code(sys_left_top) -> 192;
broadcast_code(sys_guild) -> 256;
broadcast_code(sys_team) -> 512;
broadcast_code(world) -> 1 + 128;
broadcast_code(BroadcastType) ->
    case is_integer(BroadcastType) of
      true -> BroadcastType;
      false -> 0
    end.

broadcast_interval(_Flag, <<>>, _CD) -> ok;
broadcast_interval(Flag, Notice, CD) ->
    case catch gen_server:call(drop_mgr,
			       {notice_interval, Flag, CD})
	of
      {ok, true} -> notice:broadcast(rumor_left_top, Notice);
      _Other -> ignore
    end.


