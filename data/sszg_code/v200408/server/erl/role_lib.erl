get_online_role() -> ets:tab2list(role_online).

get_online_role(Opt) ->
    MatchSpec = [{make_ms1(Opt), make_ms2(Opt), ['$_']}],
    ets:select(role_online, MatchSpec).

make_ms1(Opt) ->
    lists:foldl(fun (Tuple, RO_0) ->
			Index = element(1, Tuple),
			erlang:setelement(Index, RO_0,
					  list_to_atom("$" ++
							 integer_to_list(Index)))
		end,
		erlang:make_tuple(erlang:tuple_size(#role_online{}),
				  '_'),
		Opt).

make_ms2(Opt) ->
    lists:foldl(fun ({Index, Val}, Res) ->
			[{'==', list_to_atom("$" ++ integer_to_list(Index)),
			  Val}
			 | Res];
		    ({Index, Val, Con}, Res) ->
			[{Con, list_to_atom("$" ++ integer_to_list(Index)), Val}
			 | Res]
		end,
		[], Opt).

