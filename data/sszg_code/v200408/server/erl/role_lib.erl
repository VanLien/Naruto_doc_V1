    case sys_lib:is_local(SrvId) of
      true -> local_cast(Flag, Key, MFA);
      false ->
	  cluster_lib:cast(SrvId, role_lib, local_cast,
			   [Flag, Key, MFA])
    end;
cast(Flag, Key, MFA) -> local_cast(Flag, Key, MFA).

