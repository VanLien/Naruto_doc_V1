-spec gm_reset(#role{}) -> {ok, #role{}}.

gm_reset(Role) -> {ok, Role#role{m_lev_gift = init()}}.

-spec init() -> #m_lev_gift{}.

init() -> #m_lev_gift{}.

login(Role) ->
    NewRole = util:if_true(check_open(),
			   do_ref_lev_gift(Role), Role),
    holiday:push_bid_can_reward(NewRole, 93002),
    {ok, NewRole}.

do_ref_lev_gift(Role = #role{lev = Lev,
			     m_lev_gift = MLevGift = #m_lev_gift{gifts = L}}) ->
    Fun = fun ({Id, NeedLev}, Acc) ->
		  case lists:keyfind(Id, 1, L) of
		    {_, 0} when Lev >= NeedLev -> [{Id, 1} | Acc];
		    {Id, Status} -> [{Id, Status} | Acc];
		    _ ->
			Status = util:if_true(Lev >= NeedLev, 1, 0),
			[{Id, Status} | Acc]
		  end
	  end,
    NewL = lists:foldl(Fun, [], lev_gift_data:lev_list()),
    Role#role{m_lev_gift =
		  MLevGift#m_lev_gift{gifts = NewL}}.

-spec level_up(#role{}) -> #role{}.

level_up(Role) ->
    case check_open() of
      false -> Role;
      _ ->
	  NewRole = do_ref_lev_gift(Role),
	  push_lev_gift_info(NewRole),
	  NewRole
    end.

-spec gifts_info(#role{}) -> ok.

gifts_info(Role) ->
    case check_open() of
      true -> push_lev_gift_info(Role);
      _ -> notice:alert(lang:get(<<"活动未开启"/utf8>>))
    end.

-spec reward(#role{}, pos_integer()) -> {ok, #role{}} |
					{false, binary()}.

reward(Role = #role{m_lev_gift =
			MLevGift = #m_lev_gift{gifts = L}},
       Id) ->
    case check_can_reward(L, Id) of
      {false, Msg} -> {false, Msg};
      {ok, Count} ->
	  Lock = {lev_gift_reward, Id},
	  case sys_env:lock(Lock) of
	    true ->
		Award = lev_gift_data:get_award(Id),
		Gain = format:val_to_gain(Award, lev_gift_reward),
		case role_gain:do_notice(Role, Gain) of
		  {ok, NRole} ->
		      log:log_gain(Gain, Role, NRole,
				   <<"运营活动_开服限量等级礼包"/utf8>>,
				   util:fbin(lang:get(<<"领取等级礼包~w"/utf8>>),
					     [Id])),
		      lev_gift_mgr:cast({get_reward, Id}),
		      ets:insert(lev_gift, {Id, Count + 1}),
		      sys_env:unlock(Lock),
		      dets:insert(lev_gift, {Id, Count + 1}),
		      NewL = lists:keyreplace(Id, 1, L, {Id, 2}),
		      NewMLevGift = MLevGift#m_lev_gift{gifts = NewL},
		      NewRole = NRole#role{m_lev_gift = NewMLevGift},
		      push_lev_gift_info(NewRole),
		      {ok, NewRole};
		  {false, #loss{msg = Msg}} ->
		      lev_gift_mgr:cast({get_reward_false, Id}), {false, Msg}
		end;
	    _ ->
		sys_env:unlock(Lock),
		{false, lang:get(<<"领取失败,请重新尝试"/utf8>>)}
	  end
    end.

check_can_reward(L, Id) ->
    case check_open() of
      true ->
	  case lists:keyfind(Id, 1, L) of
	    {_, 2} -> {false, lang:get(<<"奖励已领取"/utf8>>)};
	    {_, 0} -> {false, lang:get(<<"未达成领取条件"/utf8>>)};
	    {_, 1} ->
		Count = lev_gift_mgr:get_count(Id),
		MaxCount = lev_gift_data:get_max_count(Id),
		case Count >= MaxCount of
		  true -> {false, lang:get(<<"该奖励已领完"/utf8>>)};
		  _ -> {ok, Count}
		end;
	    _ -> {false, lang:get(<<"参数错误"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"活动未开启"/utf8>>)}
    end.

check_open() ->
    case holiday_lib:get_open_holiday(93002) of
      undefined -> false;
      _ -> true
    end.

push_lev_gift_info(#role{m_lev_gift =
			     #m_lev_gift{gifts = L}}) ->
    PushInfo = [{Id, Status, lev_gift_mgr:get_count(Id)}
		|| {Id, Status} <- L],
    sys_conn:pack_send(21200, {PushInfo}).

get_lev_gift_status(#role{m_lev_gift =
			      #m_lev_gift{gifts = L}}) ->
    Fun = fun ({Id, Status}) ->
		  case Status == 1 of
		    true ->
			Count = lev_gift_mgr:get_count(Id),
			MaxCount = lev_gift_data:get_max_count(Id),
			case Count >= MaxCount of
			  true -> false;
			  _ -> true
			end;
		    _ -> false
		  end
	  end,
    lists:any(Fun, L).


