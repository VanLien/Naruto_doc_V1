			    #m_star_tower{max_tower = MaxTower}},
		  Tower)
    when Tower =< MaxTower ->
    false;
check_combat_skip(Role, Tower) ->
    case Tower =<
	   star_tower_data:get_constant(monster_run_floor_condition)
	of
      true ->
	  DefPower = star_tower_data:get_power(Tower),
	  RolePower = formation:get_sys_formation_power(Role, 17),
	  LimitRio =
	      star_tower_data:get_constant(monster_run_battlenum_condition),
	  case RolePower >= DefPower * LimitRio / 1000 of
	    true ->
		Pro =
		    star_tower_data:get_constant(monster_run_probability),
		case util:rand_per_mille(Pro) of
		  true -> true;
		  _ -> false
		end;
	    _ -> false
	  end;
      _ -> false
    end.

