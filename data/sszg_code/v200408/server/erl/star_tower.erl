				     {NewRole, <<"功能玩法"/utf8>>,
				      <<"试炼塔"/utf8>>}),
			    {ok, NewRole, Count - 1, BuyCount};
			_ -> {false, lang:get(<<"扫荡失败"/utf8>>)}
		      end
		end
	  end
    end.

