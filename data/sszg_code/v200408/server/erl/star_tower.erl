				      <<"试炼塔"/utf8>>}),
			    {ok, NewRole, Count, BuyCount + 1};
			{false, #loss{msg = Msg}} -> {false, Msg};
			{false, #gain{msg = Msg}} -> {false, Msg}
		      end
		end;
	    _ ->
		case check_can_combat(Role, Tower) of
		  {false, Msg} -> {false, Msg};
		  _ ->
		      {_, _, _, Award} = star_tower_data:get_award(Tower),
