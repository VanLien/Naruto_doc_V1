	  case check_combat_skip(Role, Tower) of
	    true -> do_skip_combat_over(Role, Tower);
	    _ ->
		#formation_sys{type = FormationType, pos_info = PosInfo,
			       hallows_id = HallowsId} =
		    formation:get_sys_formation(Role, 17),
