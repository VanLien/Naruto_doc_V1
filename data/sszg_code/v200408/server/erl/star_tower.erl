							 FightPos),
		AtkGroup = sprite_tree:gen_fight_object_type(Role, 17)
			     ++
			     hallows_lib:gen_fight_object(Role, HallowsId) ++
			       AtkGroup1,
		DefPower = star_tower_data:get_power(Tower),
		UnitId = star_tower_data:get_unit_id(Tower),
		case unit_data:get(UnitId) of
		  #unit_data{formation = {BFormationType, BFormationLev},
			     name = TarName} ->
		      case unit_monster:gen_fight_objects(Lev, UnitId) of
			[DefendList | _] ->
			    {ok, CRole0} = role_convert:do(combat_role, Role),
			    CRole = case UICombatType == 7 of
				      true -> CRole0;
				      _ ->
					  CRole0#combat_role{auto_watch_model =
								 1,
							     watching = 0,
							     is_auto = true,
							     is_offline = true,
							     conn_pid = 0}
				    end,
			    Args = #{on_role_combat_end =>
					 {star_tower, combat_over,
					  [{Tower, date:unixtime()}]},
				     ext_args =>
					 [{cli_ext_args, [Tower]},
