to_replay_data(Role = #role{id = {Rid, Sid}}) ->
    #tower_replay_data{rid = Rid, sid = Sid,
		       name = Role#role.name, face_id = Role#role.face_id,
		       power = Role#role.max_power}.

check_open(Role) ->
    LimitId = star_tower_data:get_constant(open_floor),
    case role_misc:check_open_cond(LimitId, Role) of
      {false, Msg} -> {false, Msg};
      _ -> true
    end.

check_open(Role = #role{m_star_tower =
			    #m_star_tower{max_tower = MaxTower}},
	   Tower) ->
    AllTower = lists:max(star_tower_data:get_list()),
    LimitDunId = star_tower_data:get_limit_dun_id(Tower),
    MaxDunId = dungeon:max_dun_id(Role),
    case check_open(Role) of
      {false, Msg} -> {false, Msg};
      _ ->
	  if Tower > AllTower ->
		 {false, lang:get(<<"已到达试炼塔最高层"/utf8>>)};
	     Tower < 1 -> {false, lang:get(<<"参数错误"/utf8>>)};
	     Tower > MaxTower + 1 ->
		 {false, lang:get(<<"通关上一层解锁"/utf8>>)};
	     MaxDunId < LimitDunId ->
		 case dungeon_data:get(LimitDunId) of
		   #dungeon_data{name = Name} ->
		       {false,
			util:fbin(lang:get(<<"需通关~ts开启"/utf8>>), [Name])};
		   _ -> {false, lang:get(<<"开启条件未达成"/utf8>>)}
		 end;
	     true -> true
	  end
    end.

check_can_combat(Role = #role{m_star_tower =
				  #m_star_tower{max_tower = MaxTower},
			      combat_type_list = CombatTypeList},
		 Tower) ->
    case check_open(Role, Tower) of
      {false, Msg} -> {false, Msg};
      _ ->
	  Count = var:get_var(Role, day, 62,
			      star_tower_data:get_constant(free_times)),
	  case Count =< 0 andalso Tower =< MaxTower of
	    true -> {false, lang:get(<<"挑战次数不足"/utf8>>)};
	    _ ->
		case lists:keymember(7, 1, CombatTypeList) of
		  true -> {false, lang:get(<<"正在战斗中"/utf8>>)};
		  _ -> ok
		end
	  end
    end.

