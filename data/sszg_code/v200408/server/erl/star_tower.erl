do_ref_replay(Role, ReplayId, Tower, Time, MaxTower) ->
    ReplayData = to_replay_data(Role),
    star_tower_mgr:ref_repaly(Tower,
			      ReplayData#tower_replay_data{repaly_id = ReplayId,
							   time = Time},
