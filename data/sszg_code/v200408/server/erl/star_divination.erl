check_can_divination([count | Other],
		     Role = #role{m_star_divination = MStarDivination}, 1,
		     Count) ->
    LimitCount =
	star_divination_data:get_constant(divine_times),
    DayCount =
	MStarDivination#m_star_divination.day_gold_count,
    case DayCount + Count > LimitCount of
      true -> {false, lang:get(<<"超出每日钻石召唤限制"/utf8>>)};
      _ -> check_can_divination(Other, Role, 1, Count)
    end;
check_can_divination([count | Other], Role, Type,
		     Count) ->
    check_can_divination(Other, Role, Type, Count);
check_can_divination([expend | _],
		     Role = #role{m_star_divination =
				      M = #m_star_divination{flag = 0}},
		     1, 1) ->
    {ok,
     Role#role{m_star_divination =
		   M#m_star_divination{flag = 1}},
     []};
check_can_divination([expend | _], Role, Type, Count) ->
    case get_expend(Type, Count) of
      {false, Msg} -> {false, Msg};
      Expend ->
	  Loss = format:val_to_loss(Expend, star_divination),
	  case role_gain:do(Role, Loss) of
	    {ok, Role2} -> {ok, Role2, Loss};
	    {false, #loss{msg = Msg}} ->
		case Type == 2 of
		  true -> {false, lang:get(<<"星魂不足"/utf8>>)};
		  _ -> {false, Msg}
		end;
	    _ -> {false, lang:get(<<"资产不足"/utf8>>)}
	  end
    end.

do_divination(MStarDivination, Count, _Type, Items,
	      _OnwerStar)
    when Count =< 0 ->
    {MStarDivination, Items};
do_divination(MStarDivination = #m_star_divination{luck
						       = Luck,
						   quality = Quality,
						   all_count = AllCount},
	      Count, Type, Items, OnwerStar) ->
    Item = do_divination_once(Luck, Quality, OnwerStar),
    NewCount = AllCount + 1,
    NextQuality = get_next_quality(Quality, NewCount, Type),
    NewMStarDivination0 =
	MStarDivination#m_star_divination{quality = NextQuality,
					  all_count = NewCount},
    NewMStarDivination = add_type_count(NewMStarDivination0,
					Type),
    do_divination(NewMStarDivination, Count - 1, Type,
		  [Item | Items], OnwerStar).

add_type_count(MStarDivination =
