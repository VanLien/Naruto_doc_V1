-spec five_flush(#role{}) -> {ok, #role{}}.

five_flush(Role = #role{m_star_divination =
			    MDivination = #m_star_divination{luck = Luck}}) ->
    NewLuck = do_ref(Role, Luck),
    NewMDivination = MDivination#m_star_divination{ref_count
						       = 0,
						   luck = NewLuck, flag = 0,
						   day_gold_count = 0,
						   day_hun_count = 0},
    {ok, Role#role{m_star_divination = NewMDivination}}.

-spec get_info(#role{}) -> term().

get_info(#role{m_star_divination =
		   #m_star_divination{luck = Luck, quality = Quality,
				      flag = Flag, ref_count = RefCount,
				      day_gold_count = DayCount,
				      all_count = AllCount}}) ->
    EndCount = get_end_count(AllCount),
    {Quality, Luck, EndCount, RefCount, DayCount, Flag}.

get_end_count(AllCount) ->
    [MastCount | _] = star_divination_data:get_mast_list(),
    MastCount - AllCount rem MastCount.

-spec ref(#role{}) -> {false, binary()} |
		      {ok, #role{}, pos_integer(), pos_integer()}.

ref(Role = #role{m_star_divination =
		     MDivination = #m_star_divination{ref_count = RefCount,
						      luck = Luck}}) ->
    Expend = star_divination_data:get_expend(RefCount + 1),
    Loss = format:val_to_loss(Expend, star_divination_ref),
    case role_gain:do(Role, Loss) of
      {ok, NRole} ->
	  log:log_gain(Loss, Role, NRole, <<"占卜"/utf8>>,
		       util:fbin("运势刷新次数:~w", [RefCount + 1])),
	  NewLuck = do_ref(NRole, Luck),
	  NewMDivination = MDivination#m_star_divination{luck =
							     NewLuck,
							 ref_count =
							     RefCount + 1},
	  NewRole = NRole#role{m_star_divination =
				   NewMDivination},
	  {ok, NewRole, NewLuck, RefCount + 1};
      {false, #loss{msg = Msg}} -> {false, Msg};
      _ -> {false, lang:get(<<"资产不足"/utf8>>)}
    end.

do_ref(Role, OldLuck) ->
    OnwerStar = case get_star_list(Role) of
		  List when length(List) > 1 ->
		      lists:delete(OldLuck, List);
		  L -> L
		end,
    RnadList0 = star_divination_data:get_luck_rands(),
    RnadList = [{SetId, Pro}
		|| {SetId, Pro} <- RnadList0,
		   lists:member(SetId, OnwerStar)],
    NewLuck = case util:rand_list(RnadList, 2) of
		{NewLuckT, _} -> NewLuckT;
		_ -> OldLuck
	      end,
    NewLuck.

-spec divination(#role{}, pos_integer(),
		 pos_integer()) -> {false, binary()} | {ok, #role{}}.

divination(Role = #role{m_star_divination =
			    #m_star_divination{flag = Flag}},
	   Type = 1, Count) ->
    case check_can_divination([count, expend], Role, Type,
			      Count)
	of
      {ok,
       Role2 = #role{m_star_divination =
			 MStarDivination = #m_star_divination{flag = NewFlag}},
       Loss} ->
	  OnwerStar = get_star_list(Role2),
	  {NewMStarDivination = #m_star_divination{quality =
						       Quality,
						   day_gold_count = DayCount,
						   luck = Luck,
						   all_count = AllCount},
	   ItemListT} =
	      do_divination(MStarDivination, Count, Type, [],
			    OnwerStar),
	  ItemList = [{Id, Num} || {Id, Num, _, _} <- ItemListT],
	  OtehrItem = get_other_award(Type, Count),
	  Award = ItemList ++ OtehrItem,
	  GL = format:val_to_gain(Award, star_divination),
	  case role_gain:do(Role2, GL) of
	    {ok, NRole} ->
		log:log_gain(GL ++ Loss, Role, NRole, <<"占卜"/utf8>>,
			     util:fbin("占卜类型:~w,次数:~w,当前品质:~w,运势:~w,奖励:~w, flag:~w",
				       [Type, Count, Quality, Luck, Award,
					Flag])),
		NRole1 = NRole#role{m_star_divination =
					NewMStarDivination},
		NewRole0 = role_trigger:fire(#evt_star_divination{type =
								      Type,
								  count =
								      Count},
					     NRole1),
		NewRole = days_rank_mgr:in_rank(divination, NewRole0,
						Count),
		EndCount = get_end_count(AllCount),
		do_notice(NewRole, ItemListT),
		LogMsg = get_log_msg(Type, Count),
		log:save(join, {NewRole, <<"产出类玩法"/utf8>>, LogMsg}),
		{ok, NewRole, EndCount, Quality, DayCount, NewFlag,
		 ItemList, OtehrItem};
	    {false, #gain{msg = Msg}} -> {false, Msg};
	    _ -> {false, lang:get(<<"占卜失败"/utf8>>)}
	  end;
      {false, Msg} -> {false, Msg};
      _ -> {false, lang:get(<<"资产不足"/utf8>>)}
    end;
divination(_Role, _, _Count) ->
