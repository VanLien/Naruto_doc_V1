	       2) ->
    MStarDivination#m_star_divination{day_hun_count =
					  DayCount + 1};
add_type_count(MStarDivination, _Type) ->
    MStarDivination.

get_next_quality(Quality, Count, Type) ->
    [MastCount | _] = star_divination_data:get_mast_list(),
    EndCount = MastCount - Count rem MastCount,
    RandList = case EndCount == 1 of
		 true ->
		     L = star_divination_data:get_mast(MastCount),
		     list_util:keyfind(Type, L, []);
		 _ ->
		     star_divination_data:get_next_type_rands({Type,
							       Quality})
	       end,
    {NewQuality, _} = util:rand_list(RandList, 2),
    NewQuality.

do_divination_once(Luck, Quality, OnwerStar) ->
    LuckPro = star_divination_data:get_luck_pro(Luck),
    AllRandList0 =
	star_divination_data:get_divination_ran1(Quality),
    AllRandList = [{SetId, AwardId0, Pro}
		   || {SetId, AwardId0, Pro} <- AllRandList0,
		      lists:member(SetId, OnwerStar)],
    {_, AwardId, _} = case util:rand_per_mille(LuckPro) of
			true -> lists:keyfind(Luck, 1, AllRandList);
			_ -> util:rand_list(AllRandList, 3)
