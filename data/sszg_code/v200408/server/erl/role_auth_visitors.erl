check_arge(Role = #role{platform = Platform}, 0)
    when Platform == <<"symlf">> ->
    Role1 = var:set_var(Role, other, 3084, 1),
    {ok, NewRole} = set_visitors_time(Role1),
    NewRole;
check_arge(Role, _) ->
    case var:get_var(Role, other, 3084, 0) of
      1 -> Role1 = var:set_var(Role, other, 3084, 0), Role1;
      _ -> Role
    end.

set_visitors_time(Role = #role{account = Account,
			       platform = Platform})
    when Platform == <<"symlf">> ->
    case is_visitors(Role) of
      true ->
	  case get(role_auth_visitors_old_time) of
	    {ResetTime, OldTime} ->
		apply_visitors_time(Role, {ResetTime, OldTime});
	    _ ->
		catch big_world_lib:cast(center_all,
					 c_role_auth_visitors, info,
					 [{update_time, Account, self()}]),
		{ok, Role}
	  end;
      _ -> {ok, Role}
    end;
set_visitors_time(Role) -> {ok, Role}.

apply_visitors_time(Role, {ResetTime, OldTime}) ->
    Now = date:unixtime(),
    ResetEndTime = max(1, ResetTime - Now),
    LoginTime = calc_this_time(Role),
    OutTime = max(1, 3600 - (LoginTime + OldTime)),
    Timer1 = #timer{id = role_auth_visitors_reset_time,
		    timeout = ResetEndTime * 1000, times = 1,
		    m = role_auth_visitors, f = apply_reset_time, a = []},
    Role1 = role_timer:add(Timer1, Role),
    Timer2 = #timer{id = role_auth_visitors_out_time,
		    timeout = OutTime * 1000, times = 1,
		    m = role_auth_visitors, f = apply_out_time, a = []},
    Role2 = role_timer:add(Timer2, Role1),
    put(role_auth_visitors_old_time, {ResetTime, OldTime}),
    {ok, Role2}.

apply_reset_time(Role = #role{account = Account}) ->
    catch big_world_lib:cast(center_all,
			     c_role_auth_visitors, info,
			     [{reset_time, Account, self()}]),
    {ok, Role}.

apply_out_time(Role = #role{account = Account}) ->
    case is_visitors(Role) of
      true ->
	  Val = var:get_var(Role, other, 3084, 0),
	  case get(role_auth_visitors_old_time) of
	    {_, AllLoginTime} when Val == 1 ->
		LoginTime = calc_this_time(Role),
		case LoginTime + AllLoginTime >= 3600 of
		  true ->
		      case {whereis(lager_event), whereis(lager_event),
			    lager_config:get({lager_event, loglevel}, {0, []})}
			  of
			{undefined, undefined, _} ->
			    fun () -> {error, lager_not_running} end();
			{undefined, _, _} ->
			    fun () ->
				    {error, {sink_not_configured, lager_event}}
			    end();
			{__Pidrole_auth_visitors83, _,
			 {__Levelrole_auth_visitors83,
			  __Tracesrole_auth_visitors83}}
			    when __Levelrole_auth_visitors83 band 64 /= 0 orelse
				   __Tracesrole_auth_visitors83 /= [] ->
			    lager:do_log(info,
					 [{module, role_auth_visitors},
					  {function, apply_out_time},
					  {line, 83},
					  {pid, pid_to_list(self())},
					  {node, node()}
					  | lager:md()],
					 io_lib:format("~ts游客模式时间已超时,账号累计时长:~w, 本次角色登录时长:~w",
						       [Role#role.name,
							AllLoginTime,
							LoginTime]),
					 none, 4096, 64,
					 __Levelrole_auth_visitors83,
					 __Tracesrole_auth_visitors83,
					 lager_event,
					 __Pidrole_auth_visitors83);
			_ -> ok
		      end,
		      catch big_world_lib:cast(center_all,
					       c_role_auth_visitors, info,
					       [{time_out, Account}]),
		      sys_conn:pack_send(10394, {}),
		      {ok, Role};
		  _ ->
		      OutTime = max(1, 3600 - (LoginTime + AllLoginTime)),
		      Timer2 = #timer{id = role_auth_visitors_out_time,
				      timeout = OutTime * 1000, times = 1,
				      m = role_auth_visitors,
				      f = apply_out_time, a = []},
		      Role2 = role_timer:add(Timer2, Role),
		      {ok, Role2}
		end;
	    _ -> {ok, Role}
	  end;
      _ -> {ok, Role}
    end.

login_out(Role = #role{account = Account}) ->
    case is_visitors(Role) of
      true ->
	  AccTime0 = calc_this_time(Role),
	  AddTime = util:if_true(AccTime0 > 300, AccTime0 - 300,
				 AccTime0),
	  catch big_world_lib:cast(center_all,
				   c_role_auth_visitors, info,
				   [{add_login_time, Account, AddTime}]);
      _ -> skip
    end,
    {ok, Role}.

calc_this_time(#role{login =
			 #login{login_time = LoginTime}}) ->
    Now = date:unixtime(), Now - LoginTime.

is_visitors(Role = #role{account = Account}) ->
    case ip_mgr:is_white_acc(Account) of
      Flag when Flag == true orelse Flag == false ->
	  case var:get_var(Role, other, 3084, 0) of
	    1 -> true;
	    _ -> false
	  end;
      _ -> false
    end.


