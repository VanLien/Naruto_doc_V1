do_init(Table = #merge_table{server =
				 #merge_server{index = Size, size = Size}}) ->
    merge_util:dets_merge(guild, "guild.dets", set,
			  #guild.id, fun ver_convert/1),
    {ok, [], Table};
do_init(Table) -> {ok, [], Table}.

do_convert([], Table) -> {ok, Table}.

do_end(_Table) -> ignore.

ver_convert(G = #guild{name = Gname}) ->
    case ets:match_object(guild,
			  #guild{name = Gname, _ = '_'})
	of
      [G1 = #guild{}] ->
	  case compare(G, G1) of
	    true ->
		NewG1 = rename(G1),
		ets:insert(guild, NewG1),
		dets:insert(guild, NewG1),
		{ok, G};
	    false -> {ok, rename(G)}
	  end;
      [] -> {ok, G}
    end;
ver_convert(Data) ->
    {ok, G} = guild_mgr:ver(Data), ver_convert(G).

rename(G = #guild{id = {_Gid, GSrvId}, name = Gname}) ->
    [SrvSn | _T] =
	lists:reverse(re:split(bitstring_to_list(GSrvId), "_",
			       [{return, list}])),
    NewGname = util:fbin(<<"【S~s】~ts"/utf8>>,
			 [SrvSn, Gname]),
    case {whereis(lager_event), whereis(lager_event),
	  lager_config:get({lager_event, loglevel}, {0, []})}
	of
      {undefined, undefined, _} ->
	  fun () -> {error, lager_not_running} end();
      {undefined, _, _} ->
	  fun () -> {error, {sink_not_configured, lager_event}}
	  end();
      {__Pidmerge_dets_guild51, _,
       {__Levelmerge_dets_guild51, __Tracesmerge_dets_guild51}}
	  when __Levelmerge_dets_guild51 band 64 /= 0 orelse
		 __Tracesmerge_dets_guild51 /= [] ->
	  lager:do_log(info,
		       [{module, merge_dets_guild}, {function, rename},
			{line, 51}, {pid, pid_to_list(self())}, {node, node()}
			| lager:md()],
		       io_lib:format("联盟同名处理:~ts==>~ts", [Gname, NewGname]),
		       none, 4096, 64, __Levelmerge_dets_guild51,
		       __Tracesmerge_dets_guild51, lager_event,
		       __Pidmerge_dets_guild51);
      _ -> ok
    end,
    NewG = G#guild{name = NewGname},
    case ets:match_object(guild,
			  #guild{name = NewGname, _ = '_'})
	of
      [] -> NewG;
      [_] -> rename_n(NewG, 1)
    end.

rename_n(G = #guild{name = Gname}, N) ->
    NewGname = util:fbin(<<"~ts~w">>, [Gname, N]),
    case ets:match_object(guild,
			  #guild{name = NewGname, _ = '_'})
	of
      [] -> G#guild{name = NewGname};
      [_] -> rename_n(G, N + 1)
    end.

compare(#guild{lev = Lev1, members_num = Num1,
	       power = Power1, create_time = Time1},
	#guild{lev = Lev2, members_num = Num2, power = Power2,
	       create_time = Time2}) ->
    {Lev1, Num1, Power1, -Time1} >
      {Lev2, Num2, Power2, -Time2}.


