-spec init(#item{}) -> #item{}.

init(Item = #item{base_id = Bid}) ->
    case is_natal(Item) of
      false -> Item;
      _ ->
	  SetId = item_data:natal_set(Bid),
	  get_natal_attr_power(Item#item{set_id = SetId,
					 enchant = 1})
    end.

get_max_power_natal(Role = #role{p_bag =
				     #package{items = Items}}) ->
    NatalItems = [Item || Item <- Items, is_natal(Item)],
    StarNatals = get_star_natals(Role),
    case list_util:mkeysort2([{r, #item.all_score},
			      {s, #item.base_id}],
			     NatalItems ++ StarNatals)
	of
      [L | _] -> L;
      _ -> false
    end.

get_star_natals(#role{m_star =
			  #m_star{star_list = StarList}}) ->
    lists:flatten([Natals
		   || #star{natals = Natals} <- StarList]).

-spec is_natal(#item{}) -> false | true.

is_natal(#item{type = Type}) ->
    lists:member(Type, [11, 12, 13, 14]).

-spec push_ref_star(#role{}, #star{}) -> ok.

push_ref_star(Role, Star = #star{add_attr = AddAttr}) ->
    CliStar = Star#star{add_attr =
			    to_cli_add_attr(AddAttr)},
    role:pack_send(Role, 11301, {CliStar}),
    ok.

-spec del_fetter(#role{}, pos_integer()) -> #role{}.

del_fetter(Role = #role{m_star =
			    MStar = #m_star{fetter_list = L}},
	   Id) ->
    Fun = fun ({SetId, Pos, IdT}, Acc) ->
		  case IdT == Id of
		    true -> [{SetId, Pos, 0} | Acc];
		    _ -> [{SetId, Pos, IdT} | Acc]
		  end
	  end,
    NewL = lists:foldl(Fun, [], L),
    Role#role{m_star = MStar#m_star{fetter_list = NewL}}.

-spec to_cli(list()) -> list().

to_cli(StarList) ->
    [Star#star{add_attr = to_cli_add_attr(AddAttr)}
     || Star = #star{add_attr = AddAttr} <- StarList].

to_cli_add_attr(AddAttr) ->
    [{attr_data:atom_to_int(K), V} || {K, V} <- AddAttr].

-spec get_attr(#role{}, pos_integer(),
	       pos_integer()) -> {list(), pos_integer()}.

get_attr(#role{m_star = #m_star{star_list = StarList}},
	 _Type, SetId) ->
    {FetterAttr, FetterSkillId} = get_fetter_info(StarList,
						  SetId, [], []),
    {FetterAttr, FetterSkillId};
get_attr(#role_robot{m_star =
			 #m_star{star_list = StarList}},
	 _Type, SetId) ->
    {FetterAttr, FetterSkillId} = get_fetter_info(StarList,
						  SetId, [], []),
    {FetterAttr, FetterSkillId}.

get_fetter_info(_StarList, [], AllFetterAttr,
		AllFetterSkillId) ->
    {AllFetterAttr, AllFetterSkillId};
get_fetter_info(StarList, [SetId | Other],
		AllFetterAttr, AllFetterSkillId) ->
    {FetterAttr, FetterSkillId} = get_fetter_info(StarList,
						  SetId),
    NAllFetterSkillId = case FetterSkillId == 0 of
			  true -> AllFetterSkillId;
			  _ -> [FetterSkillId | AllFetterSkillId]
			end,
    get_fetter_info(StarList, Other,
		    item_lib:merge(FetterAttr ++ AllFetterAttr, []),
		    NAllFetterSkillId).

get_fetter_info(StarList, SetId) ->
    case lists:keyfind(SetId, #star.set_id, StarList) of
      #star{add_attr = Attr1, natals = Natals,
	    set_skill_id = SkillId}
	  when length(Natals) >= 4 ->
	  {Attr1, SkillId};
      _ -> {[], 0}
    end.

-spec cal_star(#role{}, #star{}) -> #role{}.

cal_star(Role = #role{m_star =
			  MStar = #m_star{star_list = List}},
	 Star = #star{set_id = SetId}) ->
    NewStar = cal_star(Star),
    push_ref_star(Role, NewStar),
    NewList = lists:keystore(SetId, #star.set_id, List,
			     NewStar),
    Role#role{m_star = MStar#m_star{star_list = NewList}}.

cal_star(Star = #star{set_id = SetId,
		      natals = NatalsT}) ->
    Natals = [get_natal_attr_power(T) || T <- NatalsT],
    NAddAttr = lists:flatten([Attr ++
				star_data:get_natal_lev_up_attr({SetId, Type,
								 Enchant})
				  ++
				  star_data:get_natal_star_up_attr({Bid,
								    StarLev})
				    ++
				    star_data:get_natal_break_up_attr({Bid,
								       BreakCount})
			      || #item{enchant = Enchant,
				       break_count = BreakCount,
				       star_lev = StarLev, base_id = Bid,
				       type = Type, main_attr = Attr}
				     <- Natals]),
    NatalsLev = case length(Natals) < 4 of
		  true -> 0;
		  _ ->
		      lists:min([Enchant
				 || #item{enchant = Enchant} <- Natals])
		end,
    SetAttr = star_data:get_set_attr({SetId, NatalsLev}),
    SetSkill = star_data:get_set_skill({SetId, NatalsLev}),
    AddAttr = item_lib:merge(NAddAttr, SetAttr),
    {NewAddAttr, NewSetSkill, Power} = case length(Natals) <
					      4
					   of
					 true -> {[], 0, 0};
					 _ ->
					     PowerT =
						 attr_calc:calc_power(AddAttr) +
						   skill_lib:skill_power([SetSkill]),
					     {AddAttr, SetSkill, PowerT}
				       end,
    Star#star{add_attr = NewAddAttr, natals = Natals,
	      power = Power, set_skill_id = NewSetSkill}.

-spec get_natal_attr_power(#item{}) -> #item{}.

get_natal_attr_power(Item = #item{set_id = SetId,
				  type = Type, base_id = Bid,
				  break_count = BeakLev, enchant = Enchant,
				  star_lev = StarLev, main_attr = Attr}) ->
    Attr2 = star_data:get_natal_star_up_attr({Bid,
					      StarLev}),
    Attr3 = star_data:get_natal_lev_up_attr({SetId, Type,
					     Enchant}),
    Attr4 = star_data:get_natal_break_up_attr({Bid,
					       BeakLev}),
    AllScore = attr_calc:calc_power(Attr ++
				      Attr2 ++ Attr3 ++ Attr4),
    Item#item{all_score = AllScore}.


