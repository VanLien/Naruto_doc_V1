check([], _Type, _Evt, _Role) -> true;
check([Cond | T], Type, Evt, Role) ->
    case do_check(Cond, Evt, Role) of
      true when Type =:= 'or' -> true;
      true -> check(T, Type, Evt, Role);
      false when Type =:= 'or' -> check(T, Type, Evt, Role);
      false -> false
    end.

