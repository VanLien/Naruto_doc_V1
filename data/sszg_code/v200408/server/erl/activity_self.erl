-spec get_activity(all | non_neg_integer()) -> {error,
						undefined} |
					       {ok, #activity{}} | {ok, list()}.

get_activity(ActId) when is_integer(ActId) ->
    case get_activity(all) of
      {error, undefined} -> {error, undefined};
      {ok, L} ->
	  case lists:keyfind(ActId, #activity.id, L) of
	    false -> {error, undefined};
	    AC -> {ok, AC}
	  end
    end;
get_activity(all) ->
    case read_dict() of
      {error, _Reason} -> {error, undefined};
      {ok, L} -> {ok, L}
    end.

-spec get_activity(non_neg_integer(),
		   status) -> non_neg_integer().

get_activity(ActId, status) ->
    case get_activity(ActId) of
      {error, undefined} -> 0;
      {ok, AC} -> AC#activity.status
    end.

-spec send_all_activity(#role{}) -> ok.

send_all_activity(Role) ->
    L1 = case get_activity(all) of
	   {error, undefined} -> [];
	   {ok, L} -> L
	 end,
    Now = date:unixtime(),
    L2 = [{AC#activity.id, AC#activity.status,
	   activity_data(AC, Now), AC#activity.ext_args}
	  || AC <- L1],
    role:pack_send(Role, 10924, {L2}).

set_activity(ActId, StateNum, Data) ->
    set_activity(push,
		 #activity{id = ActId, status = StateNum, data = Data}).

-spec set_activity(false | push | #role{},
		   #activity{} | non_neg_integer(), non_neg_integer(),
		   list()) -> ok.

set_activity(#role{}, ActId, StateNum, Data) ->
    set_activity(push,
		 #activity{id = ActId, status = StateNum, data = Data}),
    ok;
set_activity(ActId, StateNum, Data, ExtList)
    when is_integer(ActId) andalso
	   is_list(Data) andalso is_list(ExtList) ->
    set_activity(push,
		 #activity{id = ActId, status = StateNum, data = Data,
			   ext_args = ExtList}),
    ok;
set_activity(IsNeedPush, ActId, StateNum, Data)
    when is_integer(ActId), is_integer(StateNum),
	 is_list(Data) ->
    set_activity(IsNeedPush,
		 #activity{id = ActId, status = StateNum, data = Data}).

-spec set_activity(#activity{}) -> ok.

set_activity(AC) when is_record(AC, activity) ->
    set_activity(push, AC).

-spec set_activity(false | push, #activity{}) -> ok.

set_activity(IsNeedPush, AC)
    when is_record(AC, activity) ->
    write_dict(AC),
    case IsNeedPush of
      false -> ignore;
      _ ->
	  role:pack_send(10925,
			 {AC#activity.id, AC#activity.status,
			  activity_data(AC, date:unixtime()),
			  AC#activity.ext_args})
    end.

-spec activity_data(#activity{},
		    non_neg_integer()) -> list().

activity_data(AC, _Now) -> AC#activity.data.

write_dict(AC = #activity{status = Status}) ->
    Result = read_dict(),
    case Result of
      {error, _Reason} -> {error, _Reason};
      {ok, L} ->
	  L1 = case Status of
		 0 -> lists:keydelete(AC#activity.id, #activity.id, L);
		 _ -> lists:keystore(AC#activity.id, #activity.id, L, AC)
	       end,
	  role:put_dict({activity_self, activity_list}, L1),
	  {ok}
    end.

read_dict() ->
    case role:get_dict({activity_self, activity_list}) of
      {ok, undefined} -> {ok, []};
      {ok, Data} -> {ok, Data};
      {error, _Reason} -> {error, _Reason}
    end.


