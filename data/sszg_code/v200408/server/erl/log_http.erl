guild_sync(#guild{id = {Gid, GSrvId}, name = GName,
		  leader_name = LeaderName, lev = GLev, members_num = Num,
		  sign = Sign, create_time = CreateTime}) ->
    [P, Zid] = string_util:explode(GSrvId, "_"),
    DataL = [{platform_name, list_to_binary(P)},
	     {gameserver_no, list_to_integer(Zid)}, {guild_id, Gid},
	     {guild_name, GName}, {chief_name, LeaderName},
	     {lv, GLev}, {role_num, Num}, {announcement, Sign},
	     {fund, 0}, {guild_create_time, CreateTime}],
    send("guild/info", DataL),
    ok.

