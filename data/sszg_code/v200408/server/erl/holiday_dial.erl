get_limit_count(Pos, Items) ->
    case lists:keyfind(Pos, 1, Items) of
      {_, _, LimitCount} when LimitCount > 0 -> LimitCount;
      _ -> 0
    end.

get_award_id(Pos, Items) ->
    case lists:keyfind(Pos, 1, Items) of
      {_, RandId, _} -> RandId;
      _ -> 0
    end.

do_dial2(_Type, 0, _RandList, L, TotulCount, Items, L2,
	 PosLimitCount) ->
    {L, TotulCount, Items, L2, PosLimitCount};
do_dial2(Type, Count, RandList, L, TotulCount, Items,
	 L2, PosLimitCount) ->
    Fun = fun ({Pos, Pro}, Acc) ->
		  case get_limit_count(Pos, Items) > 0 of
		    true ->
			MustNoCount = dial_data:get_pos_must_no_count({Type,
								       Pos}),
			DoCount = list_util:keyfind(Pos, PosLimitCount, 999),
			case DoCount >= MustNoCount of
			  true -> [{Pos, Pro} | Acc];
			  _ -> Acc
			end;
		    _ -> Acc
		  end
	  end,
    RandList2 = lists:foldl(Fun, [], RandList),
    {RandPos, _} = util:rand_list(RandList2, 2),
    LimitNum = get_limit_count(RandPos, Items),
    Id = get_award_id(RandPos, Items),
    {AwardId, AwardNum, IsNotice} =
	dial_data:get_award_by_id(Id),
    NewItems = lists:keystore(RandPos, 1, Items,
			      {RandPos, Id, LimitNum - 1}),
    NLimitCount = [{RandId, Count + 1}
		   || {RandId, Count} <- PosLimitCount],
    NewPosLimitCount = lists:keystore(RandPos, 1,
				      NLimitCount, {RandPos, 0}),
    do_dial2(Type, Count - 1, RandList,
	     [{AwardId, AwardNum, IsNotice} | L], TotulCount + 1,
	     NewItems, [RandPos | L2], NewPosLimitCount).

