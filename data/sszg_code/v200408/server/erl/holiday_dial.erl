	  {ok, Role#role{m_dial = MDial#m_dial{info = NewList}}};
      Data = #dial_info{item_limit_count = OldList} ->
	  Expend = dial_data:get_const(refreash),
	  Loss = format:val_to_loss(Expend, dial_ref),
	  case role_gain:do(Role, Loss) of
