get_award(Role, Type, Id) ->
    case check_can_get_award(Role, Type, Id) of
      {ok, DialInfo = #dial_info{lucky = Lucky}, Award} ->
	  Gain = format:val_to_gain(Award, dial_get_award),
	  case role_gain:do_notice(Role, Gain) of
	    {ok, Role2} ->
		log:log_gain(Gain, Role, Role2, <<"探宝抽奖幸运值奖励"/utf8>>,
			     util:fbin(lang:get(<<"幸运值奖励领取:~w ~w ~w"/utf8>>),
				       [Type, Id, Lucky])),
		NewDialInfo = ref_lucky(DialInfo, Id),
		NewRole = set_dial(Role2, NewDialInfo),
		{ok, NewRole};
	    {false, #gain{msg = Msg}} -> {false, Msg}
	  end;
      {false, Msg} -> {false, Msg}
    end.

ref_lucky(DialInfo = #dial_info{type = Type,
				lucky = Lucky, lucky_award = L}) ->
    AllAward = dial_data:get_lucky_list(Type),
    case [IdT
	  || IdT <- AllAward, lists:member(IdT, L) == false]
	of
      [] ->
	  DelLucky = dial_data:get_del_lucky({Type,
					      lists:max(AllAward)}),
	  DialInfo#dial_info{lucky = max(Lucky - DelLucky, 0),
			     lucky_award = []};
      _ -> DialInfo#dial_info{lucky_award = L}
    end.

ref_lucky(DialInfo = #dial_info{type = Type,
				lucky = Lucky, lucky_award = L},
	  Id) ->
    AllAward = dial_data:get_lucky_list(Type),
    case [IdT
	  || IdT <- AllAward,
	     lists:member(IdT, [Id | L]) == false]
	of
      [] ->
	  DelLucky = dial_data:get_del_lucky({Type,
					      lists:max(AllAward)}),
	  DialInfo#dial_info{lucky = max(Lucky - DelLucky, 0),
			     lucky_award = []};
      _ -> DialInfo#dial_info{lucky_award = [Id | L]}
    end.

check_can_get_award(#role{m_dial =
			      #m_dial{info = List}},
		    Type, Id) ->
    case lists:keyfind(Type, #dial_info.type, List) of
      Info = #dial_info{lucky_award = L, lucky = Lucky} ->
	  case lists:member(Id, L) of
	    true -> {false, lang:get(<<"奖励已领取"/utf8>>)};
	    _ ->
		case dial_data:get_lucky_award(Type) of
		  L2 when is_list(L2) ->
		      case lists:keyfind(Id, 2, L2) of
			{_, _, LimitLucky, Award} when Lucky >= LimitLucky ->
			    {ok, Info, Award};
			_ -> {false, lang:get(<<"没有该奖励数据"/utf8>>)}
		      end;
		  _ -> {false, lang:get(<<"找不到该奖励"/utf8>>)}
		end
	  end;
      _ -> {false, lang:get(<<"参数错误"/utf8>>)}
    end.

do_dial(Role, Type, Type2) ->
    case check_open(Role, Type, Type2) of
      {false, Msg} -> {false, Msg};
      _ ->
	  Count = dial_data:get_count({Type, Type2}),
	  ExpendItem = dial_data:get_expend_item({Type, Type2}),
	  Loss = format:val_to_loss(ExpendItem, dial),
	  case role_gain:do(Role, Loss,
			    #gain_loss_opts{need_notify_fail_item = true})
	      of
	    {ok, Role1, _} ->
		do_dial(Role1, Count, Loss, Type, Type2);
	    {false, #loss{msg = Msg}} -> {false, Msg}
	  end
    end.

check_open(Role, Type, Type2) ->
    Limits = dial_data:get_limit_open({Type, Type2}),
    do_check(Limits, Role).

