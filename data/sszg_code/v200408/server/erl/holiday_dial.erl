init() -> #m_dial{}.

-spec login(#role{}) -> ok | {ok, #role{}}.

login(Role = #role{m_dial =
		       MDial = #m_dial{info = List}}) ->
    AllList = lists:usort(dial_data:list()),
    NList = ref_data(Role, AllList, List, []),
    Role#role{m_dial = MDial#m_dial{info = NList}};
login(Role) ->
    AllList = lists:usort(dial_data:list()),
    NList = ref_data(Role, AllList, [], []),
    Role#role{m_dial =
		  #m_dial{info = NList, reset_time = date:unixtime()}}.

ref_data(_Role, [], _List, L) -> L;
ref_data(Role, [Type | Other], List, L) ->
    case lists:keyfind(Type, #dial_info.type, List) of
      Data = #dial_info{} ->
	  NewDialInfo = ref_lucky(Data),
	  ref_data(Role, Other, List, [NewDialInfo | L]);
      _ ->
	  RandList = do_ref(Role, Type),
	  LimitCount = do_add_limit_count(Type, RandList, []),
	  ref_data(Role, Other, List,
		   [#dial_info{type = Type, rand_lists = RandList,
			       item_limit_count = LimitCount}
		    | L])
    end.

do_add_limit_count(Type, RandIds, List) ->
    NApearList = [{RandId, Count + 1}
		  || {RandId, Count} <- List],
    do_add_limit_count2(Type, RandIds, NApearList).

do_add_limit_count2(_Type, [], ApearList) -> ApearList;
do_add_limit_count2(Type,
		    [{_Num, RandId, _LimitNum} | RandIds], ApearList) ->
    case dial_data:get_item_must_no_count({Type, RandId}) of
      T when T > 0 ->
	  do_add_limit_count2(Type, RandIds,
			      lists:keystore(RandId, 1, ApearList,
					     {RandId, 0}));
      _ -> do_add_limit_count2(Type, RandIds, ApearList)
    end;
do_add_limit_count2(Type, [RandId | RandIds],
		    ApearList) ->
    case dial_data:get_item_must_no_count({Type, RandId}) of
      T when T > 0 ->
	  do_add_limit_count2(Type, RandIds,
			      lists:keystore(RandId, 1, ApearList,
					     {RandId, 0}));
      _ -> do_add_limit_count2(Type, RandIds, ApearList)
    end.

do_ref(#role{lev = Lev, m_dial = #m_dial{info = Info}},
       Type) ->
    Num = get_type_num(Type),
    ItemLimitCount = case lists:keyfind(Type,
					#dial_info.type, Info)
			 of
		       #dial_info{item_limit_count = ItemLimitCountT} ->
			   ItemLimitCountT;
		       _ -> []
		     end,
    do_ref(ItemLimitCount, Num, Lev, Type, []).

do_ref(_ItemLimitCount, Num, _Lev, _Type, L)
    when Num =< 0 ->
    L;
do_ref(ItemLimitCount, Num, Lev, Type, L) ->
    RandList = dial_data:get_rand_list({Type, Num}),
    Fun = fun ({Id, MinLev, MaxLev, Pro, LimitNum}, Acc) ->
		  case Lev >= MinLev andalso Lev < MaxLev of
		    true ->
			NoMustCount = list_util:keyfind(Id, ItemLimitCount,
							9999),
			MustNoMustCount =
			    dial_data:get_item_must_no_count({Type, Id}),
			case NoMustCount >= MustNoMustCount of
			  true -> [{Id, Pro, LimitNum} | Acc];
			  _ -> Acc
			end;
		    _ -> Acc
		  end
	  end,
    RandList1 = lists:foldl(Fun, [], RandList),
    {Id, _Pro, LimitNum} = util:rand_list(RandList1, 2),
    do_ref(ItemLimitCount, Num - 1, Lev, Type,
	   [{Num, Id, LimitNum} | L]).

get_type_num(1) -> dial_data:get_const(num_1);
get_type_num(_) -> dial_data:get_const(num_2).

zero_flush(Role = #role{m_dial =
			    MDial = #m_dial{info = List}}) ->
    Fun = fun (Data = #dial_info{type = Type,
				 item_limit_count = OldList},
	       Acc) ->
		  RandList = do_ref(Role, Type),
		  LimitCount = do_add_limit_count(Type, RandList,
						  OldList),
		  [Data#dial_info{rand_lists = RandList,
				  item_limit_count = LimitCount}
		   | Acc]
	  end,
    NewList = lists:foldl(Fun, [], List),
    NewMDial = MDial#m_dial{info = NewList},
    NewRole = Role#role{m_dial = NewMDial},
    push_dial_info(NewRole),
    {ok, NewRole}.

-spec push_dial_info(#role{}) -> ok | {ok, #role{}}.

push_dial_info(#role{m_dial = #m_dial{info = List}}) ->
    PushList = [{Data#dial_info{rand_lists =
				    [{Pos, Id,
				      util:if_true(LimitNum =< 0, 1, 0)}
				     || {Pos, Id, LimitNum} <- L]},
		 get_log(Type)}
		|| Data = #dial_info{type = Type, rand_lists = L}
		       <- List],
    sys_conn:pack_send(16637, {PushList}),
    ok.

-spec push_ref_dial_info(#role{}, pos_integer()) -> ok |
						    {ok, #role{}}.

push_ref_dial_info(#role{m_dial = #m_dial{info = List}},
		   Type) ->
    case lists:keyfind(Type, #dial_info.type, List) of
      false -> ok;
      Info = #dial_info{rand_lists = RandLists} ->
	  sys_conn:pack_send(16639,
			     {Info#dial_info{rand_lists =
						 [{Pos, Id,
						   util:if_true(LimitNum =< 0,
								1, 0)}
						  || {Pos, Id, LimitNum}
							 <- RandLists]}})
    end,
    ok.

-spec ref(#role{}, pos_integer()) -> {ok, #role{}} |
				     {false, binary()}.

ref(Role = #role{m_dial = MDial = #m_dial{info = List}},
    Type) ->
    Now = date:unixtime(),
    case lists:keyfind(Type, #dial_info.type, List) of
      Data = #dial_info{end_time = EndTime,
			item_limit_count = OldList}
	  when Now >= EndTime ->
	  NewEndTime = Now + dial_data:get_const(free_time),
	  RandList = do_ref(Role, Type),
	  LimitCount = do_add_limit_count(Type, RandList,
