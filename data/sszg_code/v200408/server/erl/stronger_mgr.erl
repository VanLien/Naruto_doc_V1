-spec get_stronger_score(pos_integer()) -> list().

get_stronger_score(Bid) ->
    case ets:lookup(stronger_partner, Bid) of
      [{_, List} | _] -> List;
      _ -> []
    end.

-spec check_first_partner(#partner{}) -> ok.

check_first_partner(#partner{bid = Bid,
			     score_lists = ScoreList}) ->
    Score1 = lists:sum([T || {_, T} <- ScoreList]),
    List = get_stronger_score(Bid),
    Score2 = lists:sum([T2 || {_, T2} <- List]),
    case Score1 > Score2 of
      true ->
	  ets:insert(stronger_partner, {Bid, ScoreList}),
	  dets:insert(stronger_partner, {Bid, ScoreList});
      _ -> ok
    end.

