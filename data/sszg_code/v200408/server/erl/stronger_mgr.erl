		fun () -> {error, {sink_not_configured, lager_event}}
		end();
	    {__Pidstronger_mgr50, _,
	     {__Levelstronger_mgr50, __Tracesstronger_mgr50}}
		when __Levelstronger_mgr50 band 8 /= 0 orelse
		       __Tracesstronger_mgr50 /= [] ->
