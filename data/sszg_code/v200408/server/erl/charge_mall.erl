-spec charge_mall_id_list(#role{}) -> ok.

charge_mall_id_list(Role) ->
    MallList = charge_mall_data:get_mall_list(),
    Fun = fun ({Id, Cond}, Acc) ->
		  Cond2 = charge_mall_data:get_mall_cond2(Id),
		  case Cond2 of
		    [_ | _] ->
			case check_cond2(Role, Cond2) of
			  true -> [Id | Acc];
			  _ ->
			      case check_cond(Role, Cond) of
				true ->
				    case Id =:= 9 of
				      true ->
					  Now = date:unixtime(),
					  {NewGiftList, _} =
					      holiday_fire_gift:ref_gift_list(Role),
					  NewGiftList1 = [F
							  || F =
								 #fire_gift_info{end_time
										     =
										     EndTime}
								 <- NewGiftList,
							     Now =< EndTime],
					  case NewGiftList1 of
					    [_ | _] -> [Id | Acc];
					    _ -> Acc
					  end;
				      _ -> [Id | Acc]
				    end;
				_ -> Acc
			      end
			end;
		    _ ->
			case check_cond(Role, Cond) of
			  true ->
			      case Id =:= 9 of
				true ->
				    Now = date:unixtime(),
				    {NewGiftList, _} =
					holiday_fire_gift:ref_gift_list(Role),
				    NewGiftList1 = [F
						    || F =
							   #fire_gift_info{end_time
									       =
									       EndTime}
							   <- NewGiftList,
						       Now =< EndTime],
				    case NewGiftList1 of
				      [_ | _] -> [Id | Acc];
				      _ -> Acc
				    end;
				_ -> [Id | Acc]
			      end;
			  _ -> Acc
			end
		  end
	  end,
    List = lists:foldl(Fun, [], MallList),
    Fun1 = fun (Id, Acc) ->
		   SonList = charge_mall_data:get_son_mall(Id),
		   case SonList of
		     [_ | _] ->
			 Fun2 = fun (Id1) -> not lists:member(Id1, List) end,
			 case lists:all(Fun2, SonList) of
			   true -> Acc;
			   _ -> [Id | Acc]
			 end;
		     _ -> [Id | Acc]
		   end
	   end,
    List1 = lists:foldl(Fun1, [], List),
    List1.

check_cond2(_Role, []) -> true;
check_cond2(Role, [H | T]) ->
    case do_check_cond(Role, H) of
      true -> check_cond(Role, T);
      _ -> false
    end.

check_cond(_Role, []) -> true;
check_cond(Role, [H | T]) ->
    case do_check_cond(Role, H) of
      true -> check_cond(Role, T);
      _ -> false
    end.

do_check_cond(#role{lev = Lev}, {lev, Val}) ->
    case Lev >= Val of
      true -> true;
      _ -> false
    end;
do_check_cond(Role = #role{}, {charge_num, Val}) ->
    AllCharge = charge_misc:charge_sum(Role),
    case AllCharge >= Val of
      true -> true;
      _ -> false
    end;
do_check_cond(_Role = #role{}, {open_day, Val}) ->
    Day = date:open_srv_day(),
    case Day >= Val of
      true -> true;
      _ -> false
    end;
do_check_cond(_Role, _) -> true.

