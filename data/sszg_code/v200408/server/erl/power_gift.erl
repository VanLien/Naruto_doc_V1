-spec get_label_status(#role{}) -> Status :: 0 | 2 | 1.

get_label_status(#role{platform = <<"verifyios">>}) ->
    0;
get_label_status(#role{max_power = MaxPower,
		       m_power_gift = #m_power_gift{gifts = Gifts}}) ->
    PowerList = power_gift_data:power_list(),
    case is_reward(PowerList, MaxPower, Gifts) of
      true -> 2;
      _ ->
	  case power_gift_data:max_power() > MaxPower of
	    true -> 1;
	    false -> 0
	  end
    end.

-spec fire(#role{}, integer()) -> ok.

fire(Role = #role{max_power = MaxPower}, OldMaxPower) ->
    case MaxPower > OldMaxPower of
      true -> push_label_status(Role);
      false -> ok
    end,
    ok.

