-spec gain(#role{}, Id :: integer()) -> {ok, #role{}} |
					{false, binary()}.

gain(Role = #role{max_power = Power,
		  m_power_gift = #m_power_gift{gifts = Gifts}},
     Id) ->
    case power_gift_data:get(Id) of
      Data = #{reward := [_ | _], power := PowerLimit}
	  when Power >= PowerLimit ->
	  case lists:keyfind(Id, #power_gift.id, Gifts) of
	    false -> do_gain(Role, Data);
	    _ -> {false, lang:get(<<"已领取过该战力奖励"/utf8>>)}
	  end;
      #{power := _} ->
	  {false, lang:get(<<"未达到战力范围，无法领取奖励"/utf8>>)};
      Data when is_map(Data) ->
	  case {whereis(lager_event), whereis(lager_event),
		lager_config:get({lager_event, loglevel}, {0, []})}
	      of
	    {undefined, undefined, _} ->
		fun () -> {error, lager_not_running} end();
	    {undefined, _, _} ->
		fun () -> {error, {sink_not_configured, lager_event}}
		end();
	    {__Pidpower_gift90, _,
	     {__Levelpower_gift90, __Tracespower_gift90}}
		when __Levelpower_gift90 band 8 /= 0 orelse
		       __Tracespower_gift90 /= [] ->
		lager:do_log(error,
			     [{module, power_gift}, {function, gain},
			      {line, 90}, {pid, pid_to_list(self())},
			      {node, node()}
			      | lager:md()],
			     io_lib:format("[~ts]没有配置对应战力礼包奖励:~w",
					   [Role#role.name, Id]),
			     none, 4096, 8, __Levelpower_gift90,
			     __Tracespower_gift90, lager_event,
			     __Pidpower_gift90);
	    _ -> ok
	  end,
	  {false, lang:get(<<"奖励正在配置中，请稍后再进行领取"/utf8>>)};
      _ -> {false, lang:get(<<"对应战力的奖励还未开放"/utf8>>)}
    end.

do_gain(Role, #{id := Id, reward := Reward}) ->
    Gains = format:val_to_gain(Reward, make_power_gift),
    case role_gain:do_notice(Role, Gains) of
      {ok,
       GainRole = #role{m_power_gift =
			    MPowerGift = #m_power_gift{gifts = Gifts}}} ->
	  NewPowerGift = #power_gift{id = Id, status = 2},
	  NewGifts = lists:keystore(Id, #power_gift.id, Gifts,
				    NewPowerGift),
	  NewMPowerGift = MPowerGift#m_power_gift{gifts =
						      NewGifts},
	  NewRole = GainRole#role{m_power_gift = NewMPowerGift},
	  push_label_status(NewRole),
	  log:log_gain(Gains, Role, NewRole, <<"战力礼包"/utf8>>,
		       util:fbin("领取战力礼包[Power:~w]", [Id])),
	  {ok, NewRole};
      {false, #gain{msg = Msg}} -> {false, Msg};
      _ -> {false, lang:get(<<"背包已满，无法获取"/utf8>>)}
    end.

push_label_status(Role) ->
    IcoStatus = get_label_status(Role),
    push_label_status(Role, IcoStatus),
    ok.

push_label_status(Role = #role{is_ready = 1}, Status) ->
    role:pack_send(Role, 23402, {Status}), ok;
push_label_status(_Role, _Status) -> ok.

is_reward([], _Power, _Gifts) -> false;
is_reward([{Id, PowerCfg} | Rest], Power, Gifts)
    when Power >= PowerCfg ->
    case lists:keyfind(Id, #power_gift.id, Gifts) of
      false -> true;
      _ -> is_reward(Rest, Power, Gifts)
    end;
is_reward([_PowerCfg | Rest], Power, Gifts) ->
    is_reward(Rest, Power, Gifts).


