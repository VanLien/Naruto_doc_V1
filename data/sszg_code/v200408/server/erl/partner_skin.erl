-spec gm_time_out(#role{}, pos_integer()) -> #role{}.

gm_time_out(Role = #role{partner_bag =
			     PB = #partner_bag{partner_list = PL,
					       partner_skins = Skins}},
	    SkinId) ->
    case get_skin(Role, SkinId) of
      #partner_skin{} ->
	  NewSkins = lists:keydelete(SkinId, #partner_skin.id,
				     Skins),
	  Fun = fun (P = #partner{use_skin = UseSkin},
		     {Acc, Acc2}) ->
			case UseSkin == SkinId of
			  true ->
			      NewP = P#partner{use_skin = 0},
			      {[NewP | Acc], [NewP | Acc2]};
			  _ -> {[P | Acc], Acc2}
			end
		end,
	  {NewPL, RefPL} = lists:foldl(Fun, {[], []}, PL),
	  NewRole = Role#role{partner_bag =
				  PB#partner_bag{partner_list = NewPL,
						 partner_skins = NewSkins}},
	  NRole = partner_lib:ref_partner_by_type(NewRole, [0],
						  []),
	  NewRole2 = role_looks:del_activate(NRole,
					     partner_skin_data:get_looks_id(SkinId)),
	  NewRole3 = #role{partner_bag =
			       #partner_bag{partner_list = PL2}} =
			 role_face:del_face(NewRole2,
					    partner_skin_data:get_face_id(SkinId)),
	  get_info(NewRole3),
	  arena_elite_mirror:update_mirror(NewRole3),
	  Fun2 = fun (#partner{id = IdT}, Acc) ->
			 case lists:keyfind(IdT, #partner.id, PL2) of
			   PT = #partner{} -> [PT | Acc];
			   _ -> Acc
			 end
		 end,
	  NewRefPL = lists:foldl(Fun2, [], RefPL),
	  partner:push_all_partner_list(NewRole3, NewRefPL),
	  NewRole3;
      _ -> Role
    end.

login(Role) ->
    NRole = set_timer(Role), {ok, day_log(NRole)}.

day_log(Role = #role{partner_bag =
			 #partner_bag{partner_skins = Skins = [_ | _]}}) ->
    case var:get_var(Role, day, 124, 0) of
      0 ->
	  [do_day_log(Skin, Role)
	   || Skin = #partner_skin{end_time = 0} <- Skins],
	  var:set_var(Role, day, 124, 1);
      _ -> Role
    end;
day_log(Role) -> Role.

do_day_log(#partner_skin{id = SkinId}, Role) ->
    Msg = util:fbin("~w:~ts",
		    [SkinId, partner_skin_data:get_name(SkinId)]),
    log:save(custom,
	     {Role, <<"玩家拥有皮肤"/utf8>>, [{msg, Msg}]});
do_day_log(_, _Role) -> ok.

set_timer(Role = #role{partner_bag =
			   #partner_bag{partner_skins = Skins}}) ->
    set_timer(Role, Skins).

set_timer(Role, []) -> Role;
set_timer(Role, [Skin | Skins]) ->
    NewRole = set_timer(Role, Skin),
    set_timer(NewRole, Skins);
set_timer(Role, #partner_skin{end_time = 0}) -> Role;
set_timer(Role,
	  #partner_skin{id = SkinId, end_time = EndTime,
			ext = Ext}) ->
    case lists:keyfind(1, 1, Ext) of
      {_, 1} ->
	  DiffTime = max(1, EndTime - date:unixtime()),
	  role_timer:set(#timer{id = {partner_skin_timer, SkinId},
				timeout = DiffTime * 1000, times = 1,
				m = partner_skin, f = apply_time_out,
				a = [SkinId]},
			 Role);
      _ ->
	  DiffTime = max(1, EndTime - date:unixtime()),
	  Role1 = role_timer:set(#timer{id =
					    {partner_skin_timer, SkinId},
					timeout = DiffTime * 1000, times = 1,
					m = partner_skin, f = apply_time_out,
					a = [SkinId]},
				 Role),
	  DiffTime2 = max(1, EndTime - date:unixtime() - 86400),
	  role_timer:set(#timer{id =
				    {partner_skin_send_timer, SkinId},
				timeout = DiffTime2 * 1000, times = 1,
				m = partner_skin, f = apply_send_mail,
				a = [SkinId]},
			 Role1)
    end.

get_info(#role{partner_bag =
		   #partner_bag{partner_skins = Skins}}) ->
    sys_conn:pack_send(11020, {Skins}), ok.

calc_attr(#role{partner_bag =
		    #partner_bag{partner_skins = Skins}},
	  PartnerId) ->
    PSkins =
	partner_skin_data:get_skins_by_partner_id(PartnerId),
    lists:flatten([partner_skin_data:get_attr(SkinId)
		   || SkinId <- PSkins,
		      lists:keymember(SkinId, #partner_skin.id, Skins)]).

apply_time_out(Role = #role{partner_bag =
				PB = #partner_bag{partner_list = PL,
						  partner_skins = Skins}},
	       SkinId) ->
    Now = date:unixtime(),
    case get_skin(Role, SkinId) of
      #partner_skin{end_time = EndTime}
	  when EndTime =< Now andalso EndTime > 0 ->
	  NewSkins = lists:keydelete(SkinId, #partner_skin.id,
				     Skins),
	  Fun = fun (P = #partner{use_skin = UseSkin},
		     {Acc, Acc2}) ->
			case UseSkin == SkinId of
			  true ->
			      NewP = P#partner{use_skin = 0},
			      {[NewP | Acc], [NewP | Acc2]};
			  _ -> {[P | Acc], Acc2}
			end
		end,
	  {NewPL, RefPL} = lists:foldl(Fun, {[], []}, PL),
	  NewRole = Role#role{partner_bag =
				  PB#partner_bag{partner_list = NewPL,
						 partner_skins = NewSkins}},
	  NRole = partner_lib:ref_partner_by_type(NewRole, [0],
						  []),
	  NewRole2 = role_looks:del_activate(NRole,
					     partner_skin_data:get_looks_id(SkinId)),
	  NRole3 = #role{partner_bag =
			     #partner_bag{partner_list = PL2}} =
		       role_face:del_face(NewRole2,
					  partner_skin_data:get_face_id(SkinId)),
	  NewRole3 = cystal_resonate:fire(NRole3),
	  get_info(NewRole3),
	  arena_elite_mirror:update_mirror(NewRole3),
	  Fun2 = fun (#partner{id = IdT}, Acc) ->
			 case lists:keyfind(IdT, #partner.id, PL2) of
			   PT = #partner{} -> [PT | Acc];
			   _ -> Acc
			 end;
		     (_, Acc) -> Acc
		 end,
	  NewRefPL = lists:foldl(Fun2, [], RefPL),
	  partner:push_all_partner_list(NewRole3, NewRefPL),
	  {ok, NewRole3};
      _ -> {ok, Role}
    end.

apply_send_mail(Role, SkinId) ->
    Now = date:unixtime(),
    case get_skin(Role, SkinId) of
      Skin = #partner_skin{end_time = EndTime, ext = Ext}
	  when EndTime =< Now + 86400 andalso EndTime > 0 ->
	  PartnerBid =
	      partner_skin_data:get_skin_owner_id(SkinId),
	  #partner_base_data{name = Name} =
	      partner_data:get_base(PartnerBid),
	  Content =
	      color:msg(lang:get(<<"Ninja của bạn~tsSkin sắp hết hạn. Sau "
				   "khi hết hạn, phần thưởng hình ảnh và "
				   "thuộc tính đã thiết lập sẽ bị hủy. Vui "
				   "lòng đến trung tâm skin để đổi kịp thời.！"/utf8>>),
			[{blue, Name}]),
	  TimeOut = Now + 86400,
	  Mail = {lang:get(<<"Skin ninja sắp hết hạn"/utf8>>),
		  Content, [], [],
		  lang:get(<<"Skin ninja sắp hết hạn"/utf8>>), TimeOut},
	  {ok, NRole} = mail:add(Role, Mail),
	  NewSkin = Skin#partner_skin{ext =
					  lists:keystore(1, 1, Ext, {1, 1})},
	  NewRole = set_skin(NRole, NewSkin),
	  {ok, NewRole};
      _ -> {ok, Role}
    end.

