-spec add_skin(#role{}, pos_integer(), pos_integer(),
	       list()) -> {ok, #role{}} | {false, binary()}.

add_skin(Role = #role{partner_bag =
			  #partner_bag{partner_list = L}},
	 BaseId, TimeOut, Award) ->
    case partner_skin_data:get_skin_owner_id(BaseId) of
      OwnerId when is_integer(OwnerId) ->
	  case [P || P = #partner{bid = Bid} <- L, Bid == OwnerId]
	      of
	    [_ | _] -> do_make_skin(Role, BaseId, TimeOut, Award);
	    _ ->
		{false,
		 lang:get(<<"Không sử dụng được, không có ninja nào "
			    "như vậy"/utf8>>)}
	  end;
      _ ->
	  {false,
	   lang:get(<<"Lỗi tham số, kích hoạt giao diện không "
		      "thành công"/utf8>>)}
    end.

do_make_skin(Role = #role{partner_bag =
			      PB = #partner_bag{partner_skins = Skins}},
	     BaseId, TimeOut, Award) ->
    case lists:keyfind(BaseId, #partner_skin.id, Skins) of
      P = #partner_skin{end_time = 0, ext = Ext} ->
	  Gain = format:val_to_gain(Award, partner_skin_add),
	  case role_gain:do_notice(Role, Gain) of
	    {ok, NRole} ->
		log:log_gain(Gain, Role, NRole, <<"伙伴皮肤"/utf8>>,
			     util:fbin("已获得永久皮肤,转换为对应道具:~w", [BaseId])),
		{ok, NRole};
	    {false, #gain{msg = Msg}} -> {false, Msg}
	  end;
      P = #partner_skin{end_time = EndTime, ext = Ext} ->
	  NewEndTime = util:if_true(TimeOut == 0, 0,
				    EndTime + TimeOut),
	  NewExt = lists:keydelete(1, 1, Ext),
	  NewSkins = lists:keystore(BaseId, #partner_skin.id,
				    Skins,
				    P#partner_skin{end_time = NewEndTime,
						   ext = NewExt}),
	  NewRole = Role#role{partner_bag =
				  PB#partner_bag{partner_skins = NewSkins}},
	  NewRole2 = set_timer(NewRole, NewSkins),
	  get_info(NewRole2),
	  Day = (TimeOut + 10) div 86400,
	  case TimeOut == 0 of
	    false ->
		notice:alert(util:fbin(lang:get(<<"Skin tồn tại lâu hơn~wngày"/utf8>>),
				       [Day]));
	    _ ->
		notice:alert(lang:get(<<"Skin này đã được lấy vĩnh viễn"/utf8>>))
	  end,
	  NewRole3 = role_trigger:fire(#evt_skin{}, NewRole2),
	  {ok, NewRole3};
      _ ->
	  Skin = case TimeOut of
		   0 -> #partner_skin{id = BaseId, end_time = 0};
		   TimeOut when is_integer(TimeOut) andalso TimeOut > 0 ->
		       #partner_skin{id = BaseId,
				     end_time = date:unixtime() + TimeOut}
		 end,
	  NewSkins = [Skin | Skins],
	  NewRoleT = Role#role{partner_bag =
				   PB#partner_bag{partner_skins = NewSkins}},
	  NewRole = set_timer(NewRoleT, NewSkins),
	  NewRole2 = role_looks:activate(NewRole),
	  NewRole3 = role_face:add_face(NewRole2,
					partner_skin_data:get_face_id(BaseId)),
	  notice:alert(lang:get(<<"Đã kích hoạt thành công skin"/utf8>>)),
	  get_info(NewRole3),
	  NewRole4 = role_trigger:fire(#evt_skin{}, NewRole3),
	  auto_use(NewRole4, BaseId)
    end.

auto_use(Role = #role{partner_bag =
			  #partner_bag{partner_list = L}},
	 SkinId) ->
    case partner_skin_data:get_skin_owner_id(SkinId) of
      PartnerBid when is_integer(PartnerBid) ->
	  case [P
		|| P = #partner{bid = PartnerBidT} <- L,
		   PartnerBidT == PartnerBid]
	      of
	    L2 = [_ | _] ->
		[#partner{id = PartnerId} | _] =
		    lists:reverse(lists:keysort(#partner.power, L2)),
		case use_skin(Role, PartnerId, SkinId) of
		  {ok, NRole} -> {ok, NRole};
		  _ -> {ok, Role}
		end;
	    _ -> {ok, Role}
	  end;
      _ -> {ok, Role}
    end.

-spec use_skin(#role{}, pos_integer(),
	       pos_integer()) -> {ok, #role{}} | {false, binary()}.

use_skin(Role = #role{partner_bag =
			  PB = #partner_bag{partner_list = PL}},
	 Id, SkinId) ->
    case check_use(Role, Id, SkinId) of
      {false, Msg} -> {false, Msg};
      {ok, P} ->
	  NewP = P#partner{use_skin = SkinId},
	  NewP2 = partner_lib:calc_attr(Role, NewP),
	  NRole1 = Role#role{partner_bag =
				 PB#partner_bag{partner_list =
						    lists:keystore(Id,
								   #partner.id,
								   PL, NewP)}},
	  partner:push_ref_partner(NRole1, NewP2),
	  NRole = cystal_resonate:fire(NRole1),
	  arena_elite_mirror:update_mirror(NRole),
	  {ok, NRole}
    end.

check_use(Role = #role{partner_bag =
			   #partner_bag{partner_skins = Skins}},
	  Id, SkinId) ->
    case partner_lib:get_partner(Role, Id) of
      P = #partner{} when SkinId == 0 -> {ok, P};
      P = #partner{bid = PartnerBid} ->
	  case lists:keyfind(SkinId, #partner_skin.id, Skins) of
	    #partner_skin{} ->
		case partner_skin_data:get_skin_owner_id(SkinId) of
		  PartnerBid -> {ok, P};
		  _ ->
		      {false,
		       lang:get(<<"Skin này không thể sử dụng được"/utf8>>)}
		end;
	    _ ->
		{false, lang:get(<<"Skin không được kích hoạt"/utf8>>)}
	  end;
      _ -> {false, lang:get(<<"Không tìm thấy ninja"/utf8>>)}
    end.

