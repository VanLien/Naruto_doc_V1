get_partner_in_formation(_Role = #role{m_formation =
					   #m_formation{all_lineups = Lines,
							sys_formations =
							    SysFormations}}) ->
    PMap = do_get_partner_in_formation(Lines, #{}),
    do_get_partner_in_formation(SysFormations, PMap).

do_get_partner_in_formation([], PMap) -> PMap;
do_get_partner_in_formation([#m_arena_elite_defens{formations
						       = Formations}
			     | T],
			    PMap) ->
    PosInfo = lists:flatten([PosInfo1
			     || {_, _, PosInfo1, _} <- Formations]),
    NewPMap = do_get_partner_in_formation(PosInfo, PMap),
    do_get_partner_in_formation(T, NewPMap);
do_get_partner_in_formation([#formation_lineup{pos_info
						   = PosInfo}
			     | T],
			    PMap) ->
    NewPMap = do_get_partner_in_formation(PosInfo, PMap),
    do_get_partner_in_formation(T, NewPMap);
do_get_partner_in_formation([#formation_sys{pos_info =
						PosInfo}
			     | T],
			    PMap) ->
    NewPMap = do_get_partner_in_formation(PosInfo, PMap),
    do_get_partner_in_formation(T, NewPMap);
do_get_partner_in_formation([#formation_pos{id = PId}
			     | T],
			    PMap)
    when PId > 0 ->
    NewPMap = maps:put(PId, 1, PMap),
    do_get_partner_in_formation(T, NewPMap);
do_get_partner_in_formation([{_Pos, PId} | T], PMap)
    when PId > 0 ->
    NewPMap = maps:put(PId, 1, PMap),
    do_get_partner_in_formation(T, NewPMap);
do_get_partner_in_formation([PId | T], PMap)
    when is_integer(PId) andalso PId > 0 ->
    NewPMap = maps:put(PId, 1, PMap),
    do_get_partner_in_formation(T, NewPMap);
do_get_partner_in_formation([_ | T], PMap) ->
    do_get_partner_in_formation(T, PMap).


