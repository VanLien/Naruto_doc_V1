		    		local item = GoodsItem.New(self.goods_scroll)
		    		item:setData(Config.ItemData.data_get_data(render_list[i][1]))
		    		item:setNum(render_list[i][2])
		    		item:setAnchorPoint(cc.p(0,0.5))
