		    end

			local render_list = Config.DayBargainData.data_info[id].award
		    if render_list then
		    	local sum = #render_list
		        local start_x = 52
		        local _y = (self.goods_scroll:getContentSize().height) * 0.5
		        local max_width = (sum) * ( 109) 
